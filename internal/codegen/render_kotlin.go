// kotlinRuntimeImports are the tech.easyp.mcp.runtime.kotlin declarations
// that generated Kotlin files use.
var kotlinRuntimeImports = []string{"RegisteredTool", "checkGencodeVersion", "iconThemeOrError", "installMcpHandlers", "normalizeNamespace", "promptName", "registerProtoFiles", "resourceListing", "resourceReadResult", "templateParam", "toolExecutionOrNull", "toolName"}

func renderKotlinFile(plugin *protogen.Plugin, model JVMFileModel) error {
	if model.Language != LanguageKotlin {
		return fmt.Errorf("kotlin renderer requires lang=kotlin, got %q", model.Language)
	}
	if err := validateKotlinMetadata(model); err != nil {
		return err
	}

	info, err := newKotlinRenderInfo(plugin, model)
	if err != nil {
		return err
	}

	filePackage, err := resolveJVMFilePackage(info.file)
	if err != nil {
		return err
	}

	imports := map[string]bool{}
	for _, service := range model.Services {
		for _, method := range service.Methods {
			if _, err := info.kotlinMessageTypeExpr(method.Input, imports, filePackage.Package); err != nil {
				return err
			}
			if _, err := info.kotlinMessageTypeExpr(method.Output, imports, filePackage.Package); err != nil {
				return err
			}
		}
	}
	resourceTypes := map[string]string{}
	for _, resource := range model.Resources {
		if resource.SourceFile != "" {
			continue
		}
		outputType, err := info.kotlinMessageTypeExpr(newJVMTypeRefFromShared(resource.Output), imports, filePackage.Package)
		if err != nil {
			return err
		}
		resourceTypes[resource.ProtoFullName] = outputType
	}
	descriptorAccessors, err := collectJavaDescriptorAccessors(info.file.Desc, filePackage.Package)
	if err != nil {
		return err
	}
	for _, accessor := range descriptorAccessors {
		if accessor.ImportPath != "" {
			imports[accessor.ImportPath] = true
		}
	}

	filename := model.GeneratedFilenamePrefix + "_mcp.kt"
	generated := plugin.NewGeneratedFile(filename, "")

	generated.P("// Code generated by protoc-gen-mcp. DO NOT EDIT.")
	generated.P("// source: ", model.ProtoPath)
	generated.P()
	if filePackage.Package != "" {
		generated.P("package ", filePackage.Package)
		generated.P()
	}

	kotlinImports := []string{
		"com.networknt.schema.InputFormat",
		"com.networknt.schema.JsonSchemaFactory",
		"com.networknt.schema.SpecVersion",
		"com.google.protobuf.Descriptors",
		"com.google.protobuf.Message",
		"com.google.protobuf.util.JsonFormat",
		"io.modelcontextprotocol.kotlin.sdk.server.ClientConnection",
		"io.modelcontextprotocol.kotlin.sdk.server.Server",
		"io.modelcontextprotocol.kotlin.sdk.types.CallToolRequest",
		"io.modelcontextprotocol.kotlin.sdk.types.CallToolResult",
		"io.modelcontextprotocol.kotlin.sdk.types.Icon",
		"io.modelcontextprotocol.kotlin.sdk.types.ListToolsRequest",
		"io.modelcontextprotocol.kotlin.sdk.types.ListToolsResult",
		"io.modelcontextprotocol.kotlin.sdk.types.McpException",
		"io.modelcontextprotocol.kotlin.sdk.types.Method",
		"io.modelcontextprotocol.kotlin.sdk.types.RPCError",
		"io.modelcontextprotocol.kotlin.sdk.types.TaskSupport",
		"io.modelcontextprotocol.kotlin.sdk.types.TextContent",
		"io.modelcontextprotocol.kotlin.sdk.types.Tool",
		"io.modelcontextprotocol.kotlin.sdk.types.ToolAnnotations",
		"io.modelcontextprotocol.kotlin.sdk.types.ToolExecution",
		"io.modelcontextprotocol.kotlin.sdk.types.ToolSchema",
		"kotlinx.serialization.json.Json",
		"kotlinx.serialization.json.JsonElement",
		"kotlinx.serialization.json.JsonObject",
		"kotlinx.serialization.json.buildJsonObject",
		"kotlinx.serialization.json.jsonArray",
		"kotlinx.serialization.json.jsonObject",
		"kotlinx.serialization.json.jsonPrimitive",
		"java.util.Collections",
		"java.util.WeakHashMap",
	}
	for importPath := range imports {
		kotlinImports = append(kotlinImports, importPath)
	}
	sort.Strings(kotlinImports)
	for _, name := range kotlinRuntimeImports {
		kotlinImports = append(kotlinImports, "tech.easyp.mcp.runtime.kotlin."+name)
	}
	sort.Strings(kotlinImports)
	for _, importPath := range kotlinImports {
		generated.P("import ", importPath)
	}
	generated.P()

	accessors := make([]string, 0, len(descriptorAccessors))
	for _, accessor := range descriptorAccessors {
		accessors = append(accessors, accessor.Expr)
	}
	generated.P("@Suppress(\"unused\")")
	generated.P("private val protocGenMcpRuntimeInit: Unit = run {")
	generated.P("    checkGencodeVersion(", jvmGencodeVersion, ")")
	generated.P("    registerProtoFiles(", strings.Join(accessors, ", "), ")")
	generated.P("}")
	generated.P()

	for serviceIdx, service := range model.Services {
		generated.P("interface ", service.HandlerName, " {")
		for _, method := range service.Methods {
			inputType, err := info.kotlinMessageTypeExpr(method.Input, imports, filePackage.Package)
			if err != nil {
				return err
			}
			outputType, err := info.kotlinMessageTypeExpr(method.Output, imports, filePackage.Package)
			if err != nil {
				return err
			}
			generated.P("    suspend fun ", method.MethodName, "(ctx: ClientConnection, request: ", inputType, "): ", outputType)
		}
		generated.P("}")
		generated.P()

		generated.P("fun ", service.RegisterName, "(server: Server, impl: ", service.HandlerName, ", namespace: String? = null) {")
		generated.P("    val registry = installMcpHandlers(server)")
		generated.P("    val resolvedNamespace = normalizeNamespace(namespace, ", quote(service.Namespace), ")")
		for _, method := range service.Methods {
			inputType, err := info.kotlinMessageTypeExpr(method.Input, imports, filePackage.Package)
			if err != nil {
				return err
			}
			outputType, err := info.kotlinMessageTypeExpr(method.Output, imports, filePackage.Package)
			if err != nil {
				return err
			}
			generated.P("    registry.addTool(")
			generated.P("        RegisteredTool(")
			generated.P("            name = toolName(resolvedNamespace, ", quote(method.ToolName), "),")
			generated.P("            title = ", kotlinNullableString(method.Title), ",")
			generated.P("            description = ", kotlinNullableString(method.Description), ",")
			generated.P("            inputSchemaJson = ", method.SchemaConst, "_INPUT_SCHEMA_JSON,")
			generated.P("            outputSchemaJson = ", method.SchemaConst, "_OUTPUT_SCHEMA_JSON,")
			generated.P("            requestBuilder = { ", inputType, ".newBuilder() },")
			generated.P("            handler = { ctx, request -> impl.", method.MethodName, "(ctx, request as ", inputType, ") as Message },")
			generated.P("            annotations = ", kotlinAnnotations(method.Annotations), ",")
			icons, err := kotlinIcons(method.Icons)
			if err != nil {
				return err
			}
			generated.P("            icons = ", icons, ",")
			generated.P("            execution = ", kotlinTaskSupport(method.TaskSupport), ",")
			if meta := toolMetaJSON(method.AppUI); meta != "" {
				generated.P("            meta = Json.parseToJsonElement(", kotlinStringLiteral(meta), ").jsonObject,")
			}
			generated.P("        ),")
			generated.P("    )")
			_ = outputType
		}
		generated.P("}")
		generated.P()

		for methodIdx, method := range service.Methods {
			generated.P("private const val ", method.SchemaConst, "_INPUT_SCHEMA_JSON = ", kotlinStringLiteral(method.InputSchemaJSON))
			generated.P()
			generated.P("private const val ", method.SchemaConst, "_OUTPUT_SCHEMA_JSON = ", kotlinStringLiteral(method.OutputSchemaJSON))
			if methodIdx < len(service.Methods)-1 || serviceIdx < len(model.Services)-1 {
				generated.P()
			}
		}
	}

	if len(model.Prompts) > 0 {
		renderKotlinPrompts(generated, model)
	}

	if len(model.Resources) > 0 {
		if err := renderKotlinResources(generated, model, resourceTypes); err != nil {
			return err
		}
	}

	return nil
}

func renderKotlinResources(generated *protogen.GeneratedFile, model JVMFileModel, resourceTypes map[string]string) error {
	const sdk = "io.modelcontextprotocol.kotlin.sdk"
	fileBase := jvmFileBaseName(model.ProtoPath)
	interfaceName := jvmExportedIdentifier(fileBase) + "ResourceHandler"
	registerName := "register" + jvmExportedIdentifier(fileBase) + "Resources"

	generated.P()
	generated.P("interface ", interfaceName, " {")
	for _, resource := range model.Resources {
		returnType, ok := resourceTypes[resource.ProtoFullName]
		if !ok {
			returnType = "Any"
		}
		paramList := ""
		if resource.IsTemplate {
			generated.P("    suspend fun list", resource.ProtoName, "s(): List<", sdk, ".types.Resource>")
			for i, identifier := range kotlinParamIdentifiers(resource.Params) {
				if i > 0 {
					paramList += ", "
				}
				paramList += identifier + ": String"
			}
		}
		if resource.SourceFile != "" {
			generated.P("    /** Returns the body of ", resource.SourceFile, " as a String or ByteArray. */")
		}
		generated.P("    suspend fun read", resource.ProtoName, "(", paramList, "): ", returnType)
	}
	generated.P("}")
	generated.P()

	generated.P("/**")
	generated.P(" * Registers the resources of ", model.ProtoPath, " on [server], which must declare the resources")
	generated.P(" * capability. Like the Go target, template instances are listed once, at registration.")
	generated.P(" */")
	generated.P("suspend fun ", registerName, "(server: Server, impl: ", interfaceName, ", namespace: String? = null) {")
	for _, resource := range model.Resources {
		descriptor, err := resourceDescriptorJSON(resource)
		if err != nil {
			return err
		}
		meta := "null"
		if metaJSON := resourceMetaJSON(resource); metaJSON != "" {
			meta = "Json.parseToJsonElement(" + kotlinStringLiteral(metaJSON) + ").jsonObject"
		}
		field := "null"
		if resource.ContentField != "" {
			field = quote(resource.ContentField)
		}
		contents := func(call string) string {
			return "resourceReadResult(" + call + ", uri, " + quote(resource.MIMEType) + ", " + quote(pythonResourceContentKind(resourceContent(resource))) + ", " + field + ", " + meta + ")"
		}
		if resource.IsTemplate {
			args := make([]string, 0, len(resource.Params))
			for _, param := range resource.Params {
				args = append(args, "templateParam(params, "+quote(param.Name)+", uri)")
			}
			generated.P("    run {")
			generated.P("        val template = resourceListing(", sdk, ".types.ResourceTemplate.serializer(), ", kotlinStringLiteral(descriptor), ", namespace, ", quote(resource.Name), ")")
			generated.P("        val matcher = ", sdk, ".utils.PathSegmentTemplateMatcher(template)")
			generated.P("        val read: suspend (String, Map<String, String>) -> ", sdk, ".types.ReadResourceResult = { uri, params ->")
			generated.P("            ", contents("impl.read"+resource.ProtoName+"("+strings.Join(args, ", ")+")"))
			generated.P("        }")
			generated.P("        server.addResourceTemplate(template) { request, params -> read(request.params.uri, params) }")
			generated.P("        server.addResources(")
			generated.P("            impl.list", resource.ProtoName, "s().map { resource ->")
			generated.P("                ", sdk, ".server.RegisteredResource(resource) { request ->")
			generated.P("                    read(request.params.uri, matcher.match(request.params.uri)?.variables.orEmpty())")
			generated.P("                }")
			generated.P("            },")
			generated.P("        )")
			generated.P("    }")
		} else {
			generated.P("    server.addResources(")
			generated.P("        listOf(")
			generated.P("            ", sdk, ".server.RegisteredResource(")
			generated.P("                resourceListing(", sdk, ".types.Resource.serializer(), ", kotlinStringLiteral(descriptor), ", namespace, ", quote(resource.Name), "),")
			generated.P("            ) { request ->")
			generated.P("                val uri = request.params.uri")
			generated.P("                ", contents("impl.read"+resource.ProtoName+"()"))
			generated.P("            },")
			generated.P("        ),")
			generated.P("    )")
		}
	}
	generated.P("}")
	generated.P()
	return nil
}

func renderKotlinPrompts(generated *protogen.GeneratedFile, model JVMFileModel) {
	const sdk = "io.modelcontextprotocol.kotlin.sdk"
	fileBase := jvmFileBaseName(model.ProtoPath)
	interfaceName := jvmExportedIdentifier(fileBase) + "PromptHandler"
	registerName := "register" + jvmExportedIdentifier(fileBase) + "Prompts"

	generated.P()
	generated.P("interface ", interfaceName, " {")
	for _, prompt := range model.Prompts {
		generated.P("    suspend fun ", jvmMethodName(prompt.ProtoName), "(arguments: Map<String, String>): List<", sdk, ".types.PromptMessage>")
	}
	generated.P("}")
	generated.P()

	generated.P("fun ", registerName, "(server: Server, impl: ", interfaceName, ", namespace: String? = null) {")
	for _, prompt := range model.Prompts {
		generated.P("    server.addPrompt(")
		generated.P("        ", sdk, ".types.Prompt(")
		generated.P("            name = promptName(namespace, ", quote(prompt.Name), "),")
		generated.P("            description = ", kotlinNullableString(prompt.Description), ",")
		generated.P("            arguments = listOf(")
		for _, arg := range prompt.Arguments {
			generated.P("                ", sdk, ".types.PromptArgument(name = ", quote(arg.Name), ", description = ", kotlinNullableString(arg.Description), ", required = ", fmt.Sprintf("%t", arg.Required), "),")
		}
		generated.P("            ),")
		if prompt.Title != "" {
			generated.P("            title = ", quote(prompt.Title), ",")
		}
		generated.P("        ),")
		generated.P("    ) { request ->")
		generated.P("        val args = request.arguments.orEmpty()")
		for _, arg := range prompt.Arguments {
			if arg.Required {
				generated.P("        if (!args.containsKey(", quote(arg.Name), ")) {")
				generated.P("            throw McpException(code = RPCError.ErrorCode.INVALID_PARAMS, message = \"missing required prompt argument: ", arg.Name, "\")")
				generated.P("        }")
			}
		}
		generated.P("        ", sdk, ".types.GetPromptResult(messages = impl.", jvmMethodName(prompt.ProtoName), "(args))")
		generated.P("    }")
	}
	generated.P("}")
	generated.P()

}

type kotlinRenderInfo struct {
	file     *protogen.File
	messages map[string]*protogen.Message
}

func newKotlinRenderInfo(plugin *protogen.Plugin, model JVMFileModel) (kotlinRenderInfo, error) {
	file := plugin.FilesByPath[model.ProtoPath]
	if file == nil {
		return kotlinRenderInfo{}, fmt.Errorf("generated file %q not found in plugin", model.ProtoPath)
	}

	info := kotlinRenderInfo{
		file:     file,
		messages: map[string]*protogen.Message{},
	}
	for _, current := range plugin.Files {
		indexKotlinMessages(info.messages, current.Messages)
	}

	return info, nil
}

func indexKotlinMessages(index map[string]*protogen.Message, messages []*protogen.Message) {
	for _, message := range messages {
		index[string(message.Desc.FullName())] = message
		indexKotlinMessages(index, message.Messages)
	}
}

func (k kotlinRenderInfo) kotlinMessageTypeExpr(ref JVMTypeRef, imports map[string]bool, currentPackage string) (string, error) {
	message := k.messages[ref.ProtoFullName]
	if message == nil {
		return "", fmt.Errorf("message %q not found during Kotlin render", ref.ProtoFullName)
	}
	resolved, err := resolveJVMMessageTypeRef(message, k.file.Desc.Path())
	if err != nil {
		return "", err
	}
	if resolved.ImportPath != "" && kotlinImportPackage(resolved.ImportPath) != currentPackage {
		imports[resolved.ImportPath] = true
	}
	return resolved.Expr, nil
}

func validateKotlinMetadata(model JVMFileModel) error {
	for _, service := range model.Services {
		for _, icon := range service.Icons {
			if err := validateKotlinIconTheme(icon); err != nil {
				return err
			}
		}
		for _, method := range service.Methods {
			for _, icon := range method.Icons {
				if err := validateKotlinIconTheme(icon); err != nil {
					return err
				}
			}
		}
	}
	return nil
}

func validateKotlinIconTheme(icon *mcpoptionsv1.Icon) error {
	switch icon.GetTheme() {
	case "", "light", "dark":
		return nil
	default:
		return fmt.Errorf("unsupported Kotlin icon theme %q", icon.GetTheme())
	}
}

func kotlinAnnotations(ann *mcpoptionsv1.ToolAnnotations) string {
	if ann == nil {
		return "null"
	}

	var fields []string
	if ann.ReadOnlyHint {
		fields = append(fields, fmt.Sprintf("readOnlyHint = %t", ann.ReadOnlyHint))
	}
	if ann.DestructiveHint != nil {
		fields = append(fields, fmt.Sprintf("destructiveHint = %t", ann.GetDestructiveHint()))
	}
	if ann.IdempotentHint {
		fields = append(fields, fmt.Sprintf("idempotentHint = %t", ann.IdempotentHint))
	}
	if ann.OpenWorldHint != nil {
		fields = append(fields, fmt.Sprintf("openWorldHint = %t", ann.GetOpenWorldHint()))
	}
	if ann.Title != "" {
		fields = append(fields, "title = "+quote(ann.Title))
	}
	return "ToolAnnotations(" + strings.Join(fields, ", ") + ")"
}

func kotlinIcons(icons []*mcpoptionsv1.Icon) (string, error) {
	if len(icons) == 0 {
		return "emptyList()", nil
	}

	items := make([]string, 0, len(icons))
	for _, icon := range icons {
		if err := validateKotlinIconTheme(icon); err != nil {
			return "", err
		}
		sizes := "emptyList()"
		if len(icon.GetSizes()) > 0 {
			quotedSizes := make([]string, 0, len(icon.GetSizes()))
			for _, size := range icon.GetSizes() {
				quotedSizes = append(quotedSizes, quote(size))
			}
			sizes = "listOf(" + strings.Join(quotedSizes, ", ") + ")"
		}
		items = append(items, fmt.Sprintf(
			"Icon(src = %s, mimeType = %s, sizes = %s, theme = iconThemeOrError(%s))",
			quote(icon.GetSrc()),
			kotlinNullableString(icon.GetMimeType()),
			sizes,
			kotlinNullableString(icon.GetTheme()),
		))
	}
	return "listOf(" + strings.Join(items, ", ") + ")", nil
}

func kotlinTaskSupport(taskSupport mcpoptionsv1.TaskSupport) string {
	switch taskSupport {
	case mcpoptionsv1.TaskSupport_TASK_SUPPORT_OPTIONAL:
		return `toolExecutionOrNull("optional")`
	case mcpoptionsv1.TaskSupport_TASK_SUPPORT_REQUIRED:
		return `toolExecutionOrNull("required")`
	default:
		return `toolExecutionOrNull("none")`
	}
}

func kotlinNullableString(value string) string {
	if value == "" {
		return "null"
	}
	return quote(value)
}

func kotlinStringLiteral(value string) string {
	return strings.ReplaceAll(quote(value), "$", `\$`)
}

func kotlinImportPackage(importPath string) string {
	idx := strings.LastIndex(importPath, ".")
	if idx <= 0 {
		return ""
	}
	return importPath[:idx]
}
