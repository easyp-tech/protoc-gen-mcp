package codegen

import (
	"fmt"
	"strings"

	mcpoptionsv1 "github.com/easyp-tech/protoc-gen-mcp/mcp/options/v1"
	"google.golang.org/protobuf/compiler/protogen"
)

func renderGoFile(plugin *protogen.Plugin, model FileModel) error {
	goInfo, err := newGoRenderInfo(plugin, model)
	if err != nil {
		return err
	}

	filename := model.GeneratedFilenamePrefix + ".mcp.go"
	generated := plugin.NewGeneratedFile(filename, goInfo.file.GoImportPath)

	generated.P("// Code generated by protoc-gen-mcp. DO NOT EDIT.")
	generated.P("// source: ", model.ProtoPath)
	generated.P()
	generated.P("package ", goInfo.file.GoPackageName)
	generated.P()

	contextIdent := generated.QualifiedGoIdent(protogen.GoImportPath("context").Ident("Context"))
	errorsIdent := generated.QualifiedGoIdent(protogen.GoImportPath("errors").Ident("New"))
	mcpServerIdent := generated.QualifiedGoIdent(protogen.GoImportPath("github.com/easyp-tech/protoc-gen-mcp/mcpruntime").Ident("Server"))
	mcpruntimeImport := protogen.GoImportPath("github.com/easyp-tech/protoc-gen-mcp/mcpruntime")
	registerOptionIdent := generated.QualifiedGoIdent(mcpruntimeImport.Ident("RegisterOption"))
	registerToolIdent := generated.QualifiedGoIdent(mcpruntimeImport.Ident("RegisterProtoTool"))
	toolSpecIdent := generated.QualifiedGoIdent(mcpruntimeImport.Ident("ToolSpec"))

	for _, service := range model.Services {
		serviceGoName, err := goInfo.serviceGoName(service)
		if err != nil {
			return err
		}
		interfaceName := serviceGoName + "ToolHandler"
		generated.P("// ", interfaceName, " defines the business logic required by generated MCP tools.")
		generated.P("type ", interfaceName, " interface {")
		for _, method := range service.Methods {
			methodGoName, err := goInfo.methodGoName(method)
			if err != nil {
				return err
			}
			inputType, err := qualifyTypeRef(generated, goInfo, method.Input)
			if err != nil {
				return err
			}
			outputType, err := qualifyTypeRef(generated, goInfo, method.Output)
			if err != nil {
				return err
			}
			generated.P(methodGoName, "(ctx ", contextIdent, ", req *", inputType, ") (*", outputType, ", error)")
		}
		generated.P("}")
		generated.P()

		registerName := "Register" + serviceGoName + "Tools"
		generated.P("// ", registerName, " registers generated MCP tools for ", serviceGoName, ".")
		generated.P("func ", registerName, "(server *", mcpServerIdent, ", impl ", interfaceName, ", opts ...", registerOptionIdent, ") error {")
		generated.P("if impl == nil {")
		generated.P("return ", errorsIdent, "(\"", registerName, ": impl is nil\")")
		generated.P("}")
		for _, method := range service.Methods {
			methodGoName, err := goInfo.methodGoName(method)
			if err != nil {
				return err
			}
			specName := serviceGoName + "_" + methodGoName + "_ToolSpec"
			inputType, err := qualifyTypeRef(generated, goInfo, method.Input)
			if err != nil {
				return err
			}
			outputType, err := qualifyTypeRef(generated, goInfo, method.Output)
			if err != nil {
				return err
			}
			generated.P("if err := ", registerToolIdent, "(server, ", toolSpecIdent, "[*", inputType, ", *", outputType, "]{")
			generated.P("Name: ", quote(method.Name), ",")
			generated.P("Title: ", quote(method.Title), ",")
			generated.P("Description: ", quote(method.Description), ",")
			generated.P("Namespace: ", quote(service.Namespace), ",")
			generated.P("InputSchemaJSON: ", specName, "InputSchemaJSON,")
			generated.P("OutputSchemaJSON: ", specName, "OutputSchemaJSON,")
			generated.P("Annotations: ", stringifyAnnotations(generated, method.Annotations), ",")
			generated.P("Icons: ", stringifyIcons(generated, method.Icons), ",")
			generated.P("NewRequest: func() *", inputType, " { return &", inputType, "{} },")
			generated.P("NewResponse: func() *", outputType, " { return &", outputType, "{} },")
			generated.P("Handler: impl.", methodGoName, ",")
			generated.P("}, opts...); err != nil {")
			generated.P("return err")
			generated.P("}")
		}
		generated.P("return nil")
		generated.P("}")
		generated.P()

		for _, method := range service.Methods {
			methodGoName, err := goInfo.methodGoName(method)
			if err != nil {
				return err
			}
			specName := serviceGoName + "_" + methodGoName + "_ToolSpec"
			generated.P("const ", specName, "InputSchemaJSON = ", quote(method.InputSchemaJSON))
			generated.P()
			generated.P("const ", specName, "OutputSchemaJSON = ", quote(method.OutputSchemaJSON))
			generated.P()
		}
	}
	if len(model.Prompts) > 0 {
		mcpPromptIdent := generated.QualifiedGoIdent(protogen.GoImportPath("github.com/easyp-tech/protoc-gen-mcp/mcpruntime").Ident("Prompt"))
		mcpPromptArgIdent := generated.QualifiedGoIdent(protogen.GoImportPath("github.com/easyp-tech/protoc-gen-mcp/mcpruntime").Ident("PromptArgument"))
		mcpPromptMsgIdent := generated.QualifiedGoIdent(protogen.GoImportPath("github.com/easyp-tech/protoc-gen-mcp/mcpruntime").Ident("PromptMessage"))
		mcpGetPromptReqIdent := generated.QualifiedGoIdent(protogen.GoImportPath("github.com/easyp-tech/protoc-gen-mcp/mcpruntime").Ident("GetPromptRequest"))
		mcpGetPromptResIdent := generated.QualifiedGoIdent(protogen.GoImportPath("github.com/easyp-tech/protoc-gen-mcp/mcpruntime").Ident("GetPromptResult"))
		parsePromptArgsIdent := generated.QualifiedGoIdent(mcpruntimeImport.Ident("ParsePromptArguments"))

		// Use file base name for interface naming.
		fileGoName := goInfo.file.GoDescriptorIdent.GoName
		interfaceName := fileGoName + "PromptHandler"

		generated.P("// ", interfaceName, " defines handlers for MCP prompts in ", model.ProtoPath, ".")
		generated.P("type ", interfaceName, " interface {")
		for _, prompt := range model.Prompts {
			inputType, err := qualifyTypeRef(generated, goInfo, prompt.Input)
			if err != nil {
				return err
			}
			generated.P(prompt.ProtoName, "(ctx ", contextIdent, ", req *", inputType, ") ([]", mcpPromptMsgIdent, ", error)")
		}
		generated.P("}")
		generated.P()

		registerName := "Register" + fileGoName + "Prompts"
		generated.P("// ", registerName, " registers generated MCP prompts for ", fileGoName, ".")
		generated.P("func ", registerName, "(server *", mcpServerIdent, ", impl ", interfaceName, ", opts ...", registerOptionIdent, ") error {")
		generated.P("if impl == nil {")
		generated.P("return ", errorsIdent, "(\"", registerName, ": impl is nil\")")
		generated.P("}")

		for _, prompt := range model.Prompts {
			inputType, err := qualifyTypeRef(generated, goInfo, prompt.Input)
			if err != nil {
				return err
			}

			// Build required fields list.
			var requiredNames []string
			for _, arg := range prompt.Arguments {
				if arg.Required {
					requiredNames = append(requiredNames, arg.Name)
				}
			}

			generated.P("server.AddPrompt(&", mcpPromptIdent, "{")
			generated.P("Name: ", quote(prompt.Name), ",")
			if prompt.Title != "" {
				generated.P("Title: ", quote(prompt.Title), ",")
			}
			generated.P("Description: ", quote(prompt.Description), ",")
			if len(prompt.Icons) > 0 {
				generated.P("Icons: ", stringifyIcons(generated, prompt.Icons), ",")
			}
			generated.P("Arguments: []", mcpPromptArgIdent, "{")
			for _, arg := range prompt.Arguments {
				generated.P("{Name: ", quote(arg.Name), ", Description: ", quote(arg.Description), ", Required: ", fmt.Sprintf("%t", arg.Required), "},")
			}
			generated.P("},")
			generated.P("}, func(ctx ", contextIdent, ", req *", mcpGetPromptReqIdent, ") (*", mcpGetPromptResIdent, ", error) {")
			generated.P("msg := &", inputType, "{}")
			generated.P("if err := ", parsePromptArgsIdent, "(req.Arguments, msg, []string{")
			for _, name := range requiredNames {
				generated.P(quote(name), ",")
			}
			generated.P("}); err != nil {")
			generated.P("return nil, err")
			generated.P("}")
			generated.P("result, err := impl.", prompt.ProtoName, "(ctx, msg)")
			generated.P("if err != nil {")
			generated.P("return nil, err")
			generated.P("}")
			generated.P("return &", mcpGetPromptResIdent, "{Messages: result}, nil")
			generated.P("})")
		}
		generated.P("return nil")
		generated.P("}")
		generated.P()
	}

	if len(model.Resources) > 0 {
		mcpResourceIdent := generated.QualifiedGoIdent(protogen.GoImportPath("github.com/easyp-tech/protoc-gen-mcp/mcpruntime").Ident("Resource"))
		mcpResourceTemplateIdent := generated.QualifiedGoIdent(protogen.GoImportPath("github.com/easyp-tech/protoc-gen-mcp/mcpruntime").Ident("ResourceTemplate"))
		mcpReadResourceReqIdent := generated.QualifiedGoIdent(protogen.GoImportPath("github.com/easyp-tech/protoc-gen-mcp/mcpruntime").Ident("ReadResourceRequest"))
		mcpReadResourceResIdent := generated.QualifiedGoIdent(protogen.GoImportPath("github.com/easyp-tech/protoc-gen-mcp/mcpruntime").Ident("ReadResourceResult"))
		mcpResourceContentsIdent := generated.QualifiedGoIdent(protogen.GoImportPath("github.com/easyp-tech/protoc-gen-mcp/mcpruntime").Ident("ResourceContents"))
		mcpAnnotationsIdent := generated.QualifiedGoIdent(protogen.GoImportPath("github.com/easyp-tech/protoc-gen-mcp/mcpruntime").Ident("Annotations"))
		mcpRoleIdent := generated.QualifiedGoIdent(protogen.GoImportPath("github.com/easyp-tech/protoc-gen-mcp/mcpruntime").Ident("Role"))
		extractURIParamsIdent := generated.QualifiedGoIdent(mcpruntimeImport.Ident("ExtractURIParams"))
		marshalResourceContentIdent := generated.QualifiedGoIdent(mcpruntimeImport.Ident("MarshalResourceContent"))
		fmtErrorfIdent := generated.QualifiedGoIdent(protogen.GoImportPath("fmt").Ident("Errorf"))

		fileGoName := goInfo.file.GoDescriptorIdent.GoName
		interfaceName := fileGoName + "ResourceHandler"

		// Generate interface.
		generated.P("// ", interfaceName, " defines handlers for MCP resources in ", model.ProtoPath, ".")
		generated.P("type ", interfaceName, " interface {")
		for _, resource := range model.Resources {
			outputType, err := qualifyTypeRef(generated, goInfo, resource.Output)
			if err != nil {
				return err
			}
			if resource.IsTemplate {
				generated.P("List", resource.ProtoName, "s(ctx ", contextIdent, ") ([]", mcpResourceIdent, ", error)")
				// Read method with URI template params.
				paramList := "ctx " + contextIdent
				for _, param := range resource.Params {
					paramList += ", " + param.Name + " string"
				}
				generated.P("Read", resource.ProtoName, "(", paramList, ") (*", outputType, ", error)")
			} else {
				generated.P("Read", resource.ProtoName, "(ctx ", contextIdent, ") (*", outputType, ", error)")
			}
		}
		generated.P("}")
		generated.P()

		// Generate Register function.
		registerName := "Register" + fileGoName + "Resources"
		generated.P("// ", registerName, " registers generated MCP resources for ", fileGoName, ".")
		generated.P("func ", registerName, "(ctx ", contextIdent, ", server *", mcpServerIdent, ", impl ", interfaceName, ", opts ...", registerOptionIdent, ") error {")
		generated.P("if impl == nil {")
		generated.P("return ", errorsIdent, "(\"", registerName, ": impl is nil\")")
		generated.P("}")
		generated.P("resolvedOpts := ", generated.QualifiedGoIdent(mcpruntimeImport.Ident("ResolveOptions")), "(\"\", opts)")

		for _, resource := range model.Resources {
			// Build name with namespace.
			generated.P("{")
			generated.P("name := ", quote(resource.Name))
			generated.P("if resolvedOpts.Namespace != \"\" {")
			generated.P("name = resolvedOpts.Namespace + \"_\" + name")
			generated.P("}")

			// Build annotations if present.
			if resource.Annotations != nil {
				generated.P("annotations := &", mcpAnnotationsIdent, "{")
				if len(resource.Annotations.GetAudience()) > 0 {
					generated.P("Audience: []", mcpRoleIdent, "{")
					for _, aud := range resource.Annotations.GetAudience() {
						switch aud {
						case 1: // USER
							generated.P(quote("user"), ",")
						case 2: // ASSISTANT
							generated.P(quote("assistant"), ",")
						}
					}
					generated.P("},")
				}
				if resource.Annotations.Priority != nil {
					ptrIdent := generated.QualifiedGoIdent(mcpruntimeImport.Ident("Ptr"))
					generated.P("Priority: ", ptrIdent, "(", fmt.Sprintf("%g", resource.Annotations.GetPriority()), "),")
				}
				generated.P("}")
			}

			if resource.IsTemplate {
				// Template resource: call List, register instances, register template.
				generated.P("instances, err := impl.List", resource.ProtoName, "s(ctx)")
				generated.P("if err != nil {")
				generated.P("return ", fmtErrorfIdent, "(\"", registerName, ": listing ", resource.Name, ": %w\", err)")
				generated.P("}")

				// Register each instance with a read handler.
				generated.P("readHandler := func(ctx ", contextIdent, ", req *", mcpReadResourceReqIdent, ") (*", mcpReadResourceResIdent, ", error) {")
				generated.P("params, err := ", extractURIParamsIdent, "(req.URI, ", quote(resource.URITemplate), ")")
				generated.P("if err != nil {")
				generated.P("return nil, err")
				generated.P("}")
				// Extract each param.
				for _, param := range resource.Params {
					generated.P(param.Name, " := params[", quote(param.Name), "]")
				}
				// Call impl.
				paramArgs := "ctx"
				for _, param := range resource.Params {
					paramArgs += ", " + param.Name
				}
				generated.P("result, err := impl.Read", resource.ProtoName, "(", paramArgs, ")")
				generated.P("if err != nil {")
				generated.P("return nil, err")
				generated.P("}")
				generated.P("contents, err := ", marshalResourceContentIdent, "(req.URI, ", quote(resource.MIMEType), ", result)")
				generated.P("if err != nil {")
				generated.P("return nil, err")
				generated.P("}")
				generated.P("return &", mcpReadResourceResIdent, "{Contents: contents}, nil")
				generated.P("}")

				// Register instances.
				generated.P("for i := range instances {")
				generated.P("server.AddResource(&instances[i], readHandler)")
				generated.P("}")

				// Register template.
				generated.P("server.AddResourceTemplate(&", mcpResourceTemplateIdent, "{")
				generated.P("Name: name,")
				generated.P("URITemplate: ", quote(resource.URITemplate), ",")
				generated.P("Description: ", quote(resource.Description), ",")
				if resource.MIMEType != "" {
					generated.P("MIMEType: ", quote(resource.MIMEType), ",")
				}
				if resource.Annotations != nil {
					generated.P("Annotations: annotations,")
				}
				generated.P("}, readHandler)")
			} else {
				// Static resource: register with read handler.
				generated.P("server.AddResource(&", mcpResourceIdent, "{")
				generated.P("Name: name,")
				generated.P("URI: ", quote(resource.URI), ",")
				generated.P("Description: ", quote(resource.Description), ",")
				if resource.MIMEType != "" {
					generated.P("MIMEType: ", quote(resource.MIMEType), ",")
				}
				if resource.Annotations != nil {
					generated.P("Annotations: annotations,")
				}
				generated.P("}, func(ctx ", contextIdent, ", req *", mcpReadResourceReqIdent, ") (*", mcpReadResourceResIdent, ", error) {")
				generated.P("result, err := impl.Read", resource.ProtoName, "(ctx)")
				generated.P("if err != nil {")
				generated.P("return nil, err")
				generated.P("}")
				generated.P("contents, err := ", marshalResourceContentIdent, "(", quote(resource.URI), ", ", quote(resource.MIMEType), ", result)")
				generated.P("if err != nil {")
				generated.P("return nil, err")
				generated.P("}")
				generated.P("return &", mcpReadResourceResIdent, "{Contents: contents}, nil")
				generated.P("})")
			}

			generated.P("}")
			generated.P()

			// Suppress unused import warnings for ResourceContents.
			_ = mcpResourceContentsIdent
		}

		generated.P("return nil")
		generated.P("}")
		generated.P()
	}

	return nil
}

type goRenderInfo struct {
	file     *protogen.File
	messages map[string]*protogen.Message
	methods  map[string]*protogen.Method
	services map[string]*protogen.Service
}

func newGoRenderInfo(plugin *protogen.Plugin, model FileModel) (goRenderInfo, error) {
	file := plugin.FilesByPath[model.ProtoPath]
	if file == nil {
		return goRenderInfo{}, fmt.Errorf("generated file %q not found in plugin", model.ProtoPath)
	}

	info := goRenderInfo{
		file:     file,
		messages: map[string]*protogen.Message{},
		methods:  map[string]*protogen.Method{},
		services: map[string]*protogen.Service{},
	}
	for _, current := range plugin.Files {
		indexGoMessages(info.messages, current.Messages)
		for _, service := range current.Services {
			info.services[string(service.Desc.FullName())] = service
			for _, method := range service.Methods {
				info.methods[string(method.Desc.FullName())] = method
			}
		}
	}

	return info, nil
}

func indexGoMessages(index map[string]*protogen.Message, messages []*protogen.Message) {
	for _, message := range messages {
		index[string(message.Desc.FullName())] = message
		indexGoMessages(index, message.Messages)
	}
}

func (g goRenderInfo) serviceGoName(service ServiceModel) (string, error) {
	resolved := g.services[service.ProtoFullName]
	if resolved == nil {
		return "", fmt.Errorf("service %q not found during Go render", service.ProtoFullName)
	}
	return resolved.GoName, nil
}

func (g goRenderInfo) methodGoName(method MethodModel) (string, error) {
	resolved := g.methods[method.ProtoFullName]
	if resolved == nil {
		return "", fmt.Errorf("method %q not found during Go render", method.ProtoFullName)
	}
	return resolved.GoName, nil
}

func qualifyTypeRef(generated *protogen.GeneratedFile, goInfo goRenderInfo, ref TypeRef) (string, error) {
	message := goInfo.messages[ref.ProtoFullName]
	if message == nil {
		return "", fmt.Errorf("message %q not found during Go render", ref.ProtoFullName)
	}
	return generated.QualifiedGoIdent(message.GoIdent), nil
}

func quote(value string) string {
	return fmt.Sprintf("%q", value)
}

func stringifyAnnotations(generated *protogen.GeneratedFile, ann *mcpoptionsv1.ToolAnnotations) string {
	if ann == nil {
		return "nil"
	}
	mcpAnnIdent := generated.QualifiedGoIdent(protogen.GoImportPath("github.com/easyp-tech/protoc-gen-mcp/mcpruntime").Ident("ToolAnnotations"))

	var fields []string
	if ann.ReadOnlyHint {
		protoBoolIdent := generated.QualifiedGoIdent(protogen.GoImportPath("google.golang.org/protobuf/proto").Ident("Bool"))
		fields = append(fields, fmt.Sprintf("ReadOnlyHint: %s(%t),", protoBoolIdent, ann.ReadOnlyHint))
	}
	if ann.DestructiveHint != nil {
		protoBoolIdent := generated.QualifiedGoIdent(protogen.GoImportPath("google.golang.org/protobuf/proto").Ident("Bool"))
		fields = append(fields, fmt.Sprintf("DestructiveHint: %s(%t),", protoBoolIdent, *ann.DestructiveHint))
	}
	if ann.IdempotentHint != false {
		protoBoolIdent := generated.QualifiedGoIdent(protogen.GoImportPath("google.golang.org/protobuf/proto").Ident("Bool"))
		fields = append(fields, fmt.Sprintf("IdempotentHint: %s(%t),", protoBoolIdent, ann.IdempotentHint))
	}
	if ann.OpenWorldHint != nil {
		protoBoolIdent := generated.QualifiedGoIdent(protogen.GoImportPath("google.golang.org/protobuf/proto").Ident("Bool"))
		fields = append(fields, fmt.Sprintf("OpenWorldHint: %s(%t),", protoBoolIdent, *ann.OpenWorldHint))
	}
	if ann.Title != "" {
		protoStringIdent := generated.QualifiedGoIdent(protogen.GoImportPath("google.golang.org/protobuf/proto").Ident("String"))
		fields = append(fields, fmt.Sprintf("Title: %s(%q),", protoStringIdent, ann.Title))
	}

	if len(fields) == 0 {
		return "&" + mcpAnnIdent + "{}"
	}
	return "&" + mcpAnnIdent + "{" + strings.Join(fields, " ") + "}"
}

func stringifyIcons(generated *protogen.GeneratedFile, icons []*mcpoptionsv1.Icon) string {
	if len(icons) == 0 {
		return "nil"
	}
	mcpIconIdent := generated.QualifiedGoIdent(protogen.GoImportPath("github.com/easyp-tech/protoc-gen-mcp/mcpruntime").Ident("Icon"))

	var items []string
	for _, icon := range icons {
		items = append(items, fmt.Sprintf("%s{URL: %q, MIMEType: %q},",
			mcpIconIdent, icon.GetSrc(), icon.GetMimeType()))
	}
	return "[]" + mcpIconIdent + "{" + strings.Join(items, " ") + "}"
}
