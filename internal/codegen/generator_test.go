func diffBytes(want []byte, got []byte) string {
	return fmt.Sprintf("--- want\n+++ got\n%s", firstDiffLine(string(want), string(got)))
}

func firstDiffLine(want string, got string) string {
	wantLines := strings.Split(want, "\n")
	gotLines := strings.Split(got, "\n")
	limit := len(wantLines)
	if len(gotLines) < limit {
		limit = len(gotLines)
	}
	for i := 0; i < limit; i++ {
		if wantLines[i] != gotLines[i] {
			return fmt.Sprintf("@@ line %d @@\n- %s\n+ %s\n", i+1, wantLines[i], gotLines[i])
		}
	}
	if len(wantLines) != len(gotLines) {
		return fmt.Sprintf("@@ line count @@\n- %d lines\n+ %d lines\n", len(wantLines), len(gotLines))
	}
	return "(contents differ, but no differing line was isolated)"
}
