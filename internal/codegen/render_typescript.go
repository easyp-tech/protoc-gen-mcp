func renderTypeScriptService(generated *protogen.GeneratedFile, model TypeScriptFileModel, service TypeScriptServiceModel) {
	// Public declarations render as `export interface ExampleAPIToolHandler`
	// and `export function registerExampleAPITools` for Node consumers.
	generated.P("export interface ", service.HandlerName, " {")
	for _, method := range service.Methods {
		generated.P("  ", method.MethodName, "(")
		generated.P("    ctx: ToolRequestContext,")
		generated.P("    request: ", method.Input.TypeName, ",")
		generated.P("  ): ", method.Output.TypeName, " | Promise<", method.Output.TypeName, ">;")
	}
	generated.P("}")
	generated.P()

	for _, method := range service.Methods {
		generated.P("export const ", method.SchemaConst, "_INPUT_SCHEMA_JSON = ", typescriptStringLiteral(method.InputSchemaJSON), ";")
		generated.P("export const ", method.SchemaConst, "_OUTPUT_SCHEMA_JSON = ", typescriptStringLiteral(method.OutputSchemaJSON), ";")
		generated.P()
	}

	generated.P("export function ", service.RegisterName, "(")
	generated.P("  server: Server,")
	generated.P("  impl: ", service.HandlerName, ",")
	generated.P("  namespace?: string | null,")
	generated.P("): void {")
	generated.P("  const registry = getToolRegistry(server);")
	generated.P("  installMcpHandlers(server, registry);")
	generated.P("  registry.tools.push(")
	for _, method := range service.Methods {
		renderTypeScriptRegisteredTool(generated, model, service, method)
		generated.P("    },")
	}
	generated.P("  );")
	generated.P("}")
}

func renderTypeScriptRegisteredTool(generated *protogen.GeneratedFile, model TypeScriptFileModel, service TypeScriptServiceModel, method TypeScriptMethodModel) {
	generated.P("    {")
	generated.P("      name: resolveToolName(namespace, ", typescriptStringLiteral(method.ToolName), ", ", typescriptStringLiteral(service.Namespace), "),")
	if method.Title != "" {
		generated.P("      title: ", typescriptStringLiteral(method.Title), ",")
	}
	if method.Description != "" {
		generated.P("      description: ", typescriptStringLiteral(method.Description), ",")
	}
	generated.P("      impl,")
	generated.P("      handler: impl.", method.MethodName, ".bind(impl),")
	generated.P("      inputSchemaJson: ", method.SchemaConst, "_INPUT_SCHEMA_JSON,")
	generated.P("      outputSchemaJson: ", method.SchemaConst, "_OUTPUT_SCHEMA_JSON,")
	generated.P("      inputSchema: ", method.Input.SchemaName, ",")
	generated.P("      outputSchema: ", method.Output.SchemaName, ",")
	generated.P("      fileRegistry: ", model.CurrentFile.RegistryRef.RefName, ",")
	generated.P("      inputFileRegistry: ", method.Input.RegistryRef.RefName, ",")
	generated.P("      outputFileRegistry: ", method.Output.RegistryRef.RefName, ",")
	generated.P("      registry: buildProtoRegistry(", model.CurrentFile.RegistryRef.RefName, ", ", method.Input.RegistryRef.RefName, ", ", method.Output.RegistryRef.RefName, "),")
	generated.P("      validateInput: compileSchema(", method.SchemaConst, "_INPUT_SCHEMA_JSON),")
	generated.P("      validateOutput: compileSchema(", method.SchemaConst, "_OUTPUT_SCHEMA_JSON),")
	renderTypeScriptAnnotations(generated, method.Annotations)
	renderTypeScriptIcons(generated, method.Icons)
	renderTypeScriptExecution(generated, method.TaskSupport)
}

func renderTypeScriptAnnotations(generated *protogen.GeneratedFile, ann *mcpoptionsv1.ToolAnnotations) {
	if ann == nil {
		generated.P("      annotations: undefined,")
		return
	}

	generated.P("      annotations: {")
	if ann.ReadOnlyHint {
		generated.P("        readOnlyHint: true,")
	}
	if ann.DestructiveHint != nil {
		generated.P("        destructiveHint: ", typescriptBoolLiteral(ann.GetDestructiveHint()), ",")
	}
	if ann.IdempotentHint {
		generated.P("        idempotentHint: true,")
	}
	if ann.OpenWorldHint != nil {
		generated.P("        openWorldHint: ", typescriptBoolLiteral(ann.GetOpenWorldHint()), ",")
	}
	if ann.Title != "" {
		generated.P("        title: ", typescriptStringLiteral(ann.Title), ",")
	}
	generated.P("      },")
}

func renderTypeScriptIcons(generated *protogen.GeneratedFile, icons []*mcpoptionsv1.Icon) {
	generated.P("      icons: [")
	for _, icon := range icons {
		generated.P("        {")
		generated.P("          src: ", typescriptStringLiteral(icon.GetSrc()), ",")
		if icon.GetMimeType() != "" {
			generated.P("          mimeType: ", typescriptStringLiteral(icon.GetMimeType()), ",")
		}
		if len(icon.GetSizes()) > 0 {
			generated.P("          sizes: ", typescriptStringArrayLiteral(icon.GetSizes()), ",")
		}
		if icon.GetTheme() != "" {
			generated.P("          theme: ", typescriptStringLiteral(icon.GetTheme()), ",")
		}
		generated.P("        },")
	}
	generated.P("      ],")
}

func renderTypeScriptExecution(generated *protogen.GeneratedFile, taskSupport mcpoptionsv1.TaskSupport) {
	switch taskSupport {
	case mcpoptionsv1.TaskSupport_TASK_SUPPORT_OPTIONAL:
		generated.P(`      execution: { taskSupport: "optional" },`)
	case mcpoptionsv1.TaskSupport_TASK_SUPPORT_REQUIRED:
		generated.P(`      execution: { taskSupport: "required" },`)
	default:
		generated.P("      execution: undefined,")
	}
}

func renderTypeScriptPrivateRegistryHelpers(generated *protogen.GeneratedFile) {
	generated.P("const toolRegistries = new WeakMap<Server, ServerToolRegistry>();")
	generated.P("const jsonSchemaValidator = new Ajv2020({ strict: false, allErrors: true });")
	generated.P()
	generated.P("function getToolRegistry(server: Server): ServerToolRegistry {")
	generated.P("  let registry = toolRegistries.get(server);")
	generated.P("  if (registry === undefined) {")
	generated.P("    registry = { tools: [], handlersInstalled: false };")
	generated.P("    toolRegistries.set(server, registry);")
	generated.P("  }")
	generated.P("  return registry;")
	generated.P("}")
	generated.P()
	generated.P("function installMcpHandlers(server: Server, registry: ServerToolRegistry): void {")
	generated.P("  if (registry.handlersInstalled) {")
	generated.P("    return;")
	generated.P("  }")
	generated.P(`  server.assertCanSetRequestHandler("tools/list");`)
	generated.P(`  server.assertCanSetRequestHandler("tools/call");`)
	generated.P("  server.setRequestHandler(ListToolsRequestSchema, async (): Promise<{ tools: Tool[] }> => ({")
	generated.P("    tools: listRegisteredTools(registry),")
	generated.P("  }));")
	generated.P("  server.setRequestHandler(CallToolRequestSchema, async (request, extra): Promise<CallToolResult> => (")
	generated.P("    dispatchToolCall(")
	generated.P("      registry,")
	generated.P("      request,")
	generated.P("      extra as ToolRequestContext,")
	generated.P("    )")
	generated.P("  ));")
	generated.P("  registry.handlersInstalled = true;")
	generated.P("}")
	generated.P()
	generated.P("function listRegisteredTools(registry: ServerToolRegistry): Tool[] {")
	generated.P("  return registry.tools.map(buildListTool);")
	generated.P("}")
	generated.P()
	generated.P("function buildListTool(tool: RegisteredTool): Tool {")
	generated.P("  const listed = {")
	generated.P("    name: tool.name,")
	generated.P("    inputSchema: loadSchema(tool.inputSchemaJson),")
	generated.P("    outputSchema: loadSchema(tool.outputSchemaJson),")
	generated.P("  } as Tool;")
	generated.P("  if (tool.title !== undefined) {")
	generated.P("    listed.title = tool.title;")
	generated.P("  }")
	generated.P("  if (tool.description !== undefined) {")
	generated.P("    listed.description = tool.description;")
	generated.P("  }")
	generated.P("  if (tool.annotations !== undefined) {")
	generated.P("    listed.annotations = tool.annotations;")
	generated.P("  }")
	generated.P("  if (tool.icons.length > 0) {")
	generated.P("    listed.icons = tool.icons as Tool[\"icons\"];")
	generated.P("  }")
	generated.P("  if (tool.execution !== undefined) {")
	generated.P("    listed.execution = tool.execution;")
	generated.P("  }")
	generated.P("  return listed;")
	generated.P("}")
	generated.P()
	generated.P("function loadSchema(rawSchemaJson: string): Record<string, unknown> {")
	generated.P("  const parsed: unknown = JSON.parse(rawSchemaJson);")
	generated.P("  if (parsed === null || typeof parsed !== \"object\" || Array.isArray(parsed)) {")
	generated.P("    throw new Error(\"mcpruntime: generated schema JSON must be an object\");")
	generated.P("  }")
	generated.P("  return parsed as Record<string, unknown>;")
	generated.P("}")
	generated.P()
	generated.P("function compileSchema(rawSchemaJson: string): ValidateFunction {")
	generated.P("  return jsonSchemaValidator.compile(loadSchema(rawSchemaJson));")
	generated.P("}")
	generated.P()
	generated.P("function assertValid(")
	generated.P("  toolName: string,")
	generated.P(`  phase: "input" | "output",`)
	generated.P("  validate: ValidateFunction,")
	generated.P("  value: unknown,")
	generated.P("): void {")
	generated.P("  if (validate(value)) {")
	generated.P("    return;")
	generated.P("  }")
	generated.P("  const message = jsonSchemaValidator.errorsText(validate.errors);")
	generated.P(`  if (phase === "input") {`)
	generated.P("    invalidParams(toolName, message);")
	generated.P("  }")
	generated.P("  throw new Error(`mcpruntime: validate output for tool '${toolName}': ${message}`);")
	generated.P("}")
	generated.P()
	generated.P("function invalidParams(toolName: string, error: unknown): never {")
	generated.P("  throw new McpError(")
	generated.P("    ErrorCode.InvalidParams,")
	generated.P("    `invalid arguments for tool '${toolName}': ${errorMessage(error)}`,")
	generated.P("  );")
	generated.P("}")
	generated.P()
	generated.P("function toolErrorResult(error: unknown): CallToolResult {")
	generated.P("  return {")
	generated.P(`    content: [{ type: "text", text: errorMessage(error) }],`)
	generated.P("    isError: true,")
	generated.P("  };")
	generated.P("}")
	generated.P()
	generated.P("async function dispatchToolCall(")
	generated.P("  registry: ServerToolRegistry,")
	generated.P("  request: CallToolRequest,")
	generated.P("  extra: ToolRequestContext,")
	generated.P("): Promise<CallToolResult> {")
	generated.P("  const toolName = request.params.name;")
	generated.P("  const tool = registry.tools.find((candidate) => candidate.name === toolName);")
	generated.P("  if (tool === undefined) {")
	generated.P("    throw new McpError(ErrorCode.InvalidParams, `unknown tool '${toolName}'`);")
	generated.P("  }")
	generated.P("  const args = (request.params.arguments ?? {}) as JsonValue;")
	generated.P("  assertValid(tool.name, \"input\", tool.validateInput, args);")
	generated.P()
	generated.P("  let parsedRequest: MessageShape<typeof tool.inputSchema>;")
	generated.P("  try {")
	generated.P("    parsedRequest = fromJson(tool.inputSchema, args, { registry: tool.registry });")
	generated.P("  } catch (error) {")
	generated.P("    invalidParams(tool.name, error);")
	generated.P("  }")
	generated.P()
	generated.P("  let response: unknown;")
	generated.P("  try {")
	generated.P("    response = await tool.handler(extra, parsedRequest as never);")
	generated.P("  } catch (error) {")
	generated.P("    return toolErrorResult(error);")
	generated.P("  }")
	generated.P()
	generated.P("  let payload: JsonValue;")
	generated.P("  try {")
	generated.P("    payload = toJson(tool.outputSchema, response as MessageShape<typeof tool.outputSchema>, {")
	generated.P("      alwaysEmitImplicit: true,")
	generated.P("      registry: tool.registry,")
	generated.P("    }) as JsonValue;")
	generated.P("  } catch (error) {")
	generated.P("    throw new Error(`mcpruntime: marshal output for tool '${tool.name}': ${errorMessage(error)}`);")
	generated.P("  }")
	generated.P("  assertValid(tool.name, \"output\", tool.validateOutput, payload);")
	generated.P("  return {")
	generated.P(`    content: [{ type: "text", text: JSON.stringify(payload) }],`)
	generated.P("    structuredContent: payload as Record<string, unknown>,")
	generated.P("  };")
	generated.P("}")
	generated.P()
	generated.P("function errorMessage(error: unknown): string {")
	generated.P(`  if (error instanceof Error && error.message !== "") {`)
	generated.P("    return error.message;")
	generated.P("  }")
	generated.P("  return String(error);")
	generated.P("}")
	generated.P()
	generated.P("function buildProtoRegistry(...fileRegistries: DescFile[]): Registry {")
	generated.P("  return createRegistry(...fileRegistries);")
	generated.P("}")
	generated.P()
	generated.P("function resolveToolName(")
	generated.P("  namespace: string | null | undefined,")
	generated.P("  defaultName: string,")
	generated.P("  defaultNamespace: string,")
	generated.P("): string {")
	generated.P("  const resolvedNamespace = normalizeToolSegment(")
	generated.P("    namespace === null || namespace === undefined ? defaultNamespace : namespace,")
	generated.P("  );")
	generated.P("  const resolvedName = normalizeToolSegment(defaultName);")
	generated.P("  if (resolvedNamespace === \"\") {")
	generated.P("    return resolvedName;")
	generated.P("  }")
	generated.P("  if (resolvedName === \"\") {")
	generated.P("    return resolvedNamespace;")
	generated.P("  }")
	generated.P("  return `${resolvedNamespace}_${resolvedName}`;")
	generated.P("}")
	generated.P()
	generated.P("function normalizeToolSegment(segment: string | null | undefined): string {")
	generated.P("  if (segment === null || segment === undefined) {")
	generated.P("    return \"\";")
	generated.P("  }")
	generated.P("  return segment.trim().replace(/[.]+/g, \"_\").replace(/_+/g, \"_\").replace(/^_+|_+$/g, \"\");")
	generated.P("}")
}

func typescriptOutputPathForProtoPath(protoPath string) string {
	return typescriptGeneratedFilenamePrefixForProtoPath(protoPath) + "_mcp.ts"
}

func typescriptGeneratedFilenamePrefixForProtoPath(protoPath string) string {
	prefix := strings.TrimSuffix(protoPath, path.Ext(protoPath))
	parts := strings.Split(prefix, "/")
	for i, part := range parts {
		parts[i] = strings.ReplaceAll(part, "-", "_")
	}
	return strings.Join(parts, "/")
}

func typescriptSchemaConst(service, method string) string {
	return toUpperSnakeCase(service) + "_" + toUpperSnakeCase(method)
}

func typescriptStringLiteral(value string) string {
	encoded, err := json.Marshal(value)
	if err != nil {
		panic(fmt.Sprintf("marshal TypeScript string literal: %v", err))
	}
	return string(encoded)
}

func typescriptBoolLiteral(value bool) string {
	if value {
		return "true"
	}
	return "false"
}

func typescriptStringArrayLiteral(values []string) string {
	items := make([]string, 0, len(values))
	for _, value := range values {
		items = append(items, typescriptStringLiteral(value))
	}
	return "[" + strings.Join(items, ", ") + "]"
}
