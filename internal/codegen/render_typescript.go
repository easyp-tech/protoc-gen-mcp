func renderTypeScriptFile(plugin *protogen.Plugin, model TypeScriptFileModel) error {
	if model.Language != LanguageTypeScript {
		return fmt.Errorf("typescript renderer requires lang=typescript, got %q", model.Language)
	}

	filename := typescriptOutputPathForProtoPath(model.ProtoPath)
	generated := plugin.NewGeneratedFile(filename, "")

	generated.P("// Code generated by protoc-gen-mcp. DO NOT EDIT.")
	generated.P("// source: ", model.ProtoPath)
	generated.P()
	renderTypeScriptImports(generated, model)
	generated.P("export type ToolRequestContext = protocGenMcp.ToolRequestContext;")
	generated.P()
	generated.P("protocGenMcp.checkGencodeVersion(", typescriptGencodeVersion, ");")
	generated.P()

	for _, service := range model.Services {
		renderTypeScriptService(generated, model, service)
		generated.P()
	}

	if len(model.Prompts) > 0 {
		renderTypeScriptPrompts(generated, model)
		generated.P()
	}

	if len(model.Resources) > 0 {
		if err := renderTypeScriptResources(generated, model); err != nil {
			return err
		}
		generated.P()
	}

	if model.Factory.Emit {
		renderTypeScriptServerFactory(generated, model)
		generated.P()
	}
	return nil
}

// renderTypeScriptServerFactory mirrors render_go_server.go. Stateless HTTP
// needs a fresh Server per request, so the factory is the natural entry point.
func renderTypeScriptServerFactory(generated *protogen.GeneratedFile, model TypeScriptFileModel) {
	fileName := typescriptExportedIdentifier(typescriptFileBaseName(model.ProtoPath))
	generated.P("/** Business handlers for every MCP primitive in ", model.ProtoPath, ". */")
	generated.P("export type ", fileName, "MCPHandlers = {")
	for _, service := range model.Services {
		generated.P("  ", typescriptMethodName(service.ProtoName), ": ", service.HandlerName, ";")
	}
	if len(model.Prompts) > 0 {
		generated.P("  prompts: ", fileName, "PromptHandler;")
	}
	if len(model.Resources) > 0 {
		generated.P("  resources: ", fileName, "ResourceHandler;")
	}
	generated.P("};")
	generated.P()
	generated.P("/** Builds the server declared by ", model.ProtoPath, " and registers its primitives. */")
	generated.P("export function create", fileName, "MCPServer(handlers: ", fileName, "MCPHandlers): Server {")
	generated.P("  const server = protocGenMcp.newConfiguredServer(", typescriptStringLiteral(model.Factory.Name), ", ", typescriptStringLiteral(model.Factory.Version), ", ", typescriptBoolLiteral(model.Factory.Apps), ");")
	for _, service := range model.Services {
		generated.P("  ", service.RegisterName, "(server, handlers.", typescriptMethodName(service.ProtoName), ");")
	}
	if len(model.Prompts) > 0 {
		generated.P("  register", fileName, "Prompts(server, handlers.prompts);")
	}
	if len(model.Resources) > 0 {
		generated.P("  register", fileName, "Resources(server, handlers.resources);")
	}
	generated.P("  return server;")
	generated.P("}")

	if !model.Factory.HTTP {
		return
	}
	generated.P()
	generated.P("/**")
	generated.P(" * Serves ", model.ProtoPath, " over stateless Streamable HTTP with its declared policy.")
	generated.P(" * A fresh server is built per request; with OAuth, verifier defaults to the")
	generated.P(" * built-in RS256 JWKS verifier.")
	generated.P(" */")
	generated.P("export function create", fileName, "MCPHttpHandler(handlers: ", fileName, "MCPHandlers, verifier?: protocGenMcp.TokenVerifier): protocGenMcp.HttpHandler {")
	oauth := model.Factory.OAuth
	if oauth == nil {
		generated.P("  return protocGenMcp.newHttpHandler(() => create", fileName, "MCPServer(handlers));")
		generated.P("}")
		return
	}
	generated.P("  return protocGenMcp.newHttpHandler(() => create", fileName, "MCPServer(handlers), {")
	generated.P("    resourceUrl: ", typescriptStringLiteral(oauth.GetResourceUrl()), ",")
	generated.P("    authorizationServers: ", typescriptStringArrayLiteral(oauth.GetAuthorizationServers()), ",")
	generated.P("    scopes: ", typescriptStringArrayLiteral(oauth.GetScopes()), ",")
	generated.P("    issuer: ", typescriptStringLiteral(oauth.GetIssuer()), ",")
	generated.P("    audience: ", typescriptStringLiteral(oauth.GetAudience()), ",")
	generated.P("    jwksUrl: ", typescriptStringLiteral(oauth.GetJwksUri()), ",")
	generated.P("    mcpPath: ", typescriptStringLiteral(oauth.GetMcpPath()), ",")
	generated.P("  }, verifier);")
	generated.P("}")
}

// typescriptGencodeVersion must match GENCODE_VERSION in
// runtime/typescript/src/version.ts.
const typescriptGencodeVersion = "1"

func renderTypeScriptImports(generated *protogen.GeneratedFile, model TypeScriptFileModel) {
	generated.P(`import type { Server } from "@modelcontextprotocol/sdk/server/index.js";`)
	var sdkTypes []string
	if len(model.Prompts) > 0 {
		sdkTypes = append(sdkTypes, "GetPromptResult")
	}
	if len(model.Resources) > 0 {
		sdkTypes = append(sdkTypes, "Resource", "ResourceTemplate")
	}
	if len(sdkTypes) > 0 {
		generated.P("import type { ", strings.Join(sdkTypes, ", "), " } from \"@modelcontextprotocol/sdk/types.js\";")
	}
	generated.P(`import * as protocGenMcp from "@easyp-tech/protoc-gen-mcp-runtime";`)

	imports := collectTypeScriptRenderImports(model)
	if len(imports) == 0 {
		generated.P()
		return
	}

	generated.P()
	for _, imp := range imports {
		if len(imp.TypeNames) > 0 {
			generated.P("import type { ", strings.Join(imp.TypeNames, ", "), " } from ", typescriptStringLiteral(imp.ModuleSpecifier), ";")
		}

		valueNames := append([]string{}, imp.SchemaNames...)
		valueNames = append(valueNames, imp.RegistryRefs...)
		sort.Strings(valueNames)
		if len(valueNames) > 0 {
			generated.P("import { ", strings.Join(valueNames, ", "), " } from ", typescriptStringLiteral(imp.ModuleSpecifier), ";")
		}
	}
	generated.P()
}

func collectTypeScriptRenderImports(model TypeScriptFileModel) []TypeScriptImport {
	importByProtoPath := map[string]*typeScriptImportAccumulator{}
	addRef := func(ref TypeScriptTypeRef) {
		if ref.Owner.ProtoPath == "" {
			return
		}
		acc := importByProtoPath[ref.Owner.ProtoPath]
		if acc == nil {
			acc = &typeScriptImportAccumulator{
				protoPath:               ref.Owner.ProtoPath,
				generatedFilenamePrefix: ref.Owner.GeneratedFilenamePrefix,
				moduleSpecifier:         ref.Owner.ModuleSpecifier,
				typeNames:               map[string]struct{}{},
				schemaNames:             map[string]struct{}{},
				registryRefs:            map[string]struct{}{},
			}
			importByProtoPath[ref.Owner.ProtoPath] = acc
		}
		if ref.TypeName != "" {
			acc.typeNames[ref.TypeName] = struct{}{}
		}
		if ref.SchemaName != "" {
			acc.schemaNames[ref.SchemaName] = struct{}{}
		}
		if ref.RegistryRef.RefName != "" {
			acc.registryRefs[ref.RegistryRef.RefName] = struct{}{}
		}
	}

	for _, service := range model.Services {
		for _, method := range service.Methods {
			addRef(method.Input)
			addRef(method.Output)
		}
	}
	for _, resource := range model.Resources {
		if ref, ok := model.ResourceOutputs[resource.ProtoFullName]; ok {
			addRef(ref)
		}
	}

	return flattenTypeScriptImports(importByProtoPath)
}

func renderTypeScriptService(generated *protogen.GeneratedFile, model TypeScriptFileModel, service TypeScriptServiceModel) {
	// Public declarations render as `export interface ExampleAPIToolHandler`
	// and `export function registerExampleAPITools` for Node consumers.
	generated.P("export interface ", service.HandlerName, " {")
	for _, method := range service.Methods {
		generated.P("  ", method.MethodName, "(")
		generated.P("    ctx: ToolRequestContext,")
		generated.P("    request: ", method.Input.TypeName, ",")
		generated.P("  ): ", method.Output.TypeName, " | Promise<", method.Output.TypeName, ">;")
	}
	generated.P("}")
	generated.P()

	for _, method := range service.Methods {
		generated.P("export const ", method.SchemaConst, "_INPUT_SCHEMA_JSON = ", typescriptStringLiteral(method.InputSchemaJSON), ";")
		generated.P("export const ", method.SchemaConst, "_OUTPUT_SCHEMA_JSON = ", typescriptStringLiteral(method.OutputSchemaJSON), ";")
		generated.P()
	}

	generated.P("export function ", service.RegisterName, "(")
	generated.P("  server: Server,")
	generated.P("  impl: ", service.HandlerName, ",")
	generated.P("  namespace?: string | null,")
	generated.P("): void {")
	generated.P("  protocGenMcp.addTools(server, [")
	for _, method := range service.Methods {
		renderTypeScriptRegisteredTool(generated, model, service, method)
		generated.P("    },")
	}
	generated.P("  ]);")
	generated.P("}")
}

func renderTypeScriptRegisteredTool(generated *protogen.GeneratedFile, model TypeScriptFileModel, service TypeScriptServiceModel, method TypeScriptMethodModel) {
	generated.P("    {")
	generated.P("      name: protocGenMcp.resolveToolName(namespace, ", typescriptStringLiteral(method.ToolName), ", ", typescriptStringLiteral(service.Namespace), "),")
	if method.Title != "" {
		generated.P("      title: ", typescriptStringLiteral(method.Title), ",")
	}
	if method.Description != "" {
		generated.P("      description: ", typescriptStringLiteral(method.Description), ",")
	}
	generated.P("      handler: impl.", method.MethodName, ".bind(impl),")
	generated.P("      inputSchemaJson: ", method.SchemaConst, "_INPUT_SCHEMA_JSON,")
	generated.P("      outputSchemaJson: ", method.SchemaConst, "_OUTPUT_SCHEMA_JSON,")
	generated.P("      inputSchema: ", method.Input.SchemaName, ",")
	generated.P("      outputSchema: ", method.Output.SchemaName, ",")
	generated.P("      registry: protocGenMcp.buildProtoRegistry(", model.CurrentFile.RegistryRef.RefName, ", ", method.Input.RegistryRef.RefName, ", ", method.Output.RegistryRef.RefName, "),")
	generated.P("      validateInput: protocGenMcp.compileSchema(", method.SchemaConst, "_INPUT_SCHEMA_JSON),")
	generated.P("      validateOutput: protocGenMcp.compileSchema(", method.SchemaConst, "_OUTPUT_SCHEMA_JSON),")
	renderTypeScriptAnnotations(generated, method.Annotations)
	renderTypeScriptIcons(generated, method.Icons)
	renderTypeScriptExecution(generated, method.TaskSupport)
	if meta := toolMetaJSON(method.AppUI); meta != "" {
		generated.P("      meta: JSON.parse(", typescriptStringLiteral(meta), ") as Record<string, unknown>,")
	}
	if len(method.RequiredScopes) > 0 {
		generated.P("      requiredScopes: ", typescriptStringArrayLiteral(method.RequiredScopes), ",")
	}
}

func renderTypeScriptAnnotations(generated *protogen.GeneratedFile, ann *mcpoptionsv1.ToolAnnotations) {
	if ann == nil {
		generated.P("      annotations: undefined,")
		return
	}

	generated.P("      annotations: {")
	if ann.ReadOnlyHint {
		generated.P("        readOnlyHint: true,")
	}
	if ann.DestructiveHint != nil {
		generated.P("        destructiveHint: ", typescriptBoolLiteral(ann.GetDestructiveHint()), ",")
	}
	if ann.IdempotentHint {
		generated.P("        idempotentHint: true,")
	}
	if ann.OpenWorldHint != nil {
		generated.P("        openWorldHint: ", typescriptBoolLiteral(ann.GetOpenWorldHint()), ",")
	}
	if ann.Title != "" {
		generated.P("        title: ", typescriptStringLiteral(ann.Title), ",")
	}
	generated.P("      },")
}

func renderTypeScriptIcons(generated *protogen.GeneratedFile, icons []*mcpoptionsv1.Icon) {
	generated.P("      icons: [")
	for _, icon := range icons {
		generated.P("        {")
		generated.P("          src: ", typescriptStringLiteral(icon.GetSrc()), ",")
		if icon.GetMimeType() != "" {
			generated.P("          mimeType: ", typescriptStringLiteral(icon.GetMimeType()), ",")
		}
		if len(icon.GetSizes()) > 0 {
			generated.P("          sizes: ", typescriptStringArrayLiteral(icon.GetSizes()), ",")
		}
		if icon.GetTheme() != "" {
			generated.P("          theme: ", typescriptStringLiteral(icon.GetTheme()), ",")
		}
		generated.P("        },")
	}
	generated.P("      ],")
}

func renderTypeScriptExecution(generated *protogen.GeneratedFile, taskSupport mcpoptionsv1.TaskSupport) {
	switch taskSupport {
	case mcpoptionsv1.TaskSupport_TASK_SUPPORT_OPTIONAL:
		generated.P(`      execution: { taskSupport: "optional" },`)
	case mcpoptionsv1.TaskSupport_TASK_SUPPORT_REQUIRED:
		generated.P(`      execution: { taskSupport: "required" },`)
	default:
		generated.P("      execution: undefined,")
	}
}

func typescriptOutputPathForProtoPath(protoPath string) string {
	return typescriptGeneratedFilenamePrefixForProtoPath(protoPath) + "_mcp.ts"
}

func typescriptGeneratedFilenamePrefixForProtoPath(protoPath string) string {
	prefix := strings.TrimSuffix(protoPath, path.Ext(protoPath))
	parts := strings.Split(prefix, "/")
	for i, part := range parts {
		parts[i] = strings.ReplaceAll(part, "-", "_")
	}
	return strings.Join(parts, "/")
}

func typescriptSchemaConst(service, method string) string {
	return toUpperSnakeCase(service) + "_" + toUpperSnakeCase(method)
}

func typescriptStringLiteral(value string) string {
	encoded, err := json.Marshal(value)
	if err != nil {
		panic(fmt.Sprintf("marshal TypeScript string literal: %v", err))
	}
	return string(encoded)
}

func typescriptBoolLiteral(value bool) string {
	if value {
		return "true"
	}
	return "false"
}

func typescriptStringArrayLiteral(values []string) string {
	items := make([]string, 0, len(values))
	for _, value := range values {
		items = append(items, typescriptStringLiteral(value))
	}
	return "[" + strings.Join(items, ", ") + "]"
}

func typescriptFileBaseName(protoPath string) string {
	base := strings.TrimSuffix(protoPath, ".proto")
	if idx := strings.LastIndex(base, "/"); idx >= 0 {
		base = base[idx+1:]
	}
	return base
}

func renderTypeScriptPrompts(generated *protogen.GeneratedFile, model TypeScriptFileModel) {
	fileBase := typescriptFileBaseName(model.ProtoPath)
	interfaceName := typescriptExportedIdentifier(fileBase) + "PromptHandler"
	registerName := "register" + typescriptExportedIdentifier(fileBase) + "Prompts"

	generated.P("export interface ", interfaceName, " {")
	for _, prompt := range model.Prompts {
		generated.P("  ", typescriptMethodName(prompt.ProtoName), "(args: Record<string, string>): Promise<GetPromptResult> | GetPromptResult;")
	}
	generated.P("}")
	generated.P()

	generated.P("export function ", registerName, "(server: Server, impl: ", interfaceName, ", namespace?: string): void {")
	generated.P("  const registry = protocGenMcp.installPromptHandlers(server);")
	for _, prompt := range model.Prompts {
		generated.P("  protocGenMcp.addRegisteredPrompt(registry, {")
		generated.P("    prompt: {")
		generated.P("      name: protocGenMcp.promptName(namespace, ", typescriptStringLiteral(prompt.Name), "),")
		if prompt.Title != "" {
			generated.P("      title: ", typescriptStringLiteral(prompt.Title), ",")
		}
		if prompt.Description != "" {
			generated.P("      description: ", typescriptStringLiteral(prompt.Description), ",")
		}
		generated.P("      arguments: [")
		for _, arg := range prompt.Arguments {
			generated.P("        { name: ", typescriptStringLiteral(arg.Name), ", description: ", typescriptStringLiteral(arg.Description), ", required: ", typescriptBoolLiteral(arg.Required), " },")
		}
		generated.P("      ],")
		generated.P("    },")
		generated.P("    handler: impl.", typescriptMethodName(prompt.ProtoName), ".bind(impl),")
		generated.P("  });")
	}
	generated.P("}")
}

func renderTypeScriptResources(generated *protogen.GeneratedFile, model TypeScriptFileModel) error {
	fileBase := typescriptFileBaseName(model.ProtoPath)
	interfaceName := typescriptExportedIdentifier(fileBase) + "ResourceHandler"
	registerName := "register" + typescriptExportedIdentifier(fileBase) + "Resources"

	generated.P("export interface ", interfaceName, " {")
	for _, resource := range model.Resources {
		returnType := "string | Uint8Array"
		if ref, ok := model.ResourceOutputs[resource.ProtoFullName]; ok {
			returnType = ref.TypeName
		}
		paramList := ""
		if resource.IsTemplate {
			generated.P("  list", resource.ProtoName, "s(): Promise<Resource[]> | Resource[];")
			for i, identifier := range typescriptParamIdentifiers(resource.Params) {
				if i > 0 {
					paramList += ", "
				}
				paramList += identifier + ": string"
			}
		}
		generated.P("  read", resource.ProtoName, "(", paramList, "): Promise<", returnType, "> | ", returnType, ";")
	}
	generated.P("}")
	generated.P()

	generated.P("export function ", registerName, "(server: Server, impl: ", interfaceName, ", namespace?: string): void {")
	generated.P("  const registry = protocGenMcp.installResourceHandlers(server);")
	generated.P("  const protoRegistry = protocGenMcp.buildProtoRegistry(", model.CurrentFile.RegistryRef.RefName, ");")
	for _, resource := range model.Resources {
		descriptor, err := resourceDescriptorJSON(resource)
		if err != nil {
			return err
		}
		meta := "undefined"
		if metaJSON := resourceMetaJSON(resource); metaJSON != "" {
			meta = "JSON.parse(" + typescriptStringLiteral(metaJSON) + ")"
		}
		encoding := "{ kind: \"raw\" }"
		if ref, ok := model.ResourceOutputs[resource.ProtoFullName]; ok {
			switch resourceContent(resource) {
			case resourceContentTextField:
				encoding = "{ kind: \"text_field\", schema: " + ref.SchemaName + ", field: " + typescriptStringLiteral(resource.ContentField) + " }"
			case resourceContentBlobField:
				encoding = "{ kind: \"blob_field\", schema: " + ref.SchemaName + ", field: " + typescriptStringLiteral(resource.ContentField) + " }"
			default:
				encoding = "{ kind: \"protojson\", schema: " + ref.SchemaName + ", registry: protoRegistry }"
			}
		}
		options := "{ mimeType: " + typescriptStringLiteral(resource.MIMEType) + ", meta: " + meta + ", encoding: " + encoding + " }"
		if resource.IsTemplate {
			args := make([]string, 0, len(resource.Params))
			for _, param := range resource.Params {
				args = append(args, "params["+typescriptStringLiteral(param.Name)+"] ?? \"\"")
			}
			generated.P("  protocGenMcp.addResourceTemplate(registry, {")
			generated.P("    template: protocGenMcp.resourceListing(", typescriptStringLiteral(descriptor), ", namespace, ", typescriptStringLiteral(resource.Name), ") as ResourceTemplate,")
			generated.P("    pattern: protocGenMcp.compileUriTemplate(", typescriptStringLiteral(resource.URITemplate), "),")
			generated.P("    names: ", typescriptStringArrayLiteral(resourceParamNames(resource.Params)), ",")
			generated.P("    list: async () => await impl.list", resource.ProtoName, "s(),")
			generated.P("    read: async (uri, params) => protocGenMcp.resourceContents(await impl.read", resource.ProtoName, "(", strings.Join(args, ", "), "), uri, ", options, "),")
			generated.P("  });")
		} else {
			generated.P("  protocGenMcp.addStaticResource(registry, {")
			generated.P("    resource: protocGenMcp.resourceListing(", typescriptStringLiteral(descriptor), ", namespace, ", typescriptStringLiteral(resource.Name), ") as Resource,")
			generated.P("    read: async (uri) => protocGenMcp.resourceContents(await impl.read", resource.ProtoName, "(), uri, ", options, "),")
			generated.P("  });")
		}
	}
	generated.P("}")
	return nil
}

func resourceParamNames(params []ResourceParamModel) []string {
	names := make([]string, 0, len(params))
	for _, param := range params {
		names = append(names, param.Name)
	}
	return names
}

// renderTypeScriptResourceRuntime emits the per-server resource registry and
// ports of mcpruntime.ExtractURIParams and mcpruntime.MarshalResourceContent.
