func renderTypeScriptFile(plugin *protogen.Plugin, model TypeScriptFileModel) error {
	if model.Language != LanguageTypeScript {
		return fmt.Errorf("typescript renderer requires lang=typescript, got %q", model.Language)
	}

	filename := typescriptOutputPathForProtoPath(model.ProtoPath)
	generated := plugin.NewGeneratedFile(filename, "")

	generated.P("// Code generated by protoc-gen-mcp. DO NOT EDIT.")
	generated.P("// source: ", model.ProtoPath)
	generated.P()
	renderTypeScriptImports(generated, model)
	generated.P("export type ToolRequestContext = RequestHandlerExtra<ServerRequest, ServerNotification>;")
	generated.P()
	renderTypeScriptPrivateTypes(generated)
	generated.P()

	for _, service := range model.Services {
		renderTypeScriptService(generated, model, service)
		generated.P()
	}

	renderTypeScriptPrivateRegistryHelpers(generated)
	return nil
}

func renderTypeScriptImports(generated *protogen.GeneratedFile, model TypeScriptFileModel) {
	generated.P(`import { createRegistry, fromJson, toJson } from "@bufbuild/protobuf";`)
	generated.P(`import type { DescFile, DescMessage, MessageShape } from "@bufbuild/protobuf";`)
	generated.P(`import type { JsonValue, Registry } from "@bufbuild/protobuf";`)
	generated.P(`import { Server } from "@modelcontextprotocol/sdk/server/index.js";`)
	generated.P(`import type { RequestHandlerExtra } from "@modelcontextprotocol/sdk/shared/protocol.js";`)
	generated.P(`import { CallToolRequestSchema, ErrorCode, ListToolsRequestSchema, McpError } from "@modelcontextprotocol/sdk/types.js";`)
	generated.P(`import type { CallToolRequest } from "@modelcontextprotocol/sdk/types.js";`)
	generated.P(`import type { CallToolResult, ServerNotification, ServerRequest, Tool } from "@modelcontextprotocol/sdk/types.js";`)
	generated.P(`import { Ajv2020 } from "ajv/dist/2020.js";`)
	generated.P(`import type { ValidateFunction } from "ajv/dist/2020.js";`)

	imports := collectTypeScriptRenderImports(model)
	if len(imports) == 0 {
		generated.P()
		return
	}

	generated.P()
	for _, imp := range imports {
		if len(imp.TypeNames) > 0 {
			generated.P("import type { ", strings.Join(imp.TypeNames, ", "), " } from ", typescriptStringLiteral(imp.ModuleSpecifier), ";")
		}

		valueNames := append([]string{}, imp.SchemaNames...)
		valueNames = append(valueNames, imp.RegistryRefs...)
		sort.Strings(valueNames)
		if len(valueNames) > 0 {
			generated.P("import { ", strings.Join(valueNames, ", "), " } from ", typescriptStringLiteral(imp.ModuleSpecifier), ";")
		}
	}
	generated.P()
}

func collectTypeScriptRenderImports(model TypeScriptFileModel) []TypeScriptImport {
	importByProtoPath := map[string]*typeScriptImportAccumulator{}
	addRef := func(ref TypeScriptTypeRef) {
		if ref.Owner.ProtoPath == "" {
			return
		}
		acc := importByProtoPath[ref.Owner.ProtoPath]
		if acc == nil {
			acc = &typeScriptImportAccumulator{
				protoPath:               ref.Owner.ProtoPath,
				generatedFilenamePrefix: ref.Owner.GeneratedFilenamePrefix,
				moduleSpecifier:         ref.Owner.ModuleSpecifier,
				typeNames:               map[string]struct{}{},
				schemaNames:             map[string]struct{}{},
				registryRefs:            map[string]struct{}{},
			}
			importByProtoPath[ref.Owner.ProtoPath] = acc
		}
		if ref.TypeName != "" {
			acc.typeNames[ref.TypeName] = struct{}{}
		}
		if ref.SchemaName != "" {
			acc.schemaNames[ref.SchemaName] = struct{}{}
		}
		if ref.RegistryRef.RefName != "" {
			acc.registryRefs[ref.RegistryRef.RefName] = struct{}{}
		}
	}

	for _, service := range model.Services {
		for _, method := range service.Methods {
			addRef(method.Input)
			addRef(method.Output)
		}
	}

	return flattenTypeScriptImports(importByProtoPath)
}

