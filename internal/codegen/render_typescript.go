func renderTypeScriptService(generated *protogen.GeneratedFile, model TypeScriptFileModel, service TypeScriptServiceModel) {
	// Public declarations render as `export interface ExampleAPIToolHandler`
	// and `export function registerExampleAPITools` for Node consumers.
	generated.P("export interface ", service.HandlerName, " {")
	for _, method := range service.Methods {
		generated.P("  ", method.MethodName, "(")
		generated.P("    ctx: ToolRequestContext,")
		generated.P("    request: ", method.Input.TypeName, ",")
		generated.P("  ): ", method.Output.TypeName, " | Promise<", method.Output.TypeName, ">;")
	}
	generated.P("}")
	generated.P()

	for _, method := range service.Methods {
		generated.P("export const ", method.SchemaConst, "_INPUT_SCHEMA_JSON = ", typescriptStringLiteral(method.InputSchemaJSON), ";")
		generated.P("export const ", method.SchemaConst, "_OUTPUT_SCHEMA_JSON = ", typescriptStringLiteral(method.OutputSchemaJSON), ";")
		generated.P()
	}

	generated.P("export function ", service.RegisterName, "(")
	generated.P("  server: Server,")
	generated.P("  impl: ", service.HandlerName, ",")
	generated.P("  namespace?: string | null,")
	generated.P("): void {")
	generated.P("  const registry = getToolRegistry(server);")
	generated.P("  installMcpHandlers(server, registry);")
	generated.P("  registry.tools.push(")
	for _, method := range service.Methods {
		renderTypeScriptRegisteredTool(generated, model, service, method)
		generated.P("    },")
	}
	generated.P("  );")
	generated.P("}")
}

func renderTypeScriptRegisteredTool(generated *protogen.GeneratedFile, model TypeScriptFileModel, service TypeScriptServiceModel, method TypeScriptMethodModel) {
	generated.P("    {")
	generated.P("      name: resolveToolName(namespace, ", typescriptStringLiteral(method.ToolName), ", ", typescriptStringLiteral(service.Namespace), "),")
	if method.Title != "" {
		generated.P("      title: ", typescriptStringLiteral(method.Title), ",")
	}
	if method.Description != "" {
		generated.P("      description: ", typescriptStringLiteral(method.Description), ",")
	}
	generated.P("      impl,")
	generated.P("      handler: impl.", method.MethodName, ".bind(impl),")
	generated.P("      inputSchemaJson: ", method.SchemaConst, "_INPUT_SCHEMA_JSON,")
	generated.P("      outputSchemaJson: ", method.SchemaConst, "_OUTPUT_SCHEMA_JSON,")
	generated.P("      inputSchema: ", method.Input.SchemaName, ",")
	generated.P("      outputSchema: ", method.Output.SchemaName, ",")
	generated.P("      fileRegistry: ", model.CurrentFile.RegistryRef.RefName, ",")
	generated.P("      inputFileRegistry: ", method.Input.RegistryRef.RefName, ",")
	generated.P("      outputFileRegistry: ", method.Output.RegistryRef.RefName, ",")
	generated.P("      registry: buildProtoRegistry(", model.CurrentFile.RegistryRef.RefName, ", ", method.Input.RegistryRef.RefName, ", ", method.Output.RegistryRef.RefName, "),")
	generated.P("      validateInput: compileSchema(", method.SchemaConst, "_INPUT_SCHEMA_JSON),")
	generated.P("      validateOutput: compileSchema(", method.SchemaConst, "_OUTPUT_SCHEMA_JSON),")
	renderTypeScriptAnnotations(generated, method.Annotations)
	renderTypeScriptIcons(generated, method.Icons)
	renderTypeScriptExecution(generated, method.TaskSupport)
}

func renderTypeScriptAnnotations(generated *protogen.GeneratedFile, ann *mcpoptionsv1.ToolAnnotations) {
	if ann == nil {
		generated.P("      annotations: undefined,")
		return
	}

	generated.P("      annotations: {")
	if ann.ReadOnlyHint {
		generated.P("        readOnlyHint: true,")
	}
	if ann.DestructiveHint != nil {
		generated.P("        destructiveHint: ", typescriptBoolLiteral(ann.GetDestructiveHint()), ",")
	}
	if ann.IdempotentHint {
		generated.P("        idempotentHint: true,")
	}
	if ann.OpenWorldHint != nil {
		generated.P("        openWorldHint: ", typescriptBoolLiteral(ann.GetOpenWorldHint()), ",")
	}
	if ann.Title != "" {
		generated.P("        title: ", typescriptStringLiteral(ann.Title), ",")
	}
	generated.P("      },")
}

func renderTypeScriptIcons(generated *protogen.GeneratedFile, icons []*mcpoptionsv1.Icon) {
	generated.P("      icons: [")
	for _, icon := range icons {
		generated.P("        {")
		generated.P("          src: ", typescriptStringLiteral(icon.GetSrc()), ",")
		if icon.GetMimeType() != "" {
			generated.P("          mimeType: ", typescriptStringLiteral(icon.GetMimeType()), ",")
		}
		if len(icon.GetSizes()) > 0 {
			generated.P("          sizes: ", typescriptStringArrayLiteral(icon.GetSizes()), ",")
		}
		if icon.GetTheme() != "" {
			generated.P("          theme: ", typescriptStringLiteral(icon.GetTheme()), ",")
		}
		generated.P("        },")
	}
	generated.P("      ],")
}

func renderTypeScriptExecution(generated *protogen.GeneratedFile, taskSupport mcpoptionsv1.TaskSupport) {
	switch taskSupport {
	case mcpoptionsv1.TaskSupport_TASK_SUPPORT_OPTIONAL:
		generated.P(`      execution: { taskSupport: "optional" },`)
	case mcpoptionsv1.TaskSupport_TASK_SUPPORT_REQUIRED:
		generated.P(`      execution: { taskSupport: "required" },`)
	default:
		generated.P("      execution: undefined,")
	}
}

func renderTypeScriptPrivateRegistryHelpers(generated *protogen.GeneratedFile) {
	generated.P(`const toolRegistrySymbol: unique symbol = Symbol.for("protoc-gen-mcp.typescript.toolRegistry") as never;`)
	generated.P("const jsonSchemaValidator = new Ajv2020({ strict: false, allErrors: true });")
	generated.P()
	generated.P("type ServerWithGeneratedToolRegistry = Server & {")
	generated.P("  [toolRegistrySymbol]?: ServerToolRegistry;")
	generated.P("};")
	generated.P()
	generated.P("function getToolRegistry(server: Server): ServerToolRegistry {")
	generated.P("  const holder = server as ServerWithGeneratedToolRegistry;")
	generated.P("  let registry = holder[toolRegistrySymbol];")
	generated.P("  if (registry === undefined) {")
	generated.P("    registry = { tools: [], handlersInstalled: false };")
	generated.P("    holder[toolRegistrySymbol] = registry;")
	generated.P("  }")
	generated.P("  return registry;")
	generated.P("}")
	generated.P()
	generated.P("function installMcpHandlers(server: Server, registry: ServerToolRegistry): void {")
	generated.P("  if (registry.handlersInstalled) {")
	generated.P("    return;")
	generated.P("  }")
	generated.P(`  server.assertCanSetRequestHandler("tools/list");`)
	generated.P(`  server.assertCanSetRequestHandler("tools/call");`)
	generated.P("  server.setRequestHandler(ListToolsRequestSchema, async (): Promise<{ tools: Tool[] }> => ({")
	generated.P("    tools: listRegisteredTools(registry),")
	generated.P("  }));")
	generated.P("  server.setRequestHandler(CallToolRequestSchema, async (request, extra): Promise<CallToolResult> => (")
	generated.P("    dispatchToolCall(")
	generated.P("      registry,")
	generated.P("      request,")
	generated.P("      extra as ToolRequestContext,")
	generated.P("    )")
	generated.P("  ));")
	generated.P("  registry.handlersInstalled = true;")
	generated.P("}")
	generated.P()
	generated.P("function listRegisteredTools(registry: ServerToolRegistry): Tool[] {")
	generated.P("  return registry.tools.map(buildListTool);")
	generated.P("}")
	generated.P()
	generated.P("function buildListTool(tool: RegisteredTool): Tool {")
	generated.P("  const listed = {")
	generated.P("    name: tool.name,")
	generated.P("    inputSchema: loadSchema(tool.inputSchemaJson),")
	generated.P("    outputSchema: loadSchema(tool.outputSchemaJson),")
	generated.P("  } as Tool;")
	generated.P("  if (tool.title !== undefined) {")
	generated.P("    listed.title = tool.title;")
	generated.P("  }")
	generated.P("  if (tool.description !== undefined) {")
	generated.P("    listed.description = tool.description;")
	generated.P("  }")
	generated.P("  if (tool.annotations !== undefined) {")
	generated.P("    listed.annotations = tool.annotations;")
	generated.P("  }")
	generated.P("  if (tool.icons.length > 0) {")
	generated.P("    listed.icons = tool.icons as Tool[\"icons\"];")
	generated.P("  }")
	generated.P("  if (tool.execution !== undefined) {")
	generated.P("    listed.execution = tool.execution;")
	generated.P("  }")
	generated.P("  return listed;")
	generated.P("}")
	generated.P()
	generated.P("function loadSchema(rawSchemaJson: string): Record<string, unknown> {")
	generated.P("  const parsed: unknown = JSON.parse(rawSchemaJson);")
	generated.P("  if (parsed === null || typeof parsed !== \"object\" || Array.isArray(parsed)) {")
	generated.P("    throw new Error(\"mcpruntime: generated schema JSON must be an object\");")
	generated.P("  }")
	generated.P("  return parsed as Record<string, unknown>;")
	generated.P("}")
	generated.P()
	generated.P("function compileSchema(rawSchemaJson: string): ValidateFunction {")
	generated.P("  return jsonSchemaValidator.compile(loadSchema(rawSchemaJson));")
	generated.P("}")
	generated.P()
	generated.P("function assertValid(")
	generated.P("  toolName: string,")
	generated.P(`  phase: "input" | "output",`)
	generated.P("  validate: ValidateFunction,")
	generated.P("  value: unknown,")
	generated.P("): void {")
	generated.P("  if (validate(value)) {")
	generated.P("    return;")
	generated.P("  }")
	generated.P("  const message = jsonSchemaValidator.errorsText(validate.errors);")
	generated.P(`  if (phase === "input") {`)
	generated.P("    invalidParams(toolName, message);")
	generated.P("  }")
	generated.P("  throw new Error(`mcpruntime: validate output for tool '${toolName}': ${message}`);")
	generated.P("}")
	generated.P()
	generated.P("function invalidParams(toolName: string, error: unknown): never {")
	generated.P("  throw new McpError(")
	generated.P("    ErrorCode.InvalidParams,")
	generated.P("    `invalid arguments for tool '${toolName}': ${errorMessage(error)}`,")
	generated.P("  );")
	generated.P("}")
	generated.P()
	generated.P("function toolErrorResult(error: unknown): CallToolResult {")
	generated.P("  return {")
	generated.P(`    content: [{ type: "text", text: errorMessage(error) }],`)
	generated.P("    isError: true,")
	generated.P("  };")
	generated.P("}")
	generated.P()
	generated.P("async function dispatchToolCall(")
	generated.P("  registry: ServerToolRegistry,")
	generated.P("  request: CallToolRequest,")
	generated.P("  extra: ToolRequestContext,")
	generated.P("): Promise<CallToolResult> {")
	generated.P("  const toolName = request.params.name;")
	generated.P("  const tool = registry.tools.find((candidate) => candidate.name === toolName);")
	generated.P("  if (tool === undefined) {")
	generated.P("    throw new McpError(ErrorCode.InvalidParams, `unknown tool '${toolName}'`);")
	generated.P("  }")
	generated.P("  const args = (request.params.arguments ?? {}) as JsonValue;")
	generated.P("  assertValid(tool.name, \"input\", tool.validateInput, args);")
	generated.P()
	generated.P("  let parsedRequest: MessageShape<typeof tool.inputSchema>;")
	generated.P("  try {")
	generated.P("    parsedRequest = fromJson(tool.inputSchema, args, { registry: tool.registry });")
	generated.P("  } catch (error) {")
	generated.P("    invalidParams(tool.name, error);")
	generated.P("  }")
	generated.P()
	generated.P("  let response: unknown;")
	generated.P("  try {")
	generated.P("    response = await tool.handler(extra, parsedRequest as never);")
	generated.P("  } catch (error) {")
	generated.P("    return toolErrorResult(error);")
	generated.P("  }")
	generated.P()
	generated.P("  let payload: JsonValue;")
	generated.P("  try {")
	generated.P("    payload = toJson(tool.outputSchema, response as MessageShape<typeof tool.outputSchema>, {")
	generated.P("      alwaysEmitImplicit: true,")
	generated.P("      registry: tool.registry,")
	generated.P("    }) as JsonValue;")
	generated.P("  } catch (error) {")
	generated.P("    throw new Error(`mcpruntime: marshal output for tool '${tool.name}': ${errorMessage(error)}`);")
	generated.P("  }")
	generated.P("  const structuredContent = assertStructuredContent(tool.name, payload);")
	generated.P("  assertValid(tool.name, \"output\", tool.validateOutput, structuredContent);")
	generated.P("  return {")
	generated.P(`    content: [{ type: "text", text: JSON.stringify(structuredContent) }],`)
	generated.P("    structuredContent,")
	generated.P("  };")
	generated.P("}")
	generated.P()
	generated.P("function assertStructuredContent(toolName: string, payload: JsonValue): Record<string, unknown> {")
	generated.P("  if (payload === null || typeof payload !== \"object\" || Array.isArray(payload)) {")
	generated.P("    throw new Error(`mcpruntime: marshal output for tool '${toolName}': generated output must be a JSON object`);")
	generated.P("  }")
	generated.P("  return payload as Record<string, unknown>;")
	generated.P("}")
	generated.P()
	generated.P("function errorMessage(error: unknown): string {")
	generated.P(`  if (error instanceof Error && error.message !== "") {`)
	generated.P("    return error.message;")
	generated.P("  }")
	generated.P("  return String(error);")
	generated.P("}")
	generated.P()
	generated.P("function buildProtoRegistry(...fileRegistries: DescFile[]): Registry {")
	generated.P("  const collected: DescFile[] = [];")
	generated.P("  const seen = new Set<string>();")
	generated.P("  const visit = (file: DescFile): void => {")
	generated.P("    const key = file.proto.name || file.name;")
	generated.P("    if (seen.has(key)) {")
	generated.P("      return;")
	generated.P("    }")
	generated.P("    seen.add(key);")
	generated.P("    collected.push(file);")
	generated.P("    for (const dependency of file.dependencies) {")
	generated.P("      visit(dependency);")
	generated.P("    }")
	generated.P("  };")
	generated.P("  for (const file of fileRegistries) {")
	generated.P("    visit(file);")
	generated.P("  }")
	generated.P("  return createRegistry(...collected);")
	generated.P("}")
	generated.P()
	generated.P("function resolveToolName(")
	generated.P("  namespace: string | null | undefined,")
	generated.P("  defaultName: string,")
	generated.P("  defaultNamespace: string,")
	generated.P("): string {")
	generated.P("  const resolvedNamespace = normalizeToolSegment(")
	generated.P("    namespace === null || namespace === undefined ? defaultNamespace : namespace,")
	generated.P("  );")
	generated.P("  const resolvedName = normalizeToolSegment(defaultName);")
	generated.P("  if (resolvedNamespace === \"\") {")
	generated.P("    return resolvedName;")
	generated.P("  }")
	generated.P("  if (resolvedName === \"\") {")
	generated.P("    return resolvedNamespace;")
	generated.P("  }")
	generated.P("  return `${resolvedNamespace}_${resolvedName}`;")
	generated.P("}")
	generated.P()
	generated.P("function normalizeToolSegment(segment: string | null | undefined): string {")
	generated.P("  if (segment === null || segment === undefined) {")
	generated.P("    return \"\";")
	generated.P("  }")
	generated.P("  return segment.trim().replace(/[.]+/g, \"_\").replace(/_+/g, \"_\").replace(/^_+|_+$/g, \"\");")
	generated.P("}")
}

func typescriptOutputPathForProtoPath(protoPath string) string {
	return typescriptGeneratedFilenamePrefixForProtoPath(protoPath) + "_mcp.ts"
}

func typescriptGeneratedFilenamePrefixForProtoPath(protoPath string) string {
	prefix := strings.TrimSuffix(protoPath, path.Ext(protoPath))
	parts := strings.Split(prefix, "/")
	for i, part := range parts {
		parts[i] = strings.ReplaceAll(part, "-", "_")
	}
	return strings.Join(parts, "/")
}

func typescriptSchemaConst(service, method string) string {
	return toUpperSnakeCase(service) + "_" + toUpperSnakeCase(method)
}

func typescriptStringLiteral(value string) string {
	encoded, err := json.Marshal(value)
	if err != nil {
		panic(fmt.Sprintf("marshal TypeScript string literal: %v", err))
	}
	return string(encoded)
}

func typescriptBoolLiteral(value bool) string {
	if value {
		return "true"
	}
	return "false"
}

func typescriptStringArrayLiteral(values []string) string {
	items := make([]string, 0, len(values))
	for _, value := range values {
		items = append(items, typescriptStringLiteral(value))
	}
	return "[" + strings.Join(items, ", ") + "]"
}

func typescriptFileBaseName(protoPath string) string {
	base := strings.TrimSuffix(protoPath, ".proto")
	if idx := strings.LastIndex(base, "/"); idx >= 0 {
		base = base[idx+1:]
	}
	return base
}

func renderTypeScriptPrompts(generated *protogen.GeneratedFile, model TypeScriptFileModel) {
	fileBase := typescriptFileBaseName(model.ProtoPath)
	interfaceName := typescriptExportedIdentifier(fileBase) + "PromptHandler"
	registerName := "register" + typescriptExportedIdentifier(fileBase) + "Prompts"

	generated.P("export interface ", interfaceName, " {")
	for _, prompt := range model.Prompts {
		generated.P("  ", typescriptMethodName(prompt.ProtoName), "(args: Record<string, string>): Promise<GetPromptResult> | GetPromptResult;")
	}
	generated.P("}")
	generated.P()

	generated.P("export function ", registerName, "(server: Server, impl: ", interfaceName, ", namespace?: string): void {")
	generated.P("  const registry = installPromptHandlers(server);")
	for _, prompt := range model.Prompts {
		generated.P("  addRegisteredPrompt(registry, {")
		generated.P("    prompt: {")
		generated.P("      name: promptName(namespace, ", typescriptStringLiteral(prompt.Name), "),")
		if prompt.Title != "" {
			generated.P("      title: ", typescriptStringLiteral(prompt.Title), ",")
		}
		if prompt.Description != "" {
			generated.P("      description: ", typescriptStringLiteral(prompt.Description), ",")
		}
		generated.P("      arguments: [")
		for _, arg := range prompt.Arguments {
			generated.P("        { name: ", typescriptStringLiteral(arg.Name), ", description: ", typescriptStringLiteral(arg.Description), ", required: ", typescriptBoolLiteral(arg.Required), " },")
		}
		generated.P("      ],")
		generated.P("    },")
		generated.P("    handler: impl.", typescriptMethodName(prompt.ProtoName), ".bind(impl),")
		generated.P("  });")
	}
	generated.P("}")
	generated.P()

	generated.P("type RegisteredPrompt = {")
	generated.P("  prompt: Prompt & { arguments: PromptArgument[] };")
	generated.P("  handler: (args: Record<string, string>) => Promise<GetPromptResult> | GetPromptResult;")
	generated.P("};")
	generated.P()
	generated.P("type ServerPromptRegistry = Map<string, RegisteredPrompt>;")
	generated.P()
	generated.P(`const promptRegistrySymbol: unique symbol = Symbol.for("protoc-gen-mcp.typescript.promptRegistry") as never;`)
	generated.P()
	generated.P("function installPromptHandlers(server: Server): ServerPromptRegistry {")
	generated.P("  const holder = server as Server & { [promptRegistrySymbol]?: ServerPromptRegistry };")
	generated.P("  const existing = holder[promptRegistrySymbol];")
	generated.P("  if (existing !== undefined) {")
	generated.P("    return existing;")
	generated.P("  }")
	generated.P("  const registry: ServerPromptRegistry = new Map();")
	generated.P("  holder[promptRegistrySymbol] = registry;")
	generated.P("  server.registerCapabilities({ prompts: {} });")
	generated.P("  server.setRequestHandler(ListPromptsRequestSchema, async () => ({")
	generated.P("    prompts: [...registry.values()].map((entry) => entry.prompt),")
	generated.P("  }));")
	generated.P("  server.setRequestHandler(GetPromptRequestSchema, async (request) => {")
	generated.P("    const requestedName = request.params.name;")
	generated.P("    const entry = registry.get(requestedName);")
	generated.P("    if (entry === undefined) {")
	generated.P("      throw new McpError(ErrorCode.InvalidParams, `unknown prompt '${requestedName}'`);")
	generated.P("    }")
	generated.P("    const args: Record<string, string> = { ...(request.params.arguments ?? {}) };")
	generated.P("    for (const arg of entry.prompt.arguments) {")
	generated.P("      if (arg.required && !(arg.name in args)) {")
	generated.P("        throw new McpError(ErrorCode.InvalidParams, `missing required prompt argument: ${arg.name}`);")
	generated.P("      }")
	generated.P("    }")
	generated.P("    return await entry.handler(args);")
	generated.P("  });")
	generated.P("  return registry;")
	generated.P("}")
	generated.P()
	generated.P("function addRegisteredPrompt(registry: ServerPromptRegistry, entry: RegisteredPrompt): void {")
	generated.P("  if (registry.has(entry.prompt.name)) {")
	generated.P("    throw new Error(`duplicate prompt registration: ${entry.prompt.name}`);")
	generated.P("  }")
	generated.P("  registry.set(entry.prompt.name, entry);")
	generated.P("}")
	generated.P()
	generated.P("function promptName(namespace: string | undefined, promptName: string): string {")
	generated.P("  const normalizedNamespace = normalizeToolSegment(namespace ?? \"\");")
	generated.P("  const normalizedPromptName = normalizeToolSegment(promptName);")
	generated.P("  if (normalizedNamespace === \"\") {")
	generated.P("    return normalizedPromptName;")
	generated.P("  }")
	generated.P("  if (normalizedPromptName === \"\") {")
	generated.P("    return normalizedNamespace;")
	generated.P("  }")
	generated.P("  return `${normalizedNamespace}_${normalizedPromptName}`;")
	generated.P("}")
}

func renderTypeScriptResources(generated *protogen.GeneratedFile, model TypeScriptFileModel) error {
	fileBase := typescriptFileBaseName(model.ProtoPath)
	interfaceName := typescriptExportedIdentifier(fileBase) + "ResourceHandler"
	registerName := "register" + typescriptExportedIdentifier(fileBase) + "Resources"

	generated.P("export interface ", interfaceName, " {")
	for _, resource := range model.Resources {
		returnType := "string | Uint8Array"
		if ref, ok := model.ResourceOutputs[resource.ProtoFullName]; ok {
			returnType = ref.TypeName
		}
		paramList := ""
		if resource.IsTemplate {
			generated.P("  list", resource.ProtoName, "s(): Promise<Resource[]> | Resource[];")
			for i, identifier := range typescriptParamIdentifiers(resource.Params) {
				if i > 0 {
					paramList += ", "
				}
				paramList += identifier + ": string"
			}
		}
		generated.P("  read", resource.ProtoName, "(", paramList, "): Promise<", returnType, "> | ", returnType, ";")
	}
	generated.P("}")
	generated.P()

	generated.P("export function ", registerName, "(server: Server, impl: ", interfaceName, ", namespace?: string): void {")
	generated.P("  const registry = installResourceHandlers(server);")
	generated.P("  const protoRegistry = buildProtoRegistry(", model.CurrentFile.RegistryRef.RefName, ");")
	for _, resource := range model.Resources {
		descriptor, err := resourceDescriptorJSON(resource)
		if err != nil {
			return err
		}
		meta := "undefined"
		if metaJSON := resourceMetaJSON(resource); metaJSON != "" {
			meta = "JSON.parse(" + typescriptStringLiteral(metaJSON) + ")"
		}
		encoding := "{ kind: \"raw\" }"
		if ref, ok := model.ResourceOutputs[resource.ProtoFullName]; ok {
			switch resourceContent(resource) {
			case resourceContentTextField:
				encoding = "{ kind: \"text_field\", schema: " + ref.SchemaName + ", field: " + typescriptStringLiteral(resource.ContentField) + " }"
			case resourceContentBlobField:
				encoding = "{ kind: \"blob_field\", schema: " + ref.SchemaName + ", field: " + typescriptStringLiteral(resource.ContentField) + " }"
			default:
				encoding = "{ kind: \"protojson\", schema: " + ref.SchemaName + ", registry: protoRegistry }"
			}
		}
		options := "{ mimeType: " + typescriptStringLiteral(resource.MIMEType) + ", meta: " + meta + ", encoding: " + encoding + " }"
		if resource.IsTemplate {
			args := make([]string, 0, len(resource.Params))
			for _, param := range resource.Params {
				args = append(args, "params["+typescriptStringLiteral(param.Name)+"] ?? \"\"")
			}
			generated.P("  addResourceTemplate(registry, {")
			generated.P("    template: resourceListing(", typescriptStringLiteral(descriptor), ", namespace, ", typescriptStringLiteral(resource.Name), ") as ResourceTemplate,")
			generated.P("    pattern: compileUriTemplate(", typescriptStringLiteral(resource.URITemplate), "),")
			generated.P("    names: ", typescriptStringArrayLiteral(resourceParamNames(resource.Params)), ",")
			generated.P("    list: async () => await impl.list", resource.ProtoName, "s(),")
			generated.P("    read: async (uri, params) => resourceContents(await impl.read", resource.ProtoName, "(", strings.Join(args, ", "), "), uri, ", options, "),")
			generated.P("  });")
		} else {
			generated.P("  addStaticResource(registry, {")
			generated.P("    resource: resourceListing(", typescriptStringLiteral(descriptor), ", namespace, ", typescriptStringLiteral(resource.Name), ") as Resource,")
			generated.P("    read: async (uri) => resourceContents(await impl.read", resource.ProtoName, "(), uri, ", options, "),")
			generated.P("  });")
		}
	}
	generated.P("}")
	generated.P()
	renderTypeScriptResourceRuntime(generated)
	return nil
}

func resourceParamNames(params []ResourceParamModel) []string {
	names := make([]string, 0, len(params))
	for _, param := range params {
		names = append(names, param.Name)
	}
	return names
}

// renderTypeScriptResourceRuntime emits the per-server resource registry and
// ports of mcpruntime.ExtractURIParams and mcpruntime.MarshalResourceContent.
func renderTypeScriptResourceRuntime(generated *protogen.GeneratedFile) {
	generated.P("type ResourceEncoding =")
	generated.P(`  | { kind: "protojson"; schema: DescMessage; registry: Registry }`)
	generated.P(`  | { kind: "text_field" | "blob_field"; schema: DescMessage; field: string }`)
	generated.P(`  | { kind: "raw" };`)
	generated.P()
	generated.P("type ResourceContentOptions = {")
	generated.P("  mimeType: string;")
	generated.P("  meta: Record<string, unknown> | undefined;")
	generated.P("  encoding: ResourceEncoding;")
	generated.P("};")
	generated.P()
	generated.P("type ResourceContents = ReadResourceResult[\"contents\"][number];")
	generated.P()
	generated.P("type RegisteredStaticResource = {")
	generated.P("  resource: Resource;")
	generated.P("  read: (uri: string) => Promise<ResourceContents>;")
	generated.P("};")
	generated.P()
	generated.P("type RegisteredResourceTemplate = {")
	generated.P("  template: ResourceTemplate;")
	generated.P("  pattern: RegExp;")
	generated.P("  names: string[];")
	generated.P("  list: () => Promise<Resource[]>;")
	generated.P("  read: (uri: string, params: Record<string, string>) => Promise<ResourceContents>;")
	generated.P("};")
	generated.P()
	generated.P("type ServerResourceRegistry = {")
	generated.P("  statics: Map<string, RegisteredStaticResource>;")
	generated.P("  templates: RegisteredResourceTemplate[];")
	generated.P("};")
	generated.P()
	generated.P(`const resourceRegistrySymbol: unique symbol = Symbol.for("protoc-gen-mcp.typescript.resourceRegistry") as never;`)
	generated.P()
	generated.P("function installResourceHandlers(server: Server): ServerResourceRegistry {")
	generated.P("  const holder = server as Server & { [resourceRegistrySymbol]?: ServerResourceRegistry };")
	generated.P("  const existing = holder[resourceRegistrySymbol];")
	generated.P("  if (existing !== undefined) {")
	generated.P("    return existing;")
	generated.P("  }")
	generated.P("  const registry: ServerResourceRegistry = { statics: new Map(), templates: [] };")
	generated.P("  holder[resourceRegistrySymbol] = registry;")
	generated.P("  server.registerCapabilities({ resources: {} });")
	generated.P("  server.setRequestHandler(ListResourcesRequestSchema, async () => {")
	generated.P("    const resources: Resource[] = [...registry.statics.values()].map((entry) => entry.resource);")
	generated.P("    for (const entry of registry.templates) {")
	generated.P("      resources.push(...(await entry.list()));")
	generated.P("    }")
	generated.P("    return { resources };")
	generated.P("  });")
	generated.P("  server.setRequestHandler(ListResourceTemplatesRequestSchema, async () => ({")
	generated.P("    resourceTemplates: registry.templates.map((entry) => entry.template),")
	generated.P("  }));")
	generated.P("  server.setRequestHandler(ReadResourceRequestSchema, async (request): Promise<ReadResourceResult> => {")
	generated.P("    const uri = request.params.uri;")
	generated.P("    const entry = registry.statics.get(uri);")
	generated.P("    if (entry !== undefined) {")
	generated.P("      return { contents: [await entry.read(uri)] };")
	generated.P("    }")
	generated.P("    for (const template of registry.templates) {")
	generated.P("      const params = matchUriTemplate(template, uri);")
	generated.P("      if (params !== undefined) {")
	generated.P("        return { contents: [await template.read(uri, params)] };")
	generated.P("      }")
	generated.P("    }")
	generated.P("    throw new McpError(ErrorCode.InvalidParams, \"Resource not found\", { uri });")
	generated.P("  });")
	generated.P("  return registry;")
	generated.P("}")
	generated.P()
	generated.P("function addStaticResource(registry: ServerResourceRegistry, entry: RegisteredStaticResource): void {")
	generated.P("  if (registry.statics.has(entry.resource.uri)) {")
	generated.P("    throw new Error(`duplicate resource registration: ${entry.resource.uri}`);")
	generated.P("  }")
	generated.P("  registry.statics.set(entry.resource.uri, entry);")
	generated.P("}")
	generated.P()
	generated.P("function addResourceTemplate(registry: ServerResourceRegistry, entry: RegisteredResourceTemplate): void {")
	generated.P("  if (registry.templates.some((existing) => existing.template.uriTemplate === entry.template.uriTemplate)) {")
	generated.P("    throw new Error(`duplicate resource template registration: ${entry.template.uriTemplate}`);")
	generated.P("  }")
	generated.P("  registry.templates.push(entry);")
	generated.P("}")
	generated.P()
	generated.P("function resourceListing(descriptorJson: string, namespace: string | undefined, name: string): Record<string, unknown> {")
	generated.P("  const descriptor = JSON.parse(descriptorJson) as Record<string, unknown>;")
	generated.P("  descriptor.name = namespace ? `${namespace}_${name}` : name;")
	generated.P("  return descriptor;")
	generated.P("}")
	generated.P()
	generated.P("function compileUriTemplate(uriTemplate: string): RegExp {")
	generated.P("  const parts = uriTemplate.split(/\\{[a-zA-Z_][a-zA-Z0-9_]*\\}/);")
	generated.P("  const escaped = parts.map((part) => part.replace(/[.*+?^${}()|[\\]\\\\]/g, \"\\\\$&\"));")
	generated.P("  return new RegExp(`^${escaped.join(\"([^/]+)\")}$`);")
	generated.P("}")
	generated.P()
	generated.P("function matchUriTemplate(entry: RegisteredResourceTemplate, uri: string): Record<string, string> | undefined {")
	generated.P("  const match = entry.pattern.exec(uri);")
	generated.P("  if (match === null) {")
	generated.P("    return undefined;")
	generated.P("  }")
	generated.P("  const params: Record<string, string> = {};")
	generated.P("  entry.names.forEach((name, index) => {")
	generated.P("    const raw = match[index + 1] ?? \"\";")
	generated.P("    let value: string;")
	generated.P("    try {")
	generated.P("      value = decodeURIComponent(raw);")
	generated.P("    } catch (error) {")
	generated.P("      throw new McpError(ErrorCode.InvalidParams, `mcpruntime: parameter '${name}' in uri '${uri}': ${errorMessage(error)}`, { uri });")
	generated.P("    }")
	generated.P("    if (value === \"\") {")
	generated.P("      throw new McpError(ErrorCode.InvalidParams, `mcpruntime: parameter '${name}' has empty value in uri '${uri}'`, { uri });")
	generated.P("    }")
	generated.P("    params[name] = value;")
	generated.P("  });")
	generated.P("  return params;")
	generated.P("}")
	generated.P()
	generated.P("function resourceContents(value: unknown, uri: string, options: ResourceContentOptions): ResourceContents {")
	generated.P("  if (value === null || value === undefined) {")
	generated.P("    throw new Error(`mcpruntime: resource '${uri}' handler returned no value`);")
	generated.P("  }")
	generated.P("  const base: { uri: string; mimeType: string; _meta?: Record<string, unknown> } = { uri, mimeType: options.mimeType };")
	generated.P("  if (options.meta !== undefined) {")
	generated.P("    base._meta = options.meta;")
	generated.P("  }")
	generated.P("  const encoding = options.encoding;")
	generated.P("  switch (encoding.kind) {")
	generated.P(`    case "raw":`)
	generated.P("      if (typeof value === \"string\") {")
	generated.P("        return { ...base, text: value };")
	generated.P("      }")
	generated.P("      if (value instanceof Uint8Array) {")
	generated.P("        return { ...base, blob: base64Encode(value) };")
	generated.P("      }")
	generated.P("      throw new Error(`mcpruntime: resource '${uri}' handler must return a string or Uint8Array`);")
	generated.P(`    case "protojson":`)
	generated.P("      return {")
	generated.P("        ...base,")
	generated.P("        text: JSON.stringify(toJson(encoding.schema, value as MessageShape<typeof encoding.schema>, {")
	generated.P("          alwaysEmitImplicit: true,")
	generated.P("          registry: encoding.registry,")
	generated.P("        })),")
	generated.P("      };")
	generated.P("    default: {")
	generated.P("      const field = encoding.schema.fields.find((candidate) => candidate.name === encoding.field);")
	generated.P("      if (field === undefined) {")
	generated.P("        throw new Error(`mcpruntime: resource content field '${encoding.field}' not found`);")
	generated.P("      }")
	generated.P("      const raw = (value as Record<string, unknown>)[field.localName];")
	generated.P(`      if (encoding.kind === "text_field") {`)
	generated.P("        return { ...base, text: typeof raw === \"string\" ? raw : \"\" };")
	generated.P("      }")
	generated.P("      return { ...base, blob: base64Encode(raw instanceof Uint8Array ? raw : new Uint8Array()) };")
	generated.P("    }")
	generated.P("  }")
	generated.P("}")
}
