package codegen

import (
	"fmt"
	"strings"

	"google.golang.org/protobuf/compiler/protogen"
)

// swiftGencodeVersion must match GENCODE_VERSION in
// runtime/swift/Sources/ProtocGenMCPRuntime/Version.swift.
const swiftGencodeVersion = "1"

func renderSwiftFile(plugin *protogen.Plugin, model SwiftFileModel) error {
	generated := plugin.NewGeneratedFile(swiftOutputPath(model.GeneratedFilenamePrefix), "")
	generated.P("// Code generated by protoc-gen-mcp. DO NOT EDIT.")
	generated.P("// source: ", model.ProtoPath)
	generated.P()
	generated.P("import Foundation")
	generated.P("import MCP")
	if model.Factory.HTTP {
		generated.P("import ProtocGenMCPHTTP")
	}
	generated.P("import ProtocGenMCPRuntime")
	generated.P("import SwiftProtobuf")

	for _, service := range model.Services {
		renderSwiftService(generated, model, service)
	}
	if len(model.Prompts) > 0 {
		if err := renderSwiftPrompts(generated, model); err != nil {
			return err
		}
	}
	if len(model.Resources) > 0 {
		renderSwiftResources(generated, model)
	}
	if model.Factory.Emit {
		renderSwiftServerFactory(generated, model)
	}
	if len(model.Services) > 0 || len(model.Resources) > 0 {
		renderSwiftShapes(generated, model)
	}
	if len(model.MessageTypes) > 0 {
		generated.P()
		generated.P("/// Messages of ", model.ProtoPath, ", resolvable inside google.protobuf.Any.")
		generated.P("private let ", swiftTypesName(model), ": Void = registerAnyMessageTypes([")
		for _, name := range model.MessageTypes {
			generated.P("    ", name, ".self,")
		}
		generated.P("])")
	}
	return nil
}

func swiftTypesName(model SwiftFileModel) string {
	return jvmLowerCamelIdentifier(model.FileIdentifier) + "AnyTypes"
}

// renderSwiftRegistrationPreamble checks the runtime API and registers the
// file's messages for google.protobuf.Any once.
func renderSwiftRegistrationPreamble(generated *protogen.GeneratedFile, model SwiftFileModel) {
	generated.P("    try checkGencodeVersion(", swiftGencodeVersion, ")")
	if len(model.MessageTypes) > 0 {
		generated.P("    _ = ", swiftTypesName(model))
	}
}

func swiftShapesName(model SwiftFileModel) string {
	return jvmLowerCamelIdentifier(model.FileIdentifier) + "ProtoJSONShapes"
}

func renderSwiftService(generated *protogen.GeneratedFile, model SwiftFileModel, service SwiftServiceModel) {
	generated.P()
	generated.P("/// Business handlers for the ", service.ProtoName, " tools.")
	generated.P("protocol ", service.HandlerName, ": Sendable {")
	for _, method := range service.Methods {
		generated.P("    func ", method.FuncName, "(_ context: ToolContext, _ request: ", method.InputType, ") async throws -> ", method.OutputType)
	}
	generated.P("}")
	generated.P()
	generated.P("/// Registers the ", service.ProtoName, " tools on server. namespace replaces the proto-declared one.")
	generated.P("func ", service.RegisterName, "(_ server: Server, _ impl: some ", service.HandlerName, ", namespace: String? = nil) async throws {")
	renderSwiftRegistrationPreamble(generated, model)
	generated.P("    try await addTools(server, [")
	for _, method := range service.Methods {
		generated.P("        try RegisteredTool(")
		generated.P("            name: toolName(namespace, ", swiftStringLiteral(method.Method.Name), ", defaultNamespace: ", swiftStringLiteral(service.Namespace), "),")
		generated.P("            descriptorJSON: ", swiftStringLiteral(method.DescriptorJSON), ",")
		generated.P("            inputSchemaJSON: ", method.SchemaConst, "InputSchema,")
		generated.P("            outputSchemaJSON: ", method.SchemaConst, "OutputSchema,")
		if len(method.Method.RequiredScopes) > 0 {
			generated.P("            requiredScopes: ", swiftStringArrayLiteral(method.Method.RequiredScopes), ",")
		}
		generated.P("            request: ", method.InputType, ".self,")
		generated.P("            outputType: ", swiftStringLiteral(method.OutputFullName), ",")
		generated.P("            shapes: ", swiftShapesName(model), ",")
		generated.P("            handler: { context, request in try await impl.", method.FuncName, "(context, request) }")
		generated.P("        ),")
	}
	generated.P("    ])")
	generated.P("}")
	for _, method := range service.Methods {
		generated.P()
		generated.P("private let ", method.SchemaConst, "InputSchema = ", swiftStringLiteral(method.Method.InputSchemaJSON))
		generated.P()
		generated.P("private let ", method.SchemaConst, "OutputSchema = ", swiftStringLiteral(method.Method.OutputSchemaJSON))
	}
}

func renderSwiftPrompts(generated *protogen.GeneratedFile, model SwiftFileModel) error {
	handlerName := model.FileIdentifier + "PromptHandler"
	generated.P()
	generated.P("/// Business handlers for the prompts of ", model.ProtoPath, ".")
	generated.P("protocol ", handlerName, ": Sendable {")
	for _, prompt := range model.Prompts {
		generated.P("    func ", swiftMethodName(prompt.ProtoName), "(_ arguments: [String: String]) async throws -> GetPrompt.Result")
	}
	generated.P("}")
	generated.P()
	generated.P("/// Registers the prompts of ", model.ProtoPath, " on server.")
	generated.P("func register", model.FileIdentifier, "Prompts(_ server: Server, _ impl: some ", handlerName, ", namespace: String? = nil) async throws {")
	renderSwiftRegistrationPreamble(generated, model)
	generated.P("    try await addPrompts(server, [")
	for _, prompt := range model.Prompts {
		descriptorJSON, err := swiftPromptDescriptorJSON(prompt)
		if err != nil {
			return err
		}
		generated.P("        try RegisteredPrompt(")
		generated.P("            name: promptName(namespace, ", swiftStringLiteral(prompt.Name), "),")
		generated.P("            descriptorJSON: ", swiftStringLiteral(descriptorJSON), ",")
		generated.P("            handler: { arguments in try await impl.", swiftMethodName(prompt.ProtoName), "(arguments) }")
		generated.P("        ),")
	}
	generated.P("    ])")
	generated.P("}")
	return nil
}

func renderSwiftResources(generated *protogen.GeneratedFile, model SwiftFileModel) {
	handlerName := model.FileIdentifier + "ResourceHandler"
	generated.P()
	generated.P("/// Business handlers for the resources of ", model.ProtoPath, ".")
	generated.P("protocol ", handlerName, ": Sendable {")
	for _, resource := range model.Resources {
		returnType := "RawResourceBody"
		if resource.Kind != resourceContentSourceFile {
			returnType = resource.TypeName
		}
		if resource.Resource.IsTemplate {
			generated.P("    func list", jvmExportedIdentifier(resource.Resource.ProtoName), "s() async throws -> [Resource]")
		}
		generated.P("    func read", jvmExportedIdentifier(resource.Resource.ProtoName), "(", swiftReadParams(resource), ") async throws -> ", returnType)
	}
	generated.P("}")
	generated.P()
	generated.P("/// Registers the resources of ", model.ProtoPath, " on server.")
	generated.P("func register", model.FileIdentifier, "Resources(_ server: Server, _ impl: some ", handlerName, ", namespace: String? = nil) async throws {")
	renderSwiftRegistrationPreamble(generated, model)
	generated.P("    try await addResources(")
	generated.P("        server,")
	generated.P("        statics: [")
	for _, resource := range model.Resources {
		if resource.Resource.IsTemplate {
			continue
		}
		generated.P("            RegisteredStaticResource(")
		generated.P("                resource: try resourceListing(Resource.self, ", swiftStringLiteral(resource.DescriptorJSON), ", namespace: namespace, name: ", swiftStringLiteral(resource.Resource.Name), "),")
		generated.P("                read: { uri in ", swiftResourceContents(model, resource, "try await impl.read"+jvmExportedIdentifier(resource.Resource.ProtoName)+"()"), " }")
		generated.P("            ),")
	}
	generated.P("        ],")
	generated.P("        templates: [")
	for _, resource := range model.Resources {
		if !resource.Resource.IsTemplate {
			continue
		}
		args := make([]string, 0, len(resource.Params))
		for i, param := range resource.Params {
			args = append(args, param+": params["+swiftStringLiteral(resource.Resource.Params[i].Name)+"] ?? \"\"")
		}
		call := "try await impl.read" + jvmExportedIdentifier(resource.Resource.ProtoName) + "(" + strings.Join(args, ", ") + ")"
		generated.P("            try RegisteredResourceTemplate(")
		generated.P("                template: try resourceListing(Resource.Template.self, ", swiftStringLiteral(resource.DescriptorJSON), ", namespace: namespace, name: ", swiftStringLiteral(resource.Resource.Name), "),")
		generated.P("                list: { try await impl.list", jvmExportedIdentifier(resource.Resource.ProtoName), "s() },")
		generated.P("                read: { uri, params in ", swiftResourceContents(model, resource, call), " }")
		generated.P("            ),")
	}
	generated.P("        ]")
	generated.P("    )")
	generated.P("}")
}

func swiftReadParams(resource SwiftResourceModel) string {
	params := make([]string, 0, len(resource.Params))
	for _, param := range resource.Params {
		params = append(params, param+": String")
	}
	return strings.Join(params, ", ")
}

func swiftResourceContents(model SwiftFileModel, resource SwiftResourceModel, call string) string {
	meta := "nil"
	if metaJSON := resourceMetaJSON(resource.Resource); metaJSON != "" {
		meta = swiftStringLiteral(metaJSON)
	}
	mimeType := swiftStringLiteral(resource.Resource.MIMEType)
	var encoding string
	switch resource.Kind {
	case resourceContentSourceFile:
		return fmt.Sprintf("try resourceContents(%s, uri: uri, mimeType: %s, metaJSON: %s)", call, mimeType, meta)
	case resourceContentTextField:
		encoding = ".textField(" + swiftStringLiteral(resource.JSONField) + ")"
	case resourceContentBlobField:
		encoding = ".blobField(" + swiftStringLiteral(resource.JSONField) + ")"
	default:
		encoding = ".protojson(type: " + swiftStringLiteral(resource.Resource.Output.ProtoFullName) + ", shapes: " + swiftShapesName(model) + ")"
	}
	return fmt.Sprintf("try resourceContents(%s, uri: uri, mimeType: %s, metaJSON: %s, encoding: %s)", call, mimeType, meta, encoding)
}

func renderSwiftServerFactory(generated *protogen.GeneratedFile, model SwiftFileModel) {
	fileName := model.FileIdentifier
	type component struct{ property, protocol, register string }
	var components []component
	for _, service := range model.Services {
		components = append(components, component{jvmLowerCamelIdentifier(service.ProtoName), service.HandlerName, service.RegisterName})
	}
	if len(model.Prompts) > 0 {
		components = append(components, component{"prompts", fileName + "PromptHandler", "register" + fileName + "Prompts"})
	}
	if len(model.Resources) > 0 {
		components = append(components, component{"resources", fileName + "ResourceHandler", "register" + fileName + "Resources"})
	}
	generated.P()
	generated.P("/// Business handlers for every MCP primitive in ", model.ProtoPath, ".")
	generated.P("struct ", fileName, "MCPHandlers: Sendable {")
	for _, c := range components {
		generated.P("    var ", c.property, ": any ", c.protocol)
	}
	generated.P("}")
	generated.P()
	generated.P("/// Builds the server declared by ", model.ProtoPath, " and registers its primitives.")
	generated.P("/// Start it with serve(_:transport:) so MCP Apps is advertised when enabled.")
	generated.P("func new", fileName, "MCPServer(_ handlers: ", fileName, "MCPHandlers) async throws -> Server {")
	generated.P("    let server = try newConfiguredServer(name: ", swiftStringLiteral(model.Factory.Name), ", version: ", swiftStringLiteral(model.Factory.Version), ", apps: ", fmt.Sprintf("%t", model.Factory.Apps), ")")
	for _, c := range components {
		generated.P("    try await ", c.register, "(server, handlers.", c.property, ")")
	}
	generated.P("    return server")
	generated.P("}")
	if !model.Factory.HTTP {
		return
	}
	generated.P()
	oauth := model.Factory.OAuth
	if oauth == nil {
		generated.P("/// Serves ", model.ProtoPath, " over stateless Streamable HTTP on /mcp, building a fresh server per request.")
		generated.P("func new", fileName, "MCPHTTPHandler(_ handlers: ", fileName, "MCPHandlers) throws -> MCPHTTPHandler {")
		generated.P("    try MCPHTTPHandler(oauth: nil, verifier: nil) { try await new", fileName, "MCPServer(handlers) }")
		generated.P("}")
		return
	}
	generated.P("/// Serves ", model.ProtoPath, " over stateless Streamable HTTP as its declared OAuth")
	generated.P("/// protected resource, building a fresh server per request. When verifier is nil")
	generated.P("/// the built-in RS256 JWKS verifier is used.")
	generated.P("func new", fileName, "MCPHTTPHandler(_ handlers: ", fileName, "MCPHandlers, verifier: (any TokenVerifier)? = nil) throws -> MCPHTTPHandler {")
	generated.P("    let oauth = try OAuthResourceServer(")
	generated.P("        resourceURL: ", swiftStringLiteral(oauth.GetResourceUrl()), ",")
	generated.P("        authorizationServers: ", swiftStringArrayLiteral(oauth.GetAuthorizationServers()), ",")
	generated.P("        scopes: ", swiftStringArrayLiteral(oauth.GetScopes()), ",")
	generated.P("        issuer: ", swiftStringLiteral(oauth.GetIssuer()), ",")
	generated.P("        audience: ", swiftStringLiteral(oauth.GetAudience()), ",")
	generated.P("        jwksURL: ", swiftStringLiteral(oauth.GetJwksUri()), ",")
	generated.P("        mcpPath: ", swiftStringLiteral(oauth.GetMcpPath()))
	generated.P("    )")
	generated.P("    return try MCPHTTPHandler(oauth: oauth, verifier: verifier) { try await new", fileName, "MCPServer(handlers) }")
	generated.P("}")
}

func renderSwiftShapes(generated *protogen.GeneratedFile, model SwiftFileModel) {
	generated.P()
	generated.P("/// ProtoJSON fields printed with their defaults, as protojson EmitDefaultValues does.")
	generated.P("private let ", swiftShapesName(model), " = ProtoJSONShapes([")
	for _, message := range model.Shapes {
		if len(message.Fields) == 0 {
			generated.P("    ", swiftStringLiteral(message.FullName), ": [],")
			continue
		}
		generated.P("    ", swiftStringLiteral(message.FullName), ": [")
		for _, field := range message.Fields {
			args := []string{swiftStringLiteral(field.JSONName)}
			if field.Default != "" {
				args = append(args, "default: "+field.Default)
			}
			if field.Nested != "" {
				args = append(args, "nested: "+swiftStringLiteral(field.Nested))
				if field.Cardinality != "single" {
					args = append(args, "."+field.Cardinality)
				}
			}
			generated.P("        ProtoJSONField(", strings.Join(args, ", "), "),")
		}
		generated.P("    ],")
	}
	generated.P("])")
}
