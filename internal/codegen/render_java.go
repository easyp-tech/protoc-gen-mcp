func renderJavaFile(plugin *protogen.Plugin, model JVMFileModel) error {
	if model.Language != LanguageJava {
		return fmt.Errorf("java renderer requires lang=java, got %q", model.Language)
	}
	if err := validateJavaMetadata(model); err != nil {
		return err
	}

	info, err := newJavaRenderInfo(plugin, model)
	if err != nil {
		return err
	}

	filePackage, err := resolveJVMFilePackage(info.file)
	if err != nil {
		return err
	}

	imports := map[string]bool{}
	for _, service := range model.Services {
		for _, method := range service.Methods {
			if _, err := info.javaTypeExpr(method.Input, imports, filePackage.Package); err != nil {
				return err
			}
			if _, err := info.javaTypeExpr(method.Output, imports, filePackage.Package); err != nil {
				return err
			}
		}
	}
	for _, resource := range model.Resources {
		if resource.SourceFile != "" {
			continue
		}
		if _, err := info.javaTypeExpr(newJVMTypeRefFromShared(resource.Output), imports, filePackage.Package); err != nil {
			return err
		}
	}
	descriptorAccessors, err := collectJavaDescriptorAccessors(info.file.Desc, filePackage.Package)
	if err != nil {
		return err
	}
	for _, accessor := range descriptorAccessors {
		if accessor.ImportPath != "" {
			imports[accessor.ImportPath] = true
		}
	}

	className := javaSidecarClassName(model.GeneratedFilenamePrefix)
	filename := javaSidecarOutputPath(model.GeneratedFilenamePrefix)
	generated := plugin.NewGeneratedFile(filename, "")

	generated.P("// Code generated by protoc-gen-mcp. DO NOT EDIT.")
	generated.P("// source: ", model.ProtoPath)
	generated.P()
	if filePackage.Package != "" {
		generated.P("package ", filePackage.Package, ";")
		generated.P()
	}

	javaImports := []string{
		"com.google.protobuf.Message",
		"com.google.protobuf.util.JsonFormat",
		"com.google.protobuf.Descriptors",
		"io.modelcontextprotocol.json.McpJsonDefaults",
		"io.modelcontextprotocol.json.McpJsonMapper",
		"io.modelcontextprotocol.json.TypeRef",
		"io.modelcontextprotocol.json.schema.JsonSchemaValidator",
		"io.modelcontextprotocol.server.McpAsyncServerExchange",
		"io.modelcontextprotocol.server.McpInitRequestHandler",
		"io.modelcontextprotocol.server.McpNotificationHandler",
		"io.modelcontextprotocol.server.McpRequestHandler",
		"io.modelcontextprotocol.spec.McpError",
		"io.modelcontextprotocol.spec.McpSchema",
		"io.modelcontextprotocol.spec.McpServerSession",
		"io.modelcontextprotocol.spec.McpServerTransport",
		"io.modelcontextprotocol.spec.McpServerTransportProvider",
		"java.io.IOException",
		"java.time.Duration",
		"java.util.ArrayList",
		"java.util.Collection",
		"java.util.Collections",
		"java.util.HashSet",
		"java.util.LinkedHashMap",
		"java.util.List",
		"java.util.Map",
		"java.util.Set",
		"java.util.UUID",
		"java.util.WeakHashMap",
		"java.util.function.Supplier",
		"reactor.core.publisher.Mono",
	}
	if model.Factory.HTTP {
		javaImports = append(javaImports,
			"jakarta.servlet.http.HttpServlet",
			"tech.easyp.mcp.runtime.McpHttpServer",
			"tech.easyp.mcp.runtime.McpHttpServlet",
		)
		if model.Factory.OAuth != nil {
			javaImports = append(javaImports,
				"tech.easyp.mcp.runtime.oauth.OAuthResourceServer",
				"tech.easyp.mcp.runtime.oauth.TokenVerifier",
			)
		}
	}
	for importPath := range imports {
		javaImports = append(javaImports, importPath)
	}
	sort.Strings(javaImports)
	for _, importPath := range javaImports {
		generated.P("import ", importPath, ";")
	}
	for _, name := range javaRuntimeTypes {
		generated.P("import tech.easyp.mcp.runtime.McpRuntime.", name, ";")
	}
	for _, name := range javaRuntimeFunctions {
		generated.P("import static tech.easyp.mcp.runtime.McpRuntime.", name, ";")
	}
	generated.P()

	generated.P("public final class ", className, " {")
	generated.P("  static {")
	generated.P("    tech.easyp.mcp.runtime.McpRuntime.checkGencodeVersion(", jvmGencodeVersion, ");")
	accessors := make([]string, 0, len(descriptorAccessors))
	for _, accessor := range descriptorAccessors {
		accessors = append(accessors, accessor.Expr)
	}
	generated.P("    tech.easyp.mcp.runtime.McpRuntime.registerProtoFiles(", strings.Join(accessors, ", "), ");")
	generated.P("  }")
	generated.P()
	generated.P("  private ", className, "() {")
	generated.P("  }")
	generated.P()

	for serviceIdx, service := range model.Services {
		generated.P("  public interface ", service.HandlerName, " {")
		for _, method := range service.Methods {
			inputType, err := info.javaTypeExpr(method.Input, imports, filePackage.Package)
			if err != nil {
				return err
			}
			outputType, err := info.javaTypeExpr(method.Output, imports, filePackage.Package)
			if err != nil {
				return err
			}
			generated.P("    ", outputType, " ", method.MethodName, "(McpAsyncServerExchange ctx, ", inputType, " request) throws Exception;")
		}
		generated.P("  }")
		generated.P()

		generated.P("  public static void ", service.RegisterName, "(")
		generated.P("      McpServerTransportProvider transportProvider,")
		generated.P("      ", service.HandlerName, " impl,")
		generated.P("      String namespace) {")
		generated.P("    if (transportProvider == null) {")
		generated.P("      throw new IllegalArgumentException(\"transportProvider must not be null\");")
		generated.P("    }")
		generated.P("    if (impl == null) {")
		generated.P("      throw new IllegalArgumentException(\"impl must not be null\");")
		generated.P("    }")
		generated.P("    ServerToolRegistry registry = registryFor(transportProvider);")
		generated.P("    String resolvedNamespace = normalizeNamespace(namespace, ", quote(service.Namespace), ");")
		for _, method := range service.Methods {
			inputType, err := info.javaTypeExpr(method.Input, imports, filePackage.Package)
			if err != nil {
				return err
			}
			outputType, err := info.javaTypeExpr(method.Output, imports, filePackage.Package)
			if err != nil {
				return err
			}
			icons, err := javaIcons(method.Icons)
			if err != nil {
				return err
			}
			generated.P("    registry.registerTool(")
			generated.P("        new RegisteredTool(")
			generated.P("            toolName(resolvedNamespace, ", quote(method.ToolName), "),")
			generated.P("            ", javaNullableString(method.Title), ",")
			generated.P("            ", javaNullableString(method.Description), ",")
			generated.P("            ", method.SchemaConst, "_INPUT_SCHEMA_JSON,")
			generated.P("            ", method.SchemaConst, "_OUTPUT_SCHEMA_JSON,")
			generated.P("            () -> ", inputType, ".newBuilder(),")
			generated.P("            () -> ", outputType, ".newBuilder(),")
			generated.P("            (ctx, request) -> impl.", method.MethodName, "(ctx, (", inputType, ") request),")
			generated.P("            ", javaAnnotations(method.Annotations), ",")
			generated.P("            ", icons, ",")
			generated.P("            ", javaTaskSupport(method.TaskSupport), ",")
			meta := "null"
			if metaJSON := toolMetaJSON(method.AppUI); metaJSON != "" {
				meta = "loadSchema(" + quote(metaJSON) + ")"
			}
			if len(method.RequiredScopes) > 0 {
				generated.P("            ", meta, ",")
				generated.P("            ", javaStringListLiteral(method.RequiredScopes), ")")
			} else {
				generated.P("            ", meta, ")")
			}
			generated.P("    );")
		}
		generated.P("    installSessionFactory(transportProvider, registry);")
		generated.P("  }")
		generated.P()

		for methodIdx, method := range service.Methods {
			generated.P("  private static final String ", method.SchemaConst, "_INPUT_SCHEMA_JSON = ", quote(method.InputSchemaJSON), ";")
			generated.P()
			generated.P("  private static final String ", method.SchemaConst, "_OUTPUT_SCHEMA_JSON = ", quote(method.OutputSchemaJSON), ";")
			if methodIdx < len(service.Methods)-1 || serviceIdx < len(model.Services)-1 {
				generated.P()
			}
		}
	}

	if len(model.Prompts) > 0 {
		renderJavaPrompts(generated, model)
	}

	if len(model.Resources) > 0 {
		if err := renderJavaResources(generated, info, model, imports, filePackage.Package); err != nil {
			return err
		}
	}

	if model.Factory.Emit {
		renderJavaServerFactory(generated, model)
	}

	generated.P("}")

	return nil
}

func renderJavaResources(generated *protogen.GeneratedFile, info javaRenderInfo, model JVMFileModel, imports map[string]bool, currentPackage string) error {
	fileBase := jvmFileBaseName(model.ProtoPath)
	interfaceName := jvmExportedIdentifier(fileBase) + "ResourceHandler"
	registerName := "register" + jvmExportedIdentifier(fileBase) + "Resources"

	outputTypes := map[string]string{}
	for _, resource := range model.Resources {
		if resource.SourceFile != "" {
			continue
		}
		outputType, err := info.javaTypeExpr(newJVMTypeRefFromShared(resource.Output), imports, currentPackage)
		if err != nil {
			return err
		}
		outputTypes[resource.ProtoFullName] = outputType
	}

	generated.P()
	generated.P("  public interface ", interfaceName, " {")
	for _, resource := range model.Resources {
		returnType, ok := outputTypes[resource.ProtoFullName]
		if !ok {
			returnType = "Object"
		}
		paramList := ""
		if resource.IsTemplate {
			generated.P("    List<McpSchema.Resource> list", resource.ProtoName, "s() throws Exception;")
			for i, identifier := range javaParamIdentifiers(resource.Params) {
				if i > 0 {
					paramList += ", "
				}
				paramList += "String " + identifier
			}
		}
		if resource.SourceFile != "" {
			generated.P("    /** Returns the body of ", resource.SourceFile, " as a String or byte[]. */")
		}
		generated.P("    ", returnType, " read", resource.ProtoName, "(", paramList, ") throws Exception;")
	}
	generated.P("  }")
	generated.P()

	generated.P("  public static void ", registerName, "(")
	generated.P("      McpServerTransportProvider transportProvider,")
	generated.P("      ", interfaceName, " impl,")
	generated.P("      String namespace) {")
	generated.P("    if (transportProvider == null) {")
	generated.P("      throw new IllegalArgumentException(\"transportProvider must not be null\");")
	generated.P("    }")
	generated.P("    if (impl == null) {")
	generated.P("      throw new IllegalArgumentException(\"impl must not be null\");")
	generated.P("    }")
	generated.P("    ServerToolRegistry registry = registryFor(transportProvider);")
	for _, resource := range model.Resources {
		descriptor, err := resourceDescriptorJSON(resource)
		if err != nil {
			return err
		}
		meta := "null"
		if metaJSON := resourceMetaJSON(resource); metaJSON != "" {
			meta = "loadSchema(" + quote(metaJSON) + ")"
		}
		field := "null"
		if resource.ContentField != "" {
			field = quote(resource.ContentField)
		}
		encode := func(call string) string {
			return "resourceContents(" + call + ", uri, " + quote(resource.MIMEType) + ", " + quote(pythonResourceContentKind(resourceContent(resource))) + ", " + field + ", " + meta + ")"
		}
		listing := "resourceListing(" + quote(descriptor) + ", namespace, " + quote(resource.Name) + ")"
		if resource.IsTemplate {
			args := make([]string, 0, len(resource.Params))
			for _, param := range resource.Params {
				args = append(args, "params.get("+quote(param.Name)+")")
			}
			generated.P("    registry.registerResourceTemplate(new RegisteredResourceTemplate(")
			generated.P("        ", listing, ",")
			generated.P("        compileUriTemplate(", quote(resource.URITemplate), "),")
			generated.P("        List.of(", strings.Join(quotedParamNames(resource.Params), ", "), "),")
			generated.P("        () -> resourceList(impl.list", resource.ProtoName, "s()),")
			generated.P("        (uri, params) -> ", encode("impl.read"+resource.ProtoName+"("+strings.Join(args, ", ")+")"), "));")
		} else {
			generated.P("    registry.registerResource(new RegisteredResource(")
			generated.P("        ", listing, ",")
			generated.P("        (uri, params) -> ", encode("impl.read"+resource.ProtoName+"()"), "));")
		}
	}
	generated.P("    installSessionFactory(transportProvider, registry);")
	generated.P("  }")
	return nil
}

// renderJavaServerFactory mirrors render_go_server.go. A Java MCP server is a
// transport provider plus its runtime registry, so the factory configures the
// registry and registers this file on the given transport.
func renderJavaServerFactory(generated *protogen.GeneratedFile, model JVMFileModel) {
	fileName := jvmExportedIdentifier(jvmFileBaseName(model.ProtoPath))
	var components []string
	for _, service := range model.Services {
		components = append(components, service.HandlerName+" "+jvmLowerCamelIdentifier(service.ProtoName))
	}
	if len(model.Prompts) > 0 {
		components = append(components, fileName+"PromptHandler prompts")
	}
	if len(model.Resources) > 0 {
		components = append(components, fileName+"ResourceHandler resources")
	}
	generated.P()
	generated.P("  /** Business handlers for every MCP primitive in ", model.ProtoPath, ". */")
	generated.P("  public record ", fileName, "MCPHandlers(", strings.Join(components, ", "), ") {")
	generated.P("  }")
	generated.P()
	generated.P("  /** Configures the server declared by ", model.ProtoPath, " on transportProvider and registers its primitives. */")
	generated.P("  public static void install", fileName, "MCPServer(McpServerTransportProvider transportProvider, ", fileName, "MCPHandlers handlers) {")
	generated.P("    registryFor(transportProvider).configureServer(", quote(model.Factory.Name), ", ", quote(model.Factory.Version), ", ", javaBoolLiteral(model.Factory.Apps), ");")
	for _, service := range model.Services {
		generated.P("    ", service.RegisterName, "(transportProvider, handlers.", jvmLowerCamelIdentifier(service.ProtoName), "(), null);")
	}
	if len(model.Prompts) > 0 {
		generated.P("    register", fileName, "Prompts(transportProvider, handlers.prompts(), null);")
	}
	if len(model.Resources) > 0 {
		generated.P("    register", fileName, "Resources(transportProvider, handlers.resources(), null);")
	}
	generated.P("    installSessionFactory(transportProvider, registryFor(transportProvider));")
	generated.P("  }")
	if !model.Factory.HTTP {
		return
	}
	generated.P()
	oauth := model.Factory.OAuth
	if oauth == nil {
		generated.P("  /** Serves server, filled by install", fileName, "MCPServer, over stateless Streamable HTTP on /mcp; mount it at \"/*\". */")
		generated.P("  public static HttpServlet new", fileName, "MCPHttpServlet(McpHttpServer server) {")
		generated.P("    return McpHttpServlet.open(server);")
		generated.P("  }")
		return
	}
	generated.P("  /**")
	generated.P("   * Serves server, filled by install", fileName, "MCPServer, over stateless Streamable HTTP")
	generated.P("   * as the OAuth protected resource declared by ", model.ProtoPath, "; mount it at \"/*\".")
	generated.P("   * When verifier is null the built-in RS256 JWKS verifier is used.")
	generated.P("   */")
	generated.P("  public static HttpServlet new", fileName, "MCPHttpServlet(McpHttpServer server, TokenVerifier verifier) {")
	generated.P("    OAuthResourceServer oauth = new OAuthResourceServer(")
	generated.P("        ", quote(oauth.GetResourceUrl()), ",")
	generated.P("        ", javaStringListLiteral(oauth.GetAuthorizationServers()), ",")
	generated.P("        ", javaStringListLiteral(oauth.GetScopes()), ",")
	generated.P("        ", quote(oauth.GetIssuer()), ",")
	generated.P("        ", quote(oauth.GetAudience()), ",")
	generated.P("        ", quote(oauth.GetJwksUri()), ",")
	generated.P("        ", quote(oauth.GetMcpPath()), ");")
	generated.P("    return McpHttpServlet.protect(server, oauth, verifier);")
	generated.P("  }")
}

func quotedParamNames(params []ResourceParamModel) []string {
	quoted := make([]string, 0, len(params))
	for _, param := range params {
		quoted = append(quoted, quote(param.Name))
	}
	return quoted
}

func renderJavaPrompts(generated *protogen.GeneratedFile, model JVMFileModel) {
	fileBase := jvmFileBaseName(model.ProtoPath)
	interfaceName := jvmExportedIdentifier(fileBase) + "PromptHandler"
	registerName := "register" + jvmExportedIdentifier(fileBase) + "Prompts"

	generated.P()
	generated.P("  public interface ", interfaceName, " {")
	for _, prompt := range model.Prompts {
		generated.P("    List<Map<String, Object>> ", jvmMethodName(prompt.ProtoName), "(Map<String, String> arguments) throws Exception;")
	}
	generated.P("  }")
	generated.P()

	generated.P("  public static void ", registerName, "(")
	generated.P("      McpServerTransportProvider transportProvider,")
	generated.P("      ", interfaceName, " impl,")
	generated.P("      String namespace) {")
	generated.P("    if (transportProvider == null) {")
	generated.P("      throw new IllegalArgumentException(\"transportProvider must not be null\");")
	generated.P("    }")
	generated.P("    if (impl == null) {")
	generated.P("      throw new IllegalArgumentException(\"impl must not be null\");")
	generated.P("    }")
	generated.P("    ServerToolRegistry registry = registryFor(transportProvider);")
	for _, prompt := range model.Prompts {
		generated.P("    {")
		generated.P("      String resolvedName = toolName(namespace, ", quote(prompt.Name), ");")
		generated.P("      Map<String, Object> promptMap = new LinkedHashMap<>();")
		generated.P("      promptMap.put(\"name\", resolvedName);")
		if prompt.Title != "" {
			generated.P("      promptMap.put(\"title\", ", quote(prompt.Title), ");")
		}
		if prompt.Description != "" {
			generated.P("      promptMap.put(\"description\", ", quote(prompt.Description), ");")
		}
		generated.P("      List<Map<String, Object>> argsSpec = new ArrayList<>();")
		var requiredArgNames []string
		for _, arg := range prompt.Arguments {
			generated.P("      {")
			generated.P("        Map<String, Object> argMap = new LinkedHashMap<>();")
			generated.P("        argMap.put(\"name\", ", quote(arg.Name), ");")
			generated.P("        argMap.put(\"description\", ", quote(arg.Description), ");")
			generated.P("        argMap.put(\"required\", ", javaBoolLiteral(arg.Required), ");")
			generated.P("        argsSpec.add(argMap);")
			generated.P("      }")
			if arg.Required {
				requiredArgNames = append(requiredArgNames, quote(arg.Name))
			}
		}
		generated.P("      promptMap.put(\"arguments\", argsSpec);")
		generated.P("      registry.registerPrompt(new RegisteredPrompt(resolvedName, promptMap, List.of(", strings.Join(requiredArgNames, ", "), "), impl::", jvmMethodName(prompt.ProtoName), "));")
		generated.P("    }")
	}
	generated.P("    installSessionFactory(transportProvider, registry);")
	generated.P("  }")
}

func javaBoolLiteral(value bool) string {
	if value {
		return "Boolean.TRUE"
	}
	return "Boolean.FALSE"
}

type javaDescriptorAccessor struct {
	ImportPath string
	Expr       string
}

type javaRenderInfo struct {
	file     *protogen.File
	messages map[string]*protogen.Message
	enums    map[string]*protogen.Enum
}

func newJavaRenderInfo(plugin *protogen.Plugin, model JVMFileModel) (javaRenderInfo, error) {
	file := plugin.FilesByPath[model.ProtoPath]
	if file == nil {
		return javaRenderInfo{}, fmt.Errorf("generated file %q not found in plugin", model.ProtoPath)
	}

	info := javaRenderInfo{
		file:     file,
		messages: map[string]*protogen.Message{},
		enums:    map[string]*protogen.Enum{},
	}
	for _, current := range plugin.Files {
		indexJavaMessages(info.messages, current.Messages)
		indexJavaEnums(info.enums, current.Enums)
		indexJavaEnumsInMessages(info.enums, current.Messages)
	}

	return info, nil
}

func indexJavaMessages(index map[string]*protogen.Message, messages []*protogen.Message) {
	for _, message := range messages {
		index[string(message.Desc.FullName())] = message
		indexJavaMessages(index, message.Messages)
	}
}

func indexJavaEnums(index map[string]*protogen.Enum, enums []*protogen.Enum) {
	for _, enum := range enums {
		index[string(enum.Desc.FullName())] = enum
	}
}

func indexJavaEnumsInMessages(index map[string]*protogen.Enum, messages []*protogen.Message) {
	for _, message := range messages {
		indexJavaEnums(index, message.Enums)
		indexJavaEnumsInMessages(index, message.Messages)
	}
}

func (j javaRenderInfo) javaTypeExpr(ref JVMTypeRef, imports map[string]bool, currentPackage string) (string, error) {
	var (
		resolved jvmResolvedTypeRef
		err      error
	)

	if ref.IsEnum {
		enum := j.enums[ref.ProtoFullName]
		if enum == nil {
			return "", fmt.Errorf("enum %q not found during Java render", ref.ProtoFullName)
		}
		resolved, err = resolveJVMEnumTypeRef(enum, j.file.Desc.Path())
		if err != nil {
			return "", err
		}
	} else {
		message := j.messages[ref.ProtoFullName]
		if message == nil {
			return "", fmt.Errorf("message %q not found during Java render", ref.ProtoFullName)
		}
		resolved, err = resolveJVMMessageTypeRef(message, j.file.Desc.Path())
		if err != nil {
			return "", err
		}
	}

	if resolved.ImportPath != "" && javaImportPackage(resolved.ImportPath) != currentPackage {
		imports[resolved.ImportPath] = true
	}
	return resolved.Expr, nil
}

func collectJavaDescriptorAccessors(file protoreflect.FileDescriptor, currentPackage string) ([]javaDescriptorAccessor, error) {
	seen := map[string]bool{}
	var accessors []javaDescriptorAccessor
	var visit func(protoreflect.FileDescriptor) error
	visit = func(current protoreflect.FileDescriptor) error {
		if current == nil {
			return nil
		}
		if seen[current.Path()] {
			return nil
		}
		seen[current.Path()] = true

		if current.Path() == file.Path() || shouldIncludeJavaTypeRegistryFile(current) {
			resolved, err := resolveJVMDescriptorFilePackage(current)
			if err != nil {
				return err
			}
			importPath := ""
			if resolved.Package != currentPackage {
				importPath = resolved.Package + "." + resolved.OuterClassName
			}
			accessors = append(accessors, javaDescriptorAccessor{
				ImportPath: importPath,
				Expr:       resolved.OuterClassName + ".getDescriptor()",
			})
		}

		for i := 0; i < current.Imports().Len(); i++ {
			if err := visit(current.Imports().Get(i)); err != nil {
				return err
			}
		}
		return nil
	}
	if err := visit(file); err != nil {
		return nil, err
	}
	sort.Slice(accessors, func(i, j int) bool {
		if accessors[i].ImportPath == accessors[j].ImportPath {
			return accessors[i].Expr < accessors[j].Expr
		}
		return accessors[i].ImportPath < accessors[j].ImportPath
	})
	return accessors, nil
}

func shouldIncludeJavaTypeRegistryFile(file protoreflect.FileDescriptor) bool {
	if file == nil {
		return false
	}
	protoPath := file.Path()
	return !strings.HasPrefix(protoPath, "google/protobuf/") && !strings.HasPrefix(protoPath, "mcp/options/")
}

func validateJavaMetadata(model JVMFileModel) error {
	for _, service := range model.Services {
		for _, icon := range service.Icons {
			if err := validateJavaIconTheme(icon); err != nil {
				return err
			}
		}
		for _, method := range service.Methods {
			for _, icon := range method.Icons {
				if err := validateJavaIconTheme(icon); err != nil {
					return err
				}
			}
		}
	}
	return nil
}

func validateJavaIconTheme(icon *mcpoptionsv1.Icon) error {
	switch icon.GetTheme() {
	case "", "light", "dark":
		return nil
	default:
		return fmt.Errorf("unsupported Java icon theme %q", icon.GetTheme())
	}
}

func javaAnnotations(ann *mcpoptionsv1.ToolAnnotations) string {
	if ann == nil {
		return "null"
	}

	return strings.Join([]string{
		"toolAnnotationsMapOrNull(",
		javaNullableString(ann.Title), ", ",
		javaBoolLiteralOrNull(ann.ReadOnlyHint, ann.ReadOnlyHint), ", ",
		javaOptionalBoolLiteral(ann.DestructiveHint), ", ",
		javaBoolLiteralOrNull(ann.IdempotentHint, ann.IdempotentHint), ", ",
		javaOptionalBoolLiteral(ann.OpenWorldHint),
		")",
	}, "")
}

func javaIcons(icons []*mcpoptionsv1.Icon) (string, error) {
	if len(icons) == 0 {
		return "List.of()", nil
	}

	items := make([]string, 0, len(icons))
	for _, icon := range icons {
		if err := validateJavaIconTheme(icon); err != nil {
			return "", err
		}
		items = append(items, fmt.Sprintf(
			"iconMap(%s, %s, %s, %s)",
			quote(icon.GetSrc()),
			javaNullableString(icon.GetMimeType()),
			javaStringListLiteral(icon.GetSizes()),
			javaNullableString(icon.GetTheme()),
		))
	}
	return "List.of(" + strings.Join(items, ", ") + ")", nil
}

func javaTaskSupport(taskSupport mcpoptionsv1.TaskSupport) string {
	switch taskSupport {
	case mcpoptionsv1.TaskSupport_TASK_SUPPORT_OPTIONAL:
		return `toolExecutionMapOrNull("optional")`
	case mcpoptionsv1.TaskSupport_TASK_SUPPORT_REQUIRED:
		return `toolExecutionMapOrNull("required")`
	default:
		return `toolExecutionMapOrNull(null)`
	}
}

func javaNullableString(value string) string {
	if value == "" {
		return "null"
	}
	return quote(value)
}

func javaOptionalBoolLiteral(value *bool) string {
	if value == nil {
		return "null"
	}
	if *value {
		return "Boolean.TRUE"
	}
	return "Boolean.FALSE"
}

func javaBoolLiteralOrNull(include bool, value bool) string {
	if !include {
		return "null"
	}
	if value {
		return "Boolean.TRUE"
	}
	return "Boolean.FALSE"
}

func javaStringListLiteral(values []string) string {
	if len(values) == 0 {
		return "List.of()"
	}
	quoted := make([]string, 0, len(values))
	for _, value := range values {
		quoted = append(quoted, quote(value))
	}
	return "List.of(" + strings.Join(quoted, ", ") + ")"
}

func javaImportPackage(importPath string) string {
	idx := strings.LastIndex(importPath, ".")
	if idx <= 0 {
		return ""
	}
	return importPath[:idx]
}

func javaSidecarOutputPath(generatedFilenamePrefix string) string {
	return path.Join(path.Dir(generatedFilenamePrefix), javaSidecarClassName(generatedFilenamePrefix)+".java")
}

func javaSidecarClassName(generatedFilenamePrefix string) string {
	base := path.Base(generatedFilenamePrefix)
	var b strings.Builder
	nextUpper := true
	for _, r := range base {
		if !unicode.IsLetter(r) && !unicode.IsDigit(r) {
			nextUpper = true
			continue
		}
		if b.Len() == 0 && unicode.IsDigit(r) {
			b.WriteString("Proto")
		}
		if nextUpper {
			b.WriteRune(unicode.ToUpper(r))
			nextUpper = false
			continue
		}
		b.WriteRune(r)
	}
	if b.Len() == 0 {
		b.WriteString("Proto")
	}
	b.WriteString("Mcp")
	return b.String()
}
