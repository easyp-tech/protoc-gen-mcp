	generated.P()
	generated.P("  private static Map<String, Object> toolAnnotationsMapOrNull(")
	generated.P("      String title,")
	generated.P("      Boolean readOnlyHint,")
	generated.P("      Boolean destructiveHint,")
	generated.P("      Boolean idempotentHint,")
