	generated.P("    return requestHandlers;")
	generated.P("  }")
	generated.P()
	generated.P("  private static Map<String, McpNotificationHandler> notificationHandlers() {")
	generated.P("    return new LinkedHashMap<>();")
	generated.P("  }")
	generated.P()
	generated.P("  private static Map<String, Object> listRegisteredTools(ServerToolRegistry registry) {")
	generated.P("    Map<String, Object> result = new LinkedHashMap<>();")
	generated.P("    List<Map<String, Object>> tools = new ArrayList<>();")
	generated.P("    for (RegisteredTool tool : registry.allTools()) {")
	generated.P("      tools.add(toolAsProtocolMap(tool));")
	generated.P("    }")
	generated.P("    result.put(\"tools\", tools);")
	generated.P("    return result;")
	generated.P("  }")
	generated.P()
	generated.P("  private static Map<String, Object> toolAsProtocolMap(RegisteredTool tool) {")
	generated.P("    Map<String, Object> protocol = new LinkedHashMap<>();")
	generated.P("    protocol.put(\"name\", tool.name);")
	generated.P("    putIfNotNull(protocol, \"title\", tool.title);")
	generated.P("    putIfNotNull(protocol, \"description\", tool.description);")
	generated.P("    protocol.put(\"inputSchema\", tool.inputSchema);")
	generated.P("    protocol.put(\"outputSchema\", tool.outputSchema);")
	generated.P("    putIfNotNull(protocol, \"annotations\", tool.annotations);")
	generated.P("    if (!tool.icons.isEmpty()) {")
	generated.P("      protocol.put(\"icons\", tool.icons);")
	generated.P("    }")
	generated.P("    putIfNotNull(protocol, \"execution\", tool.execution);")
	generated.P("    return protocol;")
	generated.P("  }")
	generated.P()
	generated.P("  private static void putIfNotNull(Map<String, Object> target, String key, Object value) {")
