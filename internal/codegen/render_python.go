// pythonGencodeVersion must match GENCODE_VERSION in
// runtime/python/protoc_gen_mcp_runtime/_version.py.
const pythonGencodeVersion = "1"

func renderPythonFile(plugin *protogen.Plugin, model FileModel) error {
	info, err := newPythonRenderInfo(plugin, model)
	if err != nil {
		return err
	}
	return renderPythonFileForHandler(plugin, model, model.Options.PythonHandler, pythonOutputPath(info.file))
}

func renderPythonFileForHandler(plugin *protogen.Plugin, model FileModel, handler PythonHandler, filename string) error {
	info, err := newPythonRenderInfo(plugin, model)
	if err != nil {
		return err
	}
	protobufHandlerMode := handler == PythonHandlerProtobuf

	generated := plugin.NewGeneratedFile(filename, "")

	generated.P("# Code generated by protoc-gen-mcp. DO NOT EDIT.")
	generated.P("# source: ", model.ProtoPath)
	generated.P("from __future__ import annotations")
	generated.P()
	generated.P("import enum")
	generated.P("import json")
	generated.P("from dataclasses import dataclass, field")
	generated.P("from typing import Any, Awaitable, Protocol, TypeAlias")
	generated.P()
	generated.P("import mcp.server.lowlevel")
	generated.P("import mcp.server.session")
	generated.P("import protoc_gen_mcp_runtime")
	generated.P("import mcp.types")
	generated.P("from google.protobuf import any_pb2, duration_pb2, empty_pb2, field_mask_pb2, json_format, struct_pb2, timestamp_pb2, wrappers_pb2")
	if !protobufHandlerMode {
		for _, moduleRef := range info.publicImportsForModel(model) {
			if moduleRef.Package == "" {
				if moduleRef.Alias == moduleRef.Module {
					generated.P("import ", moduleRef.Module)
				} else {
					generated.P("import ", moduleRef.Module, " as ", moduleRef.Alias)
				}
				continue
			}
			if moduleRef.Alias == moduleRef.Module {
				generated.P("from ", moduleRef.Package, " import ", moduleRef.Module)
			} else {
				generated.P("from ", moduleRef.Package, " import ", moduleRef.Module, " as ", moduleRef.Alias)
			}
		}
	}
	for _, moduleRef := range info.protobufImportsForModel(model) {
		if moduleRef.IsCurrent {
			generated.P("try:")
			generated.P("    from . import ", moduleRef.Module)
			generated.P("except ImportError:")
			if moduleRef.Alias == moduleRef.Module {
				generated.P("    import ", moduleRef.Module)
			} else {
				generated.P("    import ", moduleRef.Module, " as ", moduleRef.Alias)
			}
			continue
		}
		if moduleRef.Package == "" {
			if moduleRef.Alias == moduleRef.Module {
				generated.P("import ", moduleRef.Module)
			} else {
				generated.P("import ", moduleRef.Module, " as ", moduleRef.Alias)
			}
			continue
		}
		if moduleRef.Alias == moduleRef.Module {
			generated.P("from ", moduleRef.Package, " import ", moduleRef.Module)
		} else {
			generated.P("from ", moduleRef.Package, " import ", moduleRef.Module, " as ", moduleRef.Alias)
		}
	}
	generated.P()
	generated.P("ToolRequestContext = mcp.server.session.ServerSession")
	generated.P()
	if !protobufHandlerMode {
		if err := renderPythonPublicTypes(generated, info, model); err != nil {
			return err
		}
	}
	generated.P("protoc_gen_mcp_runtime.check_gencode_version(", pythonGencodeVersion, ")")
	generated.P()
	if !protobufHandlerMode {
		if err := renderPythonMappers(generated, info, model); err != nil {
			return err
		}
	}

	for serviceIdx, service := range model.Services {
		generated.P("class ", pythonProtocolName(service.ProtoName), "(Protocol):")
		for _, method := range service.Methods {
			inputType, outputType, err := info.pythonHandlerMethodTypeRefs(method, protobufHandlerMode)
			if err != nil {
				return err
			}
			generated.P("    def ", pythonMethodName(method.ProtoName), "(self, ctx: ToolRequestContext, req: ", inputType, ") -> ", outputType, " | Awaitable[", outputType, "]:")
			generated.P("        ...")
		}
		generated.P()

		registerName := pythonRegisterName(service.ProtoName)
		protocolName := pythonProtocolName(service.ProtoName)
		generated.P("def ", registerName, "(server: mcp.server.lowlevel.Server, impl: ", protocolName, ", *, namespace: str | None = None) -> None:")
		generated.P("    if impl is None:")
		generated.P("        raise ValueError(\"", registerName, ": impl is nil\")")
		generated.P("    registry = protoc_gen_mcp_runtime.install_tool_registry(server)")
		generated.P("    resolved_namespace = protoc_gen_mcp_runtime.normalize_namespace(namespace, ", quote(service.Namespace), ")")
		for _, method := range service.Methods {
			inputType, err := info.pythonProtobufTypeRef(method.Input)
			if err != nil {
				return err
			}
			outputType, err := info.pythonProtobufTypeRef(method.Output)
			if err != nil {
				return err
			}
			inputMapper := "protoc_gen_mcp_runtime.identity"
			outputMapper := "protoc_gen_mcp_runtime.identity"
			if !protobufHandlerMode {
				inputMapper, err = info.pythonMapperHelperForMethodType("from_pb", method.Input)
				if err != nil {
					return err
				}
				outputMapper, err = info.pythonMapperHelperForMethodType("to_pb", method.Output)
				if err != nil {
					return err
				}
			}
			schemaName := pythonSchemaConst(service.ProtoName, method.Name)
			generated.P("    registry.add_tool(protoc_gen_mcp_runtime.RegisteredTool(")
			generated.P("        name=protoc_gen_mcp_runtime.tool_name(resolved_namespace, ", quote(method.Name), "),")
			generated.P("        title=", quote(method.Title), ",")
			generated.P("        description=", quote(method.Description), ",")
			generated.P("        input_schema_json=", schemaName, "_INPUT_SCHEMA_JSON,")
			generated.P("        output_schema_json=", schemaName, "_OUTPUT_SCHEMA_JSON,")
			generated.P("        request_type=", inputType, ",")
			generated.P("        response_type=", outputType, ",")
			generated.P("        from_pb=", inputMapper, ",")
			generated.P("        to_pb=", outputMapper, ",")
			generated.P("        handler=impl.", pythonMethodName(method.ProtoName), ",")
			generated.P("        annotations=", pythonAnnotations(method.Annotations), ",")
			generated.P("        icons=", pythonIcons(method.Icons), ",")
			generated.P("        execution=", pythonTaskSupport(method.TaskSupport), ",")
			if meta := toolMetaJSON(method.AppUI); meta != "" {
				generated.P("        meta=json.loads(", quote(meta), "),")
			}
			if len(method.RequiredScopes) > 0 {
				generated.P("        required_scopes=", pythonStringTupleOf(method.RequiredScopes), ",")
			}
			generated.P("    ))")
		}
		generated.P()

		for methodIdx, method := range service.Methods {
			schemaName := pythonSchemaConst(service.ProtoName, method.Name)
			generated.P(schemaName, "_INPUT_SCHEMA_JSON = ", quote(method.InputSchemaJSON))
			generated.P()
			generated.P(schemaName, "_OUTPUT_SCHEMA_JSON = ", quote(method.OutputSchemaJSON))
			if methodIdx < len(service.Methods)-1 || serviceIdx < len(model.Services)-1 {
				generated.P()
			}
		}
	}

	if len(model.Prompts) > 0 {
		renderPythonPrompts(generated, model)
	}

	if len(model.Resources) > 0 {
		if err := renderPythonResources(generated, info, model, protobufHandlerMode); err != nil {
			return err
		}
	}

	if model.Factory.Emit {
		renderPythonServerFactory(generated, model)
	}

	return nil
}

// renderPythonServerFactory mirrors render_go_server.go: a handlers dataclass
// and a factory that builds a configured server and registers this file.
func renderPythonServerFactory(generated *protogen.GeneratedFile, model FileModel) {
	fileBase := pythonFileBaseName(model.ProtoPath)
	handlersName := pythonExportedIdentifier(fileBase) + "MCPHandlers"
	factoryName := "create_" + toSnakeCase(fileBase) + "_mcp_server"

	generated.P()
	generated.P()
	generated.P("@dataclass")
	generated.P("class ", handlersName, ":")
	generated.P("    \"\"\"Business handlers for every MCP primitive in ", model.ProtoPath, ".\"\"\"")
	if len(model.Services) == 0 && len(model.Prompts) == 0 && len(model.Resources) == 0 {
		generated.P("    pass")
	}
	for _, service := range model.Services {
		generated.P("    ", toSnakeCase(service.ProtoName), ": ", pythonProtocolName(service.ProtoName))
	}
	if len(model.Prompts) > 0 {
		generated.P("    prompts: ", pythonExportedIdentifier(fileBase), "PromptHandler")
	}
	if len(model.Resources) > 0 {
		generated.P("    resources: ", pythonExportedIdentifier(fileBase), "ResourceHandler")
	}
	generated.P()
	generated.P()
	generated.P("def ", factoryName, "(handlers: ", handlersName, ") -> protoc_gen_mcp_runtime.ConfiguredServer:")
	generated.P("    \"\"\"Builds the server declared by ", model.ProtoPath, " and registers its primitives.\"\"\"")
	generated.P("    server = protoc_gen_mcp_runtime.new_configured_server(", quote(model.Factory.Name), ", ", quote(model.Factory.Version), ", apps=", pythonBool(model.Factory.Apps), ")")
	for _, service := range model.Services {
		generated.P("    ", pythonRegisterName(service.ProtoName), "(server, handlers.", toSnakeCase(service.ProtoName), ")")
	}
	if len(model.Prompts) > 0 {
		generated.P("    register_", toSnakeCase(fileBase), "_prompts(server, handlers.prompts)")
	}
	if len(model.Resources) > 0 {
		generated.P("    register_", toSnakeCase(fileBase), "_resources(server, handlers.resources)")
	}
	generated.P("    return server")

	if model.ServerConfig == nil {
		return
	}
	generated.P()
	generated.P()
	generated.P("def create_", toSnakeCase(fileBase), "_mcp_http_app(server: mcp.server.lowlevel.Server, verifier: Any = None) -> Any:")
	generated.P("    \"\"\"Serves server over stateless Streamable HTTP with the policy of ", model.ProtoPath, ".")
	generated.P()
	generated.P("    Returns an ASGI application. With OAuth, verifier is an SDK TokenVerifier; when")
	generated.P("    it is None the built-in RS256 JWKS verifier is used.")
	generated.P("    \"\"\"")
	oauth := model.ServerConfig.GetOauth()
	if oauth == nil {
		generated.P("    return protoc_gen_mcp_runtime.new_http_app(server)")
		return
	}
	generated.P("    oauth = protoc_gen_mcp_runtime.OAuthResourceServer(")
	generated.P("        resource_url=", quote(oauth.GetResourceUrl()), ",")
	generated.P("        authorization_servers=", pythonStringTupleOf(oauth.GetAuthorizationServers()), ",")
	generated.P("        scopes=", pythonStringTupleOf(oauth.GetScopes()), ",")
	generated.P("        issuer=", quote(oauth.GetIssuer()), ",")
	generated.P("        audience=", quote(oauth.GetAudience()), ",")
	generated.P("        jwks_url=", quote(oauth.GetJwksUri()), ",")
	generated.P("        mcp_path=", quote(oauth.GetMcpPath()), ",")
	generated.P("    )")
	generated.P("    return protoc_gen_mcp_runtime.new_http_app(server, oauth, verifier)")
}

func pythonStringTupleOf(values []string) string {
	quoted := make([]string, 0, len(values))
	for _, value := range values {
		quoted = append(quoted, quote(value))
	}
	switch len(quoted) {
	case 0:
		return "()"
	case 1:
		return "(" + quoted[0] + ",)"
	default:
		return "(" + strings.Join(quoted, ", ") + ")"
	}
}

func renderPythonResources(generated *protogen.GeneratedFile, info pythonRenderInfo, model FileModel, protobufHandlerMode bool) error {
	fileBase := pythonFileBaseName(model.ProtoPath)
	protocolName := pythonExportedIdentifier(fileBase) + "ResourceHandler"
	registerName := "register_" + toSnakeCase(fileBase) + "_resources"

	generated.P()
	generated.P("class ", protocolName, "(Protocol):")
	generated.P("    \"\"\"Handler protocol for MCP resources in ", model.ProtoPath, ".\"\"\"")
	for _, resource := range model.Resources {
		methodName := toSnakeCase(resource.ProtoName)
		returnType := "str | bytes"
		if resource.SourceFile == "" {
			var err error
			if protobufHandlerMode {
				returnType, err = info.pythonProtobufTypeRef(resource.Output)
			} else {
				returnType, err = info.pythonPublicMethodTypeRef(resource.Output)
			}
			if err != nil {
				return err
			}
		}
		paramList := "self"
		if resource.IsTemplate {
			generated.P("    def list_", methodName, "s(self) -> list[mcp.types.Resource] | Awaitable[list[mcp.types.Resource]]:")
			generated.P("        ...")
			for _, identifier := range pythonParamIdentifiers(resource.Params) {
				paramList += ", " + identifier + ": str"
			}
		}
		generated.P("    def read_", methodName, "(", paramList, ") -> ", returnType, " | Awaitable[", returnType, "]:")
		generated.P("        ...")
	}
	generated.P()

	generated.P("def ", registerName, "(")
	generated.P("    server: mcp.server.lowlevel.Server,")
	generated.P("    impl: ", protocolName, ",")
	generated.P("    *,")
	generated.P("    namespace: str | None = None,")
	generated.P(") -> None:")
	generated.P("    \"\"\"Registers MCP resources for ", fileBase, ".\"\"\"")
	generated.P("    if impl is None:")
	generated.P("        raise ValueError(\"", registerName, ": impl is nil\")")
	generated.P("    registry = protoc_gen_mcp_runtime.install_resource_registry(server)")
	for _, resource := range model.Resources {
		descriptor, err := resourceDescriptorJSON(resource)
		if err != nil {
			return err
		}
		methodName := toSnakeCase(resource.ProtoName)
		meta := "None"
		if metaJSON := resourceMetaJSON(resource); metaJSON != "" {
			meta = "json.loads(" + quote(metaJSON) + ")"
		}
		encoder := "protoc_gen_mcp_runtime.identity"
		content := resourceContent(resource)
		if content != resourceContentSourceFile && !protobufHandlerMode {
			var err error
			encoder, err = info.pythonMapperHelperForMethodType("to_pb", resource.Output)
			if err != nil {
				return err
			}
		}
		field := "None"
		if resource.ContentField != "" {
			field = quote(resource.ContentField)
		}
		args := "uri, mime_type=" + quote(resource.MIMEType) + ", kind=" + quote(pythonResourceContentKind(content)) + ", content_field=" + field + ", to_pb=" + encoder + ", meta=" + meta
		if resource.IsTemplate {
			paramArgs := make([]string, 0, len(resource.Params))
			for _, param := range resource.Params {
				paramArgs = append(paramArgs, "params["+quote(param.Name)+"]")
			}
			generated.P("    registry.add_template(protoc_gen_mcp_runtime.RegisteredResourceTemplate(")
			generated.P("        template=protoc_gen_mcp_runtime.resource_listing(mcp.types.ResourceTemplate, ", quote(descriptor), ", namespace, ", quote(resource.Name), "),")
			generated.P("        pattern=protoc_gen_mcp_runtime.compile_uri_template(", quote(resource.URITemplate), "),")
			generated.P("        names=", pythonStringTuple(resource.Params), ",")
			generated.P("        lister=impl.list_", methodName, "s,")
			generated.P("        reader=lambda uri, params: protoc_gen_mcp_runtime.read_resource_contents(impl.read_", methodName, "(", strings.Join(paramArgs, ", "), "), ", args, "),")
			generated.P("    ))")
		} else {
			generated.P("    registry.add_static(protoc_gen_mcp_runtime.RegisteredResource(")
			generated.P("        resource=protoc_gen_mcp_runtime.resource_listing(mcp.types.Resource, ", quote(descriptor), ", namespace, ", quote(resource.Name), "),")
			generated.P("        reader=lambda uri, params: protoc_gen_mcp_runtime.read_resource_contents(impl.read_", methodName, "(), ", args, "),")
			generated.P("    ))")
		}
	}
	generated.P()
	return nil
}

func pythonResourceContentKind(kind resourceContentKind) string {
	switch kind {
	case resourceContentTextField:
		return "text_field"
	case resourceContentBlobField:
		return "blob_field"
	case resourceContentSourceFile:
		return "raw"
	default:
		return "protojson"
	}
}

func pythonStringTuple(params []ResourceParamModel) string {
	quoted := make([]string, 0, len(params))
	for _, param := range params {
		quoted = append(quoted, quote(param.Name))
	}
	if len(quoted) == 1 {
		return "(" + quoted[0] + ",)"
	}
	return "(" + strings.Join(quoted, ", ") + ")"
}

func renderPythonPrompts(generated *protogen.GeneratedFile, model FileModel) {
	fileBase := pythonFileBaseName(model.ProtoPath)
	protocolName := pythonExportedIdentifier(fileBase) + "PromptHandler"
	registerName := "register_" + toSnakeCase(fileBase) + "_prompts"

	generated.P("class ", protocolName, "(Protocol):")
	for _, prompt := range model.Prompts {
		generated.P("    def ", pythonMethodName(prompt.ProtoName), "(self, arguments: dict[str, str]) -> mcp.types.GetPromptResult | Awaitable[mcp.types.GetPromptResult]:")
		generated.P("        ...")
	}
	generated.P()

	generated.P("def ", registerName, "(server: mcp.server.lowlevel.Server, impl: ", protocolName, ", *, namespace: str | None = None) -> None:")
	generated.P("    if impl is None:")
	generated.P("        raise ValueError(\"", registerName, ": impl is nil\")")
	generated.P("    registry = protoc_gen_mcp_runtime.install_prompt_registry(server)")
	for _, prompt := range model.Prompts {
		var required []string
		for _, arg := range prompt.Arguments {
			if arg.Required {
				required = append(required, quote(arg.Name))
			}
		}
		requiredTuple := "()"
		if len(required) == 1 {
			requiredTuple = "(" + required[0] + ",)"
		} else if len(required) > 1 {
			requiredTuple = "(" + strings.Join(required, ", ") + ")"
		}
		generated.P("    registry.add(protoc_gen_mcp_runtime.RegisteredPrompt(")
		generated.P("        prompt=mcp.types.Prompt(")
		generated.P("            name=protoc_gen_mcp_runtime.prompt_name(namespace, ", quote(prompt.Name), "),")
		if prompt.Title != "" {
			generated.P("            title=", quote(prompt.Title), ",")
		}
		if prompt.Description != "" {
			generated.P("            description=", quote(prompt.Description), ",")
		}
		generated.P("            arguments=[")
		for _, arg := range prompt.Arguments {
			generated.P("                mcp.types.PromptArgument(name=", quote(arg.Name), ", description=", quote(arg.Description), ", required=", pythonBool(arg.Required), "),")
		}
		generated.P("            ],")
		generated.P("        ),")
		generated.P("        required=", requiredTuple, ",")
		generated.P("        handler=impl.", pythonMethodName(prompt.ProtoName), ",")
		generated.P("    ))")
	}
	generated.P()
}

func pythonFileBaseName(protoPath string) string {
	base := strings.TrimSuffix(protoPath, ".proto")
	if idx := strings.LastIndex(base, "/"); idx >= 0 {
		base = base[idx+1:]
	}
	return base
}

func (p pythonRenderInfo) pythonHandlerMethodTypeRefs(method MethodModel, protobufHandlerMode bool) (string, string, error) {
	if protobufHandlerMode {
		inputType, err := p.pythonProtobufTypeRef(method.Input)
		if err != nil {
			return "", "", err
		}
		outputType, err := p.pythonProtobufTypeRef(method.Output)
		if err != nil {
			return "", "", err
		}
		return inputType, outputType, nil
	}

	inputType, err := p.pythonPublicMethodTypeRef(method.Input)
	if err != nil {
		return "", "", err
	}
	outputType, err := p.pythonPublicMethodTypeRef(method.Output)
	if err != nil {
		return "", "", err
	}
	return inputType, outputType, nil
}

type pythonRenderInfo struct {
	file        *protogen.File
	messages    map[string]*protogen.Message
	publicTypes map[string]PythonType
	modules     map[string]pythonModuleRef
}

type pythonModuleRef struct {
	Package   string
	Module    string
	Alias     string
	IsCurrent bool
}

func newPythonRenderInfo(plugin *protogen.Plugin, model FileModel) (pythonRenderInfo, error) {
	file := plugin.FilesByPath[model.ProtoPath]
	if file == nil {
		return pythonRenderInfo{}, fmt.Errorf("generated file %q not found in plugin", model.ProtoPath)
	}

	info := pythonRenderInfo{
		file:        file,
		messages:    map[string]*protogen.Message{},
		publicTypes: map[string]PythonType{},
		modules:     map[string]pythonModuleRef{},
	}
	for _, current := range plugin.Files {
		pkg, module := pythonImportParts(current)
		info.modules[current.Desc.Path()] = pythonModuleRef{
			Package:   pkg,
			Module:    module,
			Alias:     pythonModuleAlias(current, current.Desc.Path() == file.Desc.Path()),
			IsCurrent: current.Desc.Path() == file.Desc.Path(),
		}
		indexPythonMessages(info.messages, current.Messages)
	}
	if model.PythonTypes != nil {
		for _, typ := range model.PythonTypes.Types {
			info.publicTypes[typ.ProtoFullName] = typ
		}
	}

	return info, nil
}

func indexPythonMessages(index map[string]*protogen.Message, messages []*protogen.Message) {
	for _, message := range messages {
		index[string(message.Desc.FullName())] = message
		indexPythonMessages(index, message.Messages)
	}
}

func (p pythonRenderInfo) pythonProtobufTypeRef(ref TypeRef) (string, error) {
	message := p.messages[ref.ProtoFullName]
	if message == nil {
		return "", fmt.Errorf("message %q not found during Python render", ref.ProtoFullName)
	}

	messageFilePath := message.Desc.ParentFile().Path()
	moduleRef, ok := p.modules[messageFilePath]
	if !ok {
		return "", fmt.Errorf("module for message %q not found during Python render", ref.ProtoFullName)
	}
	return moduleRef.Alias + "." + pythonMessageRef(message), nil
}

func (p pythonRenderInfo) pythonPublicMethodTypeRef(ref TypeRef) (string, error) {
	typ, ok := p.publicTypes[ref.ProtoFullName]
	if !ok {
		return "", fmt.Errorf("public python type %q not found during render", ref.ProtoFullName)
	}
	return p.pythonPublicTypeRef(typ.typeRef()), nil
}

func (p pythonRenderInfo) pythonMapperHelperForMethodType(prefix string, ref TypeRef) (string, error) {
	typ, ok := p.publicTypes[ref.ProtoFullName]
	if !ok {
		return "", fmt.Errorf("public python type %q not found during mapper lookup", ref.ProtoFullName)
	}
	return pythonMapperHelperName(prefix, typ), nil
}

func (p pythonRenderInfo) protobufImportsForModel(model FileModel) []pythonModuleRef {
	refs := map[string]pythonModuleRef{}
	if model.PythonTypes != nil {
		for _, typ := range model.PythonTypes.Types {
			if typ.Kind != PythonTypeKindMessage || typ.WellKnownType != PythonWellKnownTypeNone {
				continue
			}
			refs[typ.Owner.ProtoPath] = p.modules[typ.Owner.ProtoPath]
		}
	}
	for _, service := range model.Services {
		for _, method := range service.Methods {
			if message := p.messages[method.Input.ProtoFullName]; message != nil {
				messageFilePath := message.Desc.ParentFile().Path()
				refs[messageFilePath] = p.modules[messageFilePath]
			}
			if message := p.messages[method.Output.ProtoFullName]; message != nil {
				messageFilePath := message.Desc.ParentFile().Path()
				refs[messageFilePath] = p.modules[messageFilePath]
			}
		}
	}
	for _, resource := range model.Resources {
		if resource.SourceFile != "" {
			continue
		}
		if message := p.messages[resource.Output.ProtoFullName]; message != nil {
			messageFilePath := message.Desc.ParentFile().Path()
			refs[messageFilePath] = p.modules[messageFilePath]
		}
	}

	ordered := make([]pythonModuleRef, 0, len(refs))
	for _, ref := range refs {
		ordered = append(ordered, ref)
	}
	sort.Slice(ordered, func(i, j int) bool {
		left := ordered[i].Package + "." + ordered[i].Module
		right := ordered[j].Package + "." + ordered[j].Module
		return left < right
	})
	return ordered
}

func (p pythonRenderInfo) publicImportsForModel(model FileModel) []pythonModuleRef {
	if model.PythonTypes == nil {
		return nil
	}

	referencedProtoPaths := p.publicImportProtoPaths(*model.PythonTypes)
	ordered := make([]pythonModuleRef, 0, len(model.PythonTypes.Imports))
	for _, ref := range model.PythonTypes.Imports {
		if _, ok := referencedProtoPaths[ref.ProtoPath]; !ok {
			continue
		}
		modulePath := ref.PublicModule.ModulePath
		lastDot := strings.LastIndex(modulePath, ".")
		moduleRef := pythonModuleRef{
			Alias:  ref.PublicModule.ModuleAlias,
			Module: ref.PublicModule.ModuleBasename,
		}
		if lastDot != -1 {
			moduleRef.Package = modulePath[:lastDot]
		}
		ordered = append(ordered, moduleRef)
	}
	sort.Slice(ordered, func(i, j int) bool {
		left := ordered[i].Package + "." + ordered[i].Module
		right := ordered[j].Package + "." + ordered[j].Module
		return left < right
	})
	return ordered
}

func (p pythonRenderInfo) publicImportProtoPaths(graph PythonTypeGraph) map[string]struct{} {
	refs := make(map[string]struct{})
	for _, typ := range graph.Types {
		if typ.Owner.IsCurrentFile || typ.WellKnownType != PythonWellKnownTypeNone {
			continue
		}
		refs[typ.Owner.ProtoPath] = struct{}{}
	}
	return refs
}

func pythonMessageRef(message *protogen.Message) string {
	fullName := string(message.Desc.FullName())
	pkg := string(message.Desc.ParentFile().Package())
	if pkg != "" {
		fullName = strings.TrimPrefix(fullName, pkg+".")
	}
	return fullName
}

func pythonAnnotations(ann *mcpoptionsv1.ToolAnnotations) string {
	if ann == nil {
		return "None"
	}

	fields := make([]string, 0, 4)
	if ann.ReadOnlyHint {
		fields = append(fields, fmt.Sprintf("%q: %s", "readOnlyHint", pythonBool(ann.ReadOnlyHint)))
	}
	if ann.DestructiveHint != nil {
		fields = append(fields, fmt.Sprintf("%q: %s", "destructiveHint", pythonBool(*ann.DestructiveHint)))
	}
	if ann.IdempotentHint {
		fields = append(fields, fmt.Sprintf("%q: %s", "idempotentHint", pythonBool(ann.IdempotentHint)))
	}
	if ann.OpenWorldHint != nil {
		fields = append(fields, fmt.Sprintf("%q: %s", "openWorldHint", pythonBool(*ann.OpenWorldHint)))
	}
	if ann.Title != "" {
		fields = append(fields, fmt.Sprintf("%q: %q", "title", ann.Title))
	}
	if len(fields) == 0 {
		return "{}"
	}
	return "{" + strings.Join(fields, ", ") + "}"
}

func pythonBool(value bool) string {
	if value {
		return "True"
	}
	return "False"
}

func pythonIcons(icons []*mcpoptionsv1.Icon) string {
	if len(icons) == 0 {
		return "None"
	}

	items := make([]string, 0, len(icons))
	for _, icon := range icons {
		sizes := "[]"
		if len(icon.GetSizes()) > 0 {
			quoted := make([]string, 0, len(icon.GetSizes()))
			for _, size := range icon.GetSizes() {
				quoted = append(quoted, fmt.Sprintf("%q", size))
			}
			sizes = "[" + strings.Join(quoted, ", ") + "]"
		}
		items = append(items, fmt.Sprintf("{%q: %q, %q: %q, %q: %s, %q: %q}",
			"src", icon.GetSrc(),
			"mimeType", icon.GetMimeType(),
			"sizes", sizes,
			"theme", icon.GetTheme()))
	}

	return "[" + strings.Join(items, ", ") + "]"
}

func pythonTaskSupport(taskSupport mcpoptionsv1.TaskSupport) string {
	switch taskSupport {
	case mcpoptionsv1.TaskSupport_TASK_SUPPORT_OPTIONAL:
		return `{"taskSupport": "optional"}`
	case mcpoptionsv1.TaskSupport_TASK_SUPPORT_REQUIRED:
		return `{"taskSupport": "required"}`
	default:
		return "None"
	}
}
