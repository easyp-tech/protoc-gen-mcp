/** Bumped whenever generated code needs a newer runtime API. */
const val GENCODE_VERSION: Int = 1

/** Fails initialization when generated code targets another runtime API. */
fun checkGencodeVersion(version: Int) {
    check(version == GENCODE_VERSION) {
        "code generated by protoc-gen-mcp needs runtime API version $version, but protoc-gen-mcp-runtime-kotlin " +
            "provides $GENCODE_VERSION; regenerate the code or use a matching runtime"
    }
}

data class RegisteredTool(
    val name: String,
    val title: String?,
    val description: String?,
    val inputSchemaJson: String,
    val outputSchemaJson: String,
    val requestBuilder: () -> Message.Builder,
    val handler: suspend (ClientConnection, Message) -> Message,
    val annotations: ToolAnnotations?,
    val icons: List<Icon>,
    val execution: ToolExecution?,
    val meta: JsonObject? = null,
)

class ServerToolRegistry {
    private val toolsByName = linkedMapOf<String, RegisteredTool>()
    private val sessionsWithHandlers = mutableSetOf<String>()
    private var handlersInstalled: Boolean = false

    @Synchronized
    fun addTool(tool: RegisteredTool) {
        require(!toolsByName.containsKey(tool.name)) { "duplicate tool registration: ${tool.name}" }
        toolsByName[tool.name] = tool
    }

    @Synchronized
    fun allTools(): List<RegisteredTool> = toolsByName.values.toList()

    @Synchronized
    fun tool(name: String): RegisteredTool? = toolsByName[name]

    @Synchronized
    fun markSessionInstalled(sessionId: String): Boolean = sessionsWithHandlers.add(sessionId)

    @Synchronized
    fun hasHandlersInstalled(): Boolean = handlersInstalled

    @Synchronized
    fun markHandlersInstalled() {
        handlersInstalled = true
    }
}

private val serverRegistries = Collections.synchronizedMap(WeakHashMap<Server, ServerToolRegistry>())
private val serverRegistryInstallLock = Any()
private val jsonSchemaFactory = JsonSchemaFactory.getInstance(SpecVersion.VersionFlag.V202012)

private val protoFiles = mutableSetOf<String>()
private val protoTypes = mutableListOf<Descriptors.Descriptor>()

@Volatile
private var protoTypeRegistry: JsonFormat.TypeRegistry = JsonFormat.TypeRegistry.getEmptyTypeRegistry()

/** Makes the messages of the given files and their imports resolvable in ProtoJSON. */
fun registerProtoFiles(vararg files: Descriptors.FileDescriptor) {
    synchronized(protoFiles) {
        for (file in files) {
            collectFileTypes(file)
        }
        protoTypeRegistry = JsonFormat.TypeRegistry.newBuilder().add(protoTypes).build()
    }
}

private fun collectFileTypes(file: Descriptors.FileDescriptor) {
    if (!protoFiles.add(file.fullName)) {
        return
    }
    file.dependencies.forEach { collectFileTypes(it) }
    file.messageTypes.forEach { collectMessageType(it) }
}

private fun collectMessageType(descriptor: Descriptors.Descriptor) {
    protoTypes.add(descriptor)
    descriptor.nestedTypes.forEach { collectMessageType(it) }
}

fun installMcpHandlers(server: Server): ServerToolRegistry {
    synchronized(serverRegistryInstallLock) {
        val registry = serverRegistries.getOrPut(server) { ServerToolRegistry() }
        if (registry.hasHandlersInstalled()) {
            return registry
        }
        require(server.tools.isEmpty()) { "protoc-gen-mcp generated handlers cannot compose with pre-existing SDK tool registrations" }
        installSessionHandlers(server, registry)
        server.onConnect { installSessionHandlers(server, registry) }
        registry.markHandlersInstalled()
        return registry
    }
}

private fun installSessionHandlers(server: Server, registry: ServerToolRegistry) {
    for (session in server.sessions.values) {
        if (!registry.markSessionInstalled(session.sessionId)) {
            continue
        }
        session.setRequestHandler(Method.Defined.ToolsList) { request: ListToolsRequest, _ ->
            listRegisteredTools(registry, request)
        }
        session.setRequestHandler(Method.Defined.ToolsCall) { request: CallToolRequest, _ ->
            dispatchToolCall(registry, server.clientConnection(session.sessionId), request)
        }
    }
}

private suspend fun listRegisteredTools(registry: ServerToolRegistry, request: ListToolsRequest): ListToolsResult {
    return ListToolsResult(tools = registry.allTools().map { buildListTool(it) }, nextCursor = null)
}

private suspend fun dispatchToolCall(registry: ServerToolRegistry, ctx: ClientConnection, request: CallToolRequest): CallToolResult {
    val tool = registry.tool(request.params.name) ?: invalidParams(request.params.name, "unknown tool")
    val arguments = request.params.arguments ?: buildJsonObject {}
    try {
        validateJson(tool.inputSchemaJson, arguments)
    } catch (error: Exception) {
        invalidParams(tool.name, error.message ?: error.toString())
    }
    val requestMessage = try {
        parseProtoJson(arguments.toString(), tool.requestBuilder())
    } catch (error: Exception) {
        invalidParams(tool.name, error.message ?: error.toString())
    }
    val responseMessage = try {
        tool.handler(ctx, requestMessage)
    } catch (error: Exception) {
        return CallToolResult(content = listOf(TextContent(text = error.message ?: error.toString())), isError = true)
    }
    val payload = marshalProtoJson(responseMessage)
    try {
        validateJson(tool.outputSchemaJson, payload)
    } catch (error: Exception) {
        throw IllegalStateException("mcpruntime: validate output for tool '${tool.name}': ${error.message}", error)
    }
    val textPayload = payload.toString()
    return CallToolResult(content = listOf(TextContent(text = textPayload)), structuredContent = payload)
}

private fun buildListTool(tool: RegisteredTool): Tool {
    return Tool(
        name = tool.name,
        title = tool.title,
        description = tool.description,
        inputSchema = projectToolSchema(tool.inputSchemaJson),
        outputSchema = projectToolSchema(tool.outputSchemaJson),
        annotations = copyToolAnnotations(tool.annotations),
        icons = tool.icons.ifEmpty { null },
        execution = tool.execution,
        meta = tool.meta,
    )
}

private fun copyToolAnnotations(annotations: ToolAnnotations?): ToolAnnotations? {
    if (annotations == null) {
        return null
    }
    return ToolAnnotations(
        title = annotations.title,
        readOnlyHint = annotations.readOnlyHint,
        destructiveHint = annotations.destructiveHint,
        idempotentHint = annotations.idempotentHint,
        openWorldHint = annotations.openWorldHint,
    )
}

private fun loadSchema(rawSchemaJson: String): JsonObject = Json.parseToJsonElement(rawSchemaJson).jsonObject

private fun projectToolSchema(rawSchemaJson: String): ToolSchema {
    val schema = loadSchema(rawSchemaJson)
    val properties = schema["properties"]?.jsonObject ?: buildJsonObject {}
    val required = schema["required"]?.jsonArray?.map { it.jsonPrimitive.content } ?: emptyList()
    val defs = schema["\$defs"]?.jsonObject
    return ToolSchema(properties = properties, required = required, defs = defs)
}

private fun validateJson(rawSchemaJson: String, payload: JsonElement) {
    val errors = jsonSchemaFactory.getSchema(rawSchemaJson).validate(payload.toString(), InputFormat.JSON)
    if (errors.isNotEmpty()) {
        throw IllegalArgumentException(errors.joinToString("; ") { it.message })
    }
}

private fun parseProtoJson(payload: String, builder: Message.Builder): Message {
    try {
        JsonFormat.parser().usingTypeRegistry(protoTypeRegistry).merge(payload, builder)
        return builder.build()
    } catch (error: Exception) {
        invalidParams("<unknown>", error.message ?: error.toString())
    }
}

private fun marshalProtoJson(message: Message): JsonObject {
    val jsonPayload = JsonFormat.printer().usingTypeRegistry(protoTypeRegistry).includingDefaultValueFields().print(message)
    return Json.parseToJsonElement(jsonPayload).jsonObject
}

private fun invalidParams(toolName: String, reason: String): Nothing {
    throw McpException(code = RPCError.ErrorCode.INVALID_PARAMS, message = "invalid arguments for tool '$toolName': $reason")
}

fun toolExecutionOrNull(taskSupport: String): ToolExecution? = when (taskSupport) {
    "optional" -> ToolExecution(taskSupport = TaskSupport.Optional)
    "required" -> ToolExecution(taskSupport = TaskSupport.Required)
    else -> null
}

fun iconThemeOrError(rawTheme: String?): Icon.Theme? = when (rawTheme) {
    null, "" -> null
    "light" -> Icon.Theme.Light
    "dark" -> Icon.Theme.Dark
    else -> throw IllegalArgumentException("unsupported icon theme: $rawTheme")
}

fun normalizeToolSegment(segment: String?): String {
    return segment
        ?.trim()
        ?.replace('.', '_')
        ?.split('_')
        ?.filter { it.isNotBlank() }
        ?.joinToString("_")
        ?: ""
}

fun normalizeNamespace(namespace: String?, defaultNamespace: String): String = normalizeToolSegment(namespace ?: defaultNamespace)

fun toolName(namespace: String, methodName: String): String {
    val normalizedNamespace = normalizeToolSegment(namespace)
    val normalizedMethodName = normalizeToolSegment(methodName)
    return when {
        normalizedNamespace.isEmpty() -> normalizedMethodName
        normalizedMethodName.isEmpty() -> normalizedNamespace
        else -> "${normalizedNamespace}_${normalizedMethodName}"
    }
}



fun promptName(namespace: String?, promptName: String): String {
    val normalizedNamespace = normalizeToolSegment(namespace ?: "")
    val normalizedPromptName = normalizeToolSegment(promptName)
    return when {
        normalizedNamespace.isEmpty() -> normalizedPromptName
        normalizedPromptName.isEmpty() -> normalizedNamespace
        else -> "${normalizedNamespace}_${normalizedPromptName}"
    }
}

fun <T> resourceListing(
    serializer: kotlinx.serialization.KSerializer<T>,
    descriptorJson: String,
    namespace: String?,
    name: String,
): T {
    val descriptor = Json.parseToJsonElement(descriptorJson).jsonObject.toMutableMap()
    descriptor["name"] = kotlinx.serialization.json.JsonPrimitive(if (namespace.isNullOrEmpty()) name else "${namespace}_$name")
    return io.modelcontextprotocol.kotlin.sdk.types.McpJson.decodeFromJsonElement(serializer, JsonObject(descriptor))
}

fun templateParam(params: Map<String, String>, name: String, uri: String): String {
    val value = params[name]
    if (value.isNullOrEmpty()) {
        throw McpException(
            code = RPCError.ErrorCode.INVALID_PARAMS,
            message = "mcpruntime: parameter '$name' has empty value in uri '$uri'",
        )
    }
    return value
}

fun resourceReadResult(
    value: Any?,
    uri: String,
    mimeType: String,
    kind: String,
    contentField: String?,
    meta: JsonObject?,
): io.modelcontextprotocol.kotlin.sdk.types.ReadResourceResult {
    requireNotNull(value) { "mcpruntime: resource '$uri' handler returned null" }
    val encoder = java.util.Base64.getEncoder()
    val contents: io.modelcontextprotocol.kotlin.sdk.types.ResourceContents = when (kind) {
        "raw" -> when (value) {
            is String -> io.modelcontextprotocol.kotlin.sdk.types.TextResourceContents(text = value, uri = uri, mimeType = mimeType, meta = meta)
            is ByteArray -> io.modelcontextprotocol.kotlin.sdk.types.BlobResourceContents(blob = encoder.encodeToString(value), uri = uri, mimeType = mimeType, meta = meta)
            else -> throw IllegalStateException("mcpruntime: resource '$uri' handler must return a String or ByteArray")
        }
        "protojson" -> io.modelcontextprotocol.kotlin.sdk.types.TextResourceContents(
            text = marshalProtoJson(value as Message).toString(),
            uri = uri,
            mimeType = mimeType,
            meta = meta,
        )
        else -> {
            val message = value as Message
            val field = message.descriptorForType.findFieldByName(contentField.orEmpty())
                ?: throw IllegalStateException("mcpruntime: resource content field '$contentField' not found")
            val fieldValue = message.getField(field)
            if (kind == "text_field") {
                io.modelcontextprotocol.kotlin.sdk.types.TextResourceContents(text = fieldValue.toString(), uri = uri, mimeType = mimeType, meta = meta)
            } else {
                val bytes = (fieldValue as com.google.protobuf.ByteString).toByteArray()
                io.modelcontextprotocol.kotlin.sdk.types.BlobResourceContents(blob = encoder.encodeToString(bytes), uri = uri, mimeType = mimeType, meta = meta)
            }
        }
    }
    return io.modelcontextprotocol.kotlin.sdk.types.ReadResourceResult(contents = listOf(contents))
}
