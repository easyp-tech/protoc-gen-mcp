/** Bumped whenever generated code needs a newer runtime API. */
export const GENCODE_VERSION = 1;

/** Fails module loading when generated code targets a different runtime API. */
export function checkGencodeVersion(version: number): void {
  if (version !== GENCODE_VERSION) {
    throw new Error(
      `code generated by protoc-gen-mcp needs runtime API version ${version}, but @easyp-tech/protoc-gen-mcp-runtime provides ${GENCODE_VERSION}; regenerate the code or install a matching runtime`,
    );
  }
}
