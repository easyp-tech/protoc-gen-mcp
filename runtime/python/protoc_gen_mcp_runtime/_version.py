"""Compatibility check between generated code and this runtime."""

from __future__ import annotations

__version__ = "0.8.0"

# GENCODE_VERSION is bumped whenever generated code needs a newer runtime API.
GENCODE_VERSION = 1


def check_gencode_version(version: int) -> None:
    """Fails import when generated code targets a different runtime API."""
    if version != GENCODE_VERSION:
        raise ImportError(
            f"code generated by protoc-gen-mcp needs runtime API version {version}, "
            f"but protoc-gen-mcp-runtime {__version__} provides {GENCODE_VERSION}; "
            "regenerate the code or install a matching protoc-gen-mcp-runtime"
        )
